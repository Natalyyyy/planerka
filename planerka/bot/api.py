"""Тонкая обёртка над Telegram Bot API.

Только стандартная библиотека (`urllib`): одна внешняя зависимость — это
то, что человек, который поставит плагин, должен будет ставить руками, и
на этом половина отвалится.

Всё, что уходит за пределы процесса, идёт через один вход — `_запрос` —
там же и вся логика повторов и понятных ошибок. Публичные функции
только собирают параметры вызова.
"""
import json
import socket
import time
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

# Разумные пределы попыток: боту нельзя виснуть навсегда, если Телеграм
# лёг или прижимает лимитом. 4 попытки — 1 обычная плюс 3 повтора.
_МАКС_ПОПЫТОК_429 = 4
_МАКС_ПОПЫТОК_5XX = 4

# Если Телеграм не прислал retry_after — ждём секунду и пробуем снова.
_ЗАДЕРЖКА_ПО_УМОЛЧАНИЮ_429 = 1.0

# Отступ между повторами при 5xx растёт вдвое: 1, 2, 4 секунды.
_НАЧАЛЬНАЯ_ЗАДЕРЖКА_5XX = 1.0

# Запас сверх таймаута долгого опроса getUpdates: Телеграм держит
# соединение открытым ровно "таймаут" секунд, сетевой таймаут должен
# быть чуть больше, иначе клиент оборвёт соединение раньше сервера.
_ЗАПАС_ДЛЯ_ДОЛГОГО_ОПРОСА = 5


class ОшибкаБота(Exception):
    """Базовая ошибка клиента Bot API."""


class ОшибкаТокена(ОшибкаБота):
    """Телеграм не принял токен (401)."""


class ОшибкаСети(ОшибкаБота):
    """Не удалось связаться с Телеграмом: обрыв, таймаут."""


class ОшибкаОтвета(ОшибкаБота):
    """Ответ Телеграма нельзя разобрать: не JSON или без поля ok."""


class ОшибкаТелеграма(ОшибкаБота):
    """Телеграм ответил ошибкой: исчерпаны повторы или ok=false."""


def _retry_after(тело_ошибки: bytes) -> float:
    try:
        разобрано = json.loads(тело_ошибки)
        return float(разобрано.get("parameters", {}).get("retry_after", _ЗАДЕРЖКА_ПО_УМОЛЧАНИЮ_429))
    except (json.JSONDecodeError, TypeError, ValueError, AttributeError):
        return _ЗАДЕРЖКА_ПО_УМОЛЧАНИЮ_429


def _разобрать(тело: bytes):
    try:
        разобрано = json.loads(тело)
    except json.JSONDecodeError as ошибка:
        raise ОшибкаОтвета(
            "Телеграм прислал ответ, который не получилось разобрать как JSON — попробуйте позже"
        ) from ошибка

    if not isinstance(разобрано, dict) or "ok" not in разобрано:
        raise ОшибкаОтвета(
            "Телеграм прислал неожиданный ответ без поля ok — попробуйте позже"
        )

    if not разобрано["ok"]:
        описание = разобрано.get("description", "без описания")
        raise ОшибкаТелеграма(f"Телеграм отклонил запрос: {описание}")

    return разобрано.get("result")


def _запрос(токен: str, метод: str, параметры: dict, таймаут: int):
    url = f"https://api.telegram.org/bot{токен}/{метод}"
    данные = json.dumps(параметры).encode("utf-8")

    попытка_429 = 0
    попытка_5xx = 0

    while True:
        запрос = Request(
            url,
            data=данные,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        try:
            with urlopen(запрос, timeout=таймаут) as ответ:
                тело = ответ.read()
            break
        except HTTPError as ошибка:
            код = ошибка.code
            тело_ошибки = ошибка.read()

            if код == 401:
                raise ОшибкаТокена(
                    "Телеграм не принял токен — проверьте, что скопировали его целиком"
                ) from ошибка

            if код == 429:
                попытка_429 += 1
                if попытка_429 >= _МАКС_ПОПЫТОК_429:
                    raise ОшибкаТелеграма(
                        "Телеграм ограничивает частоту запросов, повторные попытки "
                        "не помогли — попробуйте позже"
                    ) from ошибка
                time.sleep(_retry_after(тело_ошибки))
                continue

            if 500 <= код < 600:
                попытка_5xx += 1
                if попытка_5xx >= _МАКС_ПОПЫТОК_5XX:
                    raise ОшибкаТелеграма(
                        f"Телеграм отвечает ошибкой сервера ({код}), повторные "
                        "попытки не помогли — попробуйте позже"
                    ) from ошибка
                time.sleep(_НАЧАЛЬНАЯ_ЗАДЕРЖКА_5XX * (2 ** (попытка_5xx - 1)))
                continue

            raise ОшибкаТелеграма(
                f"Телеграм ответил ошибкой {код} — попробуйте позже"
            ) from ошибка
        except (URLError, socket.timeout, TimeoutError) as ошибка:
            raise ОшибкаСети(
                "Не удалось связаться с Телеграмом — проверьте интернет-соединение "
                "и повторите позже"
            ) from ошибка

    return _разобрать(тело)


def отправить_сообщение(токен: str, chat_id, текст: str) -> dict:
    """Отправляет обычное текстовое сообщение."""
    return _запрос(токен, "sendMessage", {"chat_id": chat_id, "text": текст}, таймаут=10)


def отправить_с_кнопками(токен: str, chat_id, текст: str, кнопки) -> dict:
    """Отправляет сообщение с инлайн-кнопками.

    `кнопки` — список пар (подпись, данные для callback); каждая кнопка
    занимает свою строку.
    """
    клавиатура = {
        "inline_keyboard": [
            [{"text": подпись, "callback_data": данные}] for подпись, данные in кнопки
        ]
    }
    return _запрос(
        токен,
        "sendMessage",
        {"chat_id": chat_id, "text": текст, "reply_markup": клавиатура},
        таймаут=10,
    )


def ответить_на_нажатие(токен: str, id_нажатия: str, текст: str | None = None) -> None:
    """Подтверждает нажатие кнопки, чтобы она не крутилась у человека."""
    параметры = {"callback_query_id": id_нажатия}
    if текст is not None:
        параметры["text"] = текст
    _запрос(токен, "answerCallbackQuery", параметры, таймаут=10)
    return None


def получить_обновления(токен: str, смещение: int | None = None, таймаут: int = 25) -> list:
    """Забирает новые обновления (длинный опрос getUpdates)."""
    параметры = {"timeout": таймаут}
    if смещение is not None:
        параметры["offset"] = смещение
    результат = _запрос(токен, "getUpdates", параметры, таймаут=таймаут + _ЗАПАС_ДЛЯ_ДОЛГОГО_ОПРОСА)
    return результат if результат is not None else []


def проверить_токен(токен: str) -> str:
    """Вызывает getMe и возвращает имя бота.

    Нужно для интервью: человек убеждается, что вставленный токен от
    того самого бота.
    """
    результат = _запрос(токен, "getMe", {}, таймаут=10)
    return результат.get("first_name", "")
