"""Тонкая обёртка над Telegram Bot API.

Только стандартная библиотека (`urllib`): одна внешняя зависимость — это
то, что человек, который поставит плагин, должен будет ставить руками, и
на этом половина отвалится.

Всё, что уходит за пределы процесса, идёт через один вход — `_запрос` —
там же и вся логика повторов и понятных ошибок. Публичные функции
только собирают параметры вызова.
"""
import json
import socket
import time
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

# Разумные пределы попыток: боту нельзя виснуть навсегда, если Телеграм
# лёг или прижимает лимитом. 4 попытки — 1 обычная плюс 3 повтора.
_МАКС_ПОПЫТОК_429 = 4
_МАКС_ПОПЫТОК_5XX = 4

# Если Телеграм не прислал retry_after — ждём секунду и пробуем снова.
_ЗАДЕРЖКА_ПО_УМОЛЧАНИЮ_429 = 1.0

# Отступ между повторами при 5xx растёт вдвое: 1, 2, 4 секунды.
_НАЧАЛЬНАЯ_ЗАДЕРЖКА_5XX = 1.0

# Потолок ожидания на 429: флуд-контроль Телеграма может попросить
# подождать сотни секунд, а этот клиент — синхронный вызов внутри
# интервью, где на другом конце ждёт живой человек. Молча стоять
# дольше половины минуты — уже не "медленно", а "как будто зависло",
# и на долгоживущем процессе с дедлайном такой эпизод съест дедлайн
# незаметно для вызывающего. 30 секунд длиннее наших обычных таймаутов
# (10 с на обычный вызов) — короткие, штатные ограничения переживаем
# внутри одного вызова, — но много меньше типичных "сотен секунд"
# жёсткого флуд-контроля: те стабильно не спим, а сразу отдаём наверх.
_ПОТОЛОК_ОЖИДАНИЯ_429 = 30.0

# Запас сверх таймаута долгого опроса getUpdates: Телеграм держит
# соединение открытым ровно "таймаут" секунд, сетевой таймаут должен
# быть чуть больше, иначе клиент оборвёт соединение раньше сервера.
_ЗАПАС_ДЛЯ_ДОЛГОГО_ОПРОСА = 5


class ОшибкаБота(Exception):
    """Базовая ошибка клиента Bot API."""


class ОшибкаТокена(ОшибкаБота):
    """Телеграм не принял токен (401)."""


class ОшибкаСети(ОшибкаБота):
    """Не удалось связаться с Телеграмом: обрыв, таймаут."""


class ОшибкаОтвета(ОшибкаБота):
    """Ответ Телеграма нельзя разобрать: не JSON или без поля ok."""


class ОшибкаТелеграма(ОшибкаБота):
    """Телеграм ответил ошибкой: исчерпаны повторы или ok=false."""


def _retry_after(тело_ошибки: bytes) -> float:
    try:
        разобрано = json.loads(тело_ошибки)
        return float(разобрано.get("parameters", {}).get("retry_after", _ЗАДЕРЖКА_ПО_УМОЛЧАНИЮ_429))
    except (json.JSONDecodeError, TypeError, ValueError, AttributeError):
        return _ЗАДЕРЖКА_ПО_УМОЛЧАНИЮ_429


def _описание_ошибки(тело_ошибки: bytes) -> str | None:
    """Достаёт description из тела HTTPError, если оно есть и это JSON."""
    try:
        разобрано = json.loads(тело_ошибки)
    except (json.JSONDecodeError, TypeError):
        return None
    описание = разобрано.get("description") if isinstance(разобрано, dict) else None
    return описание if isinstance(описание, str) else None


def _подсказка_по_описанию(код: int, описание: str) -> str | None:
    """Человеческая подсказка для двух самых частых промахов настройки.

    Остальные коды отдают description Телеграма как есть — не выдумываем
    перевод там, где нет уверенности, что действие человека одно и то же.
    """
    описание_нижний = описание.lower()
    if код == 400 and "chat not found" in описание_нижний:
        return (
            "получатель ещё не написал этому боту первым — попросите "
            "его отправить боту любое сообщение и повторите"
        )
    if код == 403 and "bot was blocked" in описание_нижний:
        return "человек заблокировал бота — попросите его разблокировать бота в Телеграме"
    return None


def _разобрать(тело: bytes):
    try:
        разобрано = json.loads(тело)
    except json.JSONDecodeError as ошибка:
        raise ОшибкаОтвета(
            "Телеграм прислал ответ, который не получилось разобрать как JSON — попробуйте позже"
        ) from ошибка

    if not isinstance(разобрано, dict) or "ok" not in разобрано:
        raise ОшибкаОтвета(
            "Телеграм прислал неожиданный ответ без поля ok — попробуйте позже"
        )

    if not разобрано["ok"]:
        описание = разобрано.get("description", "без описания")
        raise ОшибкаТелеграма(f"Телеграм отклонил запрос: {описание}")

    return разобрано.get("result")


def _запрос(токен: str, метод: str, параметры: dict, таймаут: int):
    url = f"https://api.telegram.org/bot{токен}/{метод}"
    данные = json.dumps(параметры).encode("utf-8")

    попытка_429 = 0
    попытка_5xx = 0

    while True:
        запрос = Request(
            url,
            data=данные,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        try:
            with urlopen(запрос, timeout=таймаут) as ответ:
                тело = ответ.read()
            break
        except HTTPError as ошибка:
            код = ошибка.code
            тело_ошибки = ошибка.read()

            if код == 401:
                raise ОшибкаТокена(
                    "Телеграм не принял токен — проверьте, что скопировали его целиком"
                ) from ошибка

            if код == 429:
                попытка_429 += 1
                задержка = _retry_after(тело_ошибки)
                if задержка > _ПОТОЛОК_ОЖИДАНИЯ_429:
                    raise ОшибкаТелеграма(
                        f"Телеграм просит подождать {int(задержка)} секунд из-за "
                        "ограничения частоты запросов — это больше разумного "
                        f"предела ожидания в одном вызове ({int(_ПОТОЛОК_ОЖИДАНИЯ_429)} "
                        "секунд), спать так долго не станем. Это не поломка, а "
                        "лимит самого Телеграма — попробуйте вернуться позже."
                    ) from ошибка
                if попытка_429 >= _МАКС_ПОПЫТОК_429:
                    raise ОшибкаТелеграма(
                        "Телеграм ограничивает частоту запросов, повторные попытки "
                        "не помогли — попробуйте позже"
                    ) from ошибка
                time.sleep(задержка)
                continue

            if 500 <= код < 600:
                попытка_5xx += 1
                if попытка_5xx >= _МАКС_ПОПЫТОК_5XX:
                    raise ОшибкаТелеграма(
                        f"Телеграм отвечает ошибкой сервера ({код}), повторные "
                        "попытки не помогли — попробуйте позже"
                    ) from ошибка
                time.sleep(_НАЧАЛЬНАЯ_ЗАДЕРЖКА_5XX * (2 ** (попытка_5xx - 1)))
                continue

            описание = _описание_ошибки(тело_ошибки)
            if описание:
                подсказка = _подсказка_по_описанию(код, описание)
                сообщение = f"Телеграм отклонил запрос: {описание}"
                if подсказка:
                    сообщение += f" — {подсказка}"
                raise ОшибкаТелеграма(сообщение) from ошибка

            raise ОшибкаТелеграма(
                f"Телеграм ответил ошибкой {код} — попробуйте позже"
            ) from ошибка
        except (URLError, socket.timeout, TimeoutError) as ошибка:
            raise ОшибкаСети(
                "Не удалось связаться с Телеграмом — проверьте интернет-соединение "
                "и повторите позже"
            ) from ошибка

    return _разобрать(тело)


def отправить_сообщение(токен: str, chat_id, текст: str) -> dict:
    """Отправляет обычное текстовое сообщение."""
    return _запрос(токен, "sendMessage", {"chat_id": chat_id, "text": текст}, таймаут=10)


def отправить_с_кнопками(токен: str, chat_id, текст: str, ряды) -> dict:
    """Отправляет сообщение с инлайн-кнопками.

    `ряды` — список рядов кнопок; каждый ряд — список пар (подпись,
    данные для callback). Раскладка явная: вызывающий код сам решает,
    сколько кнопок в одном ряду (например «беру / подумать / нет» одним
    рядом — с телефона это одно движение, а не промах по узкому
    столбику), клиент не гадает и не разбивает список сам.

    Пустой список рядов — ошибка вызывающего кода: без разметки нечего
    отправлять, и отправлять сообщение без клавиатуры молча — хуже, чем
    сразу сказать, что кнопки не заданы.
    """
    if not ряды:
        raise ValueError(
            "нужен хотя бы один ряд кнопок — пустой список рядов, "
            "отправлять нечего"
        )
    клавиатура = {
        "inline_keyboard": [
            [{"text": подпись, "callback_data": данные} for подпись, данные in ряд]
            for ряд in ряды
        ]
    }
    return _запрос(
        токен,
        "sendMessage",
        {"chat_id": chat_id, "text": текст, "reply_markup": клавиатура},
        таймаут=10,
    )


def ответить_на_нажатие(
    токен: str, id_нажатия: str, текст: str | None = None, show_alert: bool = False,
) -> None:
    """Подтверждает нажатие кнопки, чтобы она не крутилась у человека.

    `show_alert=True` просит Телеграм показать модальное окно вместо
    полоски-подсказки, которая гаснет сама за пару секунд: для отказа
    записать решение или для перезаписи прежнего решения человек может
    просто не успеть увидеть полоску, особенно если задел кнопку мельком,
    листая старые сообщения в чате."""
    параметры = {"callback_query_id": id_нажатия}
    if текст is not None:
        параметры["text"] = текст
    if show_alert:
        параметры["show_alert"] = True
    _запрос(токен, "answerCallbackQuery", параметры, таймаут=10)
    return None


def получить_обновления(токен: str, смещение: int | None = None, таймаут: int = 25) -> list:
    """Забирает новые обновления (длинный опрос getUpdates)."""
    параметры = {"timeout": таймаут}
    if смещение is not None:
        параметры["offset"] = смещение
    результат = _запрос(токен, "getUpdates", параметры, таймаут=таймаут + _ЗАПАС_ДЛЯ_ДОЛГОГО_ОПРОСА)
    return результат if результат is not None else []


def проверить_токен(токен: str) -> str:
    """Вызывает getMe и возвращает опознаваемое имя бота.

    Нужно для интервью: человек убеждается, что вставленный токен от
    того самого бота. Отдаём `@username` — это то, что видно в
    @BotFather и по чему бот узнаётся однозначно; `first_name` можно
    было задать любым и не обязательно помнить его. Если Телеграм не
    прислал username, откатываемся на first_name, но не молча — в
    возвращаемой строке остаётся видимая пометка, что username нет.
    """
    результат = _запрос(токен, "getMe", {}, таймаут=10)
    username = результат.get("username")
    if username:
        return f"@{username}"
    return f"{результат.get('first_name', '')} (без @username)"
