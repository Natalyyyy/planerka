"""Отправка банка тем в Телеграм — по одной теме сообщением с тремя кнопками.

Такт А (`planerka/runner/takt_a.py`) пишет файл недели с разделом «Банк
тем» — списком строк `- [ ] Тема одной строкой · откуда: источник`, которые
человек неделю решает руками, открыв файл. Этот модуль убирает шаг «не
забыть открыть файл»: бот сам приходит с каждой темой и тремя кнопками
«Беру» / «Подумать» / «Нет».

## Идентификатор темы, а не номер строки

`callback_data` кнопки не может нести порядковый номер темы: человек правит
банк между прогонами, темы сдвигаются местами, и нажатие легло бы не на ту
строку. Устойчивый идентификатор — хеш от текста темы — считает
`planerka.bot.темы.идентификатор`; тот же модуль (не копия) будет
использовать задача «приём нажатий», иначе два независимых расчёта хеша
разойдутся при любой мелкой правке одной из копий.

## Сеть отваливается на середине пачки

Файл недели после отправки НЕ переписывается — галочку в нём проставляет
только приём нажатия кнопки, не отправка. Значит, сам файл не может
служить источником «что уже отправлено»: после сбоя и повторного запуска
в «Банке тем» будут ровно те же строки без отметки, что и до сбоя, —
других следов там нет.

Поэтому что уже ушло — учитывается отдельно, в файле-спутнике рядом с
файлом недели: `<имя файла недели>.отправлено.json`, список идентификаторов
уже отправленных тем. Он дописывается атомарной записью сразу после
КАЖДОГО успешного вызова Bot API — не одной пачкой в конце: если сеть
оборвётся на третьем сообщении из пяти, первые два уже сохранены как
отправленные по отдельности, а не только «почти».

Ошибка сети или Телеграма при этом не проглатывается — пробрасывается
дальше как есть. «Не потерять неотправленное» здесь значит не сделать вид,
что прогон прошёл успешно: вызывающий код (и человек) должны узнать, что
пачка не дошла целиком, и что делать дальше — просто запустить отправку
ещё раз, уже отправленные темы не продублируются.
"""
import json
import os
from pathlib import Path

from .api import отправить_с_кнопками
from .темы import идентификатор

try:  # planerka.bot.* — вызов из тестов и из пакета planerka
    from ..runner.decisions import parse_decisions
    from ..runner.weeks import найти_файл_недели
except ImportError:  # bot.* — вызов как в run.py, планерка добавляет свой
    # каталог в sys.path напрямую, и planerka тогда не общий предок для
    # bot и runner, а два независимых пакета верхнего уровня (см. run.py).
    from runner.decisions import parse_decisions  # type: ignore[import-not-found]
    from runner.weeks import найти_файл_недели  # type: ignore[import-not-found]

# Telegram режет текст sendMessage по 4096 символам. Обрезаем с запасом на
# многоточие, чтобы получившаяся строка не превышала лимит ни на символ.
ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ = 4096
_МНОГОТОЧИЕ = "…"

# Порядок кнопок в одном горизонтальном ряду и их короткие ASCII-коды в
# callback_data. Коды латиницей нарочно: кириллица в UTF-8 весит два байта
# на символ, а лимит Телеграма на весь callback_data — 64 байта, и там же
# ещё идентификатор темы (см. planerka/bot/темы.py).
_КНОПКИ = (("Беру", "b"), ("Подумать", "d"), ("Нет", "n"))


def _файл_состояния(путь_недели: Path) -> Path:
    return путь_недели.parent / f"{путь_недели.stem}.отправлено.json"


def _прочесть_отправленные(файл: Path) -> set[str]:
    try:
        сырое = файл.read_text(encoding="utf-8")
    except OSError:
        return set()
    try:
        данные = json.loads(сырое)
    except json.JSONDecodeError:
        return set()
    отправлено = данные.get("отправлено") if isinstance(данные, dict) else None
    return set(отправлено) if isinstance(отправлено, list) else set()


def _записать_отправленные(файл: Path, идентификаторы: set[str]) -> None:
    содержимое = json.dumps({"отправлено": sorted(идентификаторы)}, ensure_ascii=False, indent=2)
    временный = файл.with_suffix(файл.suffix + ".tmp")
    временный.write_text(содержимое, encoding="utf-8")
    os.replace(временный, файл)


def _текст_сообщения(тема: str) -> str:
    """Текст сообщения — тема как есть, либо обрезанная под лимит Телеграма.

    Обрезка — только для того, что видит человек. Идентификатор темы
    (в кнопках) считается от полного, необрезанного текста — иначе задача
    «приём нажатий» не найдёт по нему исходную строку в файле.
    """
    if len(тема) <= ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ:
        return тема
    return тема[: ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ - len(_МНОГОТОЧИЕ)] + _МНОГОТОЧИЕ


def _ряды_кнопок(тема: str) -> list:
    ид = идентификатор(тема)
    return [[(подпись, f"{ид}:{код}") for подпись, код in _КНОПКИ]]


def отправить_банк_тем(токен: str, chat_id, notes_root: Path) -> dict:
    """Шлёт каждую неотмеченную тему банка текущей недели отдельным сообщением.

    Возвращает словарь:
    - `отправлено` — тексты тем, ушедшие сообщением именно в этом прогоне;
    - `пропущено` — тексты тем, что были отправлены раньше (например, до
      обрыва сети на прошлом прогоне) — сюда не дублируем;
    - `всего` — сколько неотмеченных тем нашлось в банке всего.

    Если файла недели нет или в его банке не осталось ни одной неотмеченной
    темы — ничего не отправляет, но печатает об этом: молчание неотличимо
    от «всё уже отправлено» и от «плагин не настроен».
    """
    путь_недели = найти_файл_недели(notes_root)
    if путь_недели is None:
        print("Файл недели не найден — банк тем отправлять неоткуда.")
        return {"отправлено": [], "пропущено": [], "всего": 0}

    решения = parse_decisions(путь_недели.read_text(encoding="utf-8"))
    темы = решения["не_решено"]

    if not темы:
        print(
            f"В банке тем файла «{путь_недели.name}» нет ни одной "
            "неотмеченной темы — отправлять нечего."
        )
        return {"отправлено": [], "пропущено": [], "всего": 0}

    файл_состояния = _файл_состояния(путь_недели)
    уже_отправлено = _прочесть_отправленные(файл_состояния)

    отправлено_сейчас: list[str] = []
    пропущено: list[str] = []

    for тема in темы:
        ид = идентификатор(тема)
        if ид in уже_отправлено:
            пропущено.append(тема)
            continue
        # Ошибка сети/Телеграма здесь не гасится: то, что уже успело уйти
        # и сохраниться выше по циклу, останется сохранённым, а сама
        # ошибка уйдёт вызывающему коду — прогон прервался, а не «прошёл
        # молча наполовину».
        отправить_с_кнопками(токен, chat_id, _текст_сообщения(тема), _ряды_кнопок(тема))
        уже_отправлено.add(ид)
        _записать_отправленные(файл_состояния, уже_отправлено)
        отправлено_сейчас.append(тема)

    return {"отправлено": отправлено_сейчас, "пропущено": пропущено, "всего": len(темы)}
