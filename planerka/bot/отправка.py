"""Отправка банка тем в Телеграм — по одной теме сообщением с тремя кнопками.

Такт А (`planerka/runner/takt_a.py`) пишет файл недели с разделом «Банк
тем» — списком строк `- [ ] Тема одной строкой · откуда: источник`, которые
человек неделю решает руками, открыв файл. Этот модуль убирает шаг «не
забыть открыть файл»: бот сам приходит с каждой темой и тремя кнопками
«Беру» / «Подумать» / «Нет».

## Идентификатор темы — от всей строки, не только от текста темы

`callback_data` кнопки не может нести порядковый номер темы: человек правит
банк между прогонами, темы сдвигаются местами, и нажатие легло бы не на ту
строку. Устойчивый идентификатор — хеш — считает
`planerka.bot.темы.идентификатор`; тот же модуль (не копия) будет
использовать задача «приём нажатий», иначе два независимых расчёта хеша
разойдутся при любой мелкой правке одной из копий.

Хешируется не очищенный текст темы (`тема`, как в `parse_decisions`), а всё
содержимое строки после чекбокса — `содержимое` из `строки_банка`, source
включительно (`Тема · откуда: источник`). Если хешировать только текст без
источника, две РАЗНЫЕ строки банка с одинаковым текстом темы, но из разных
источников (тема легко прилетает и из чата, и из трендвотчинга отдельными
строками) получили бы один и тот же идентификатор — вторая молча посчиталась
бы «уже отправленной» и не ушла бы никогда.

Обратная сторона этого выбора — контракт с задачей «приём нажатий»: если
человек поправит текст уже отправленной темы (или источник) в файле,
идентификатор в старой кнопке перестанет находиться в файле. Это не
дефект отправки, а свойство подхода «идентификатор = хеш от содержимого»:
нажатие на кнопку, чей идентификатор не находится в файле, должно сказать
об этом человеку, а не промолчать — это забота задачи «приём нажатий», не
этого модуля.

Полностью одинаковые строки банка (совпадают и тема, и источник, до буквы)
получают один и тот же идентификатор — и это осознанный выбор, не дыра:
такие строки неразличимы что для человека в Телеграме (два одинаковых
сообщения подряд), что для задачи «приём нажатий» (обе кнопки ищут в файле
одну и ту же строку). Вторая копия отправляется не второй раз, а
засчитывается как уже отправленная.

## Сеть отваливается на середине пачки

Файл недели после отправки НЕ переписывается — галочку в нём проставляет
только приём нажатия кнопки, не отправка. Значит, сам файл не может
служить источником «что уже отправлено»: после сбоя и повторного запуска
в «Банке тем» будут ровно те же строки без отметки, что и до сбоя, —
других следов там нет.

Поэтому что уже ушло — учитывается отдельно, в файле-спутнике рядом с
файлом недели: `<имя файла недели>.отправлено.json`, список идентификаторов
уже отправленных тем. Он дописывается атомарной записью сразу после
КАЖДОГО успешного вызова Bot API — не одной пачкой в конце: если сеть
оборвётся на третьем сообщении из пяти, первые два уже сохранены как
отправленные по отдельности, а не только «почти».

Ошибка сети или Телеграма при этом не проглатывается — пробрасывается
дальше как есть. «Не потерять неотправленное» здесь значит не сделать вид,
что прогон прошёл успешно: вызывающий код (и человек) должны узнать, что
пачка не дошла целиком, и что делать дальше — просто запустить отправку
ещё раз, уже отправленные темы не продублируются.
"""
import json
import os
import unicodedata
from pathlib import Path

from .api import отправить_с_кнопками
from .темы import идентификатор

try:  # planerka.bot.* — вызов из тестов и из пакета planerka
    from ..runner.decisions import строки_банка
    from ..runner.weeks import найти_файл_недели
except ImportError:  # bot.* — вызов как в run.py, планерка добавляет свой
    # каталог в sys.path напрямую, и planerka тогда не общий предок для
    # bot и runner, а два независимых пакета верхнего уровня (см. run.py).
    from runner.decisions import строки_банка  # type: ignore[import-not-found]
    from runner.weeks import найти_файл_недели  # type: ignore[import-not-found]

# Telegram меряет длину текста sendMessage в UTF-16 code units, не в
# питоновских кодовых точках (см. _длина_utf16) — лимит именно в этих
# единицах.
ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ = 4096
_МНОГОТОЧИЕ = "…"

# Порядок кнопок в одном горизонтальном ряду и их короткие ASCII-коды в
# callback_data. Коды латиницей нарочно: кириллица в UTF-8 весит два байта
# на символ, а лимит Телеграма на весь callback_data — 64 байта, и там же
# ещё идентификатор темы (см. planerka/bot/темы.py).
_КНОПКИ = (("Беру", "b"), ("Подумать", "d"), ("Нет", "n"))

# ZERO WIDTH JOINER — склеивает несколько эмодзи в одну составную картинку
# (например, семью из четырёх людей). Обрезка по лимиту не знает о таких
# последовательностях — см. _без_висячего_модификатора.
_СОЕДИНИТЕЛЬ = "‍"


def _файл_состояния(путь_недели: Path) -> Path:
    return путь_недели.parent / f"{путь_недели.stem}.отправлено.json"


def _прочесть_отправленные(файл: Path) -> set[str]:
    try:
        сырое = файл.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        # Файла нет, нет прав на чтение или в нём не текст, который можно
        # разобрать как UTF-8 (битые байты) — во всех случаях считаем, что
        # ничего ещё не отправлено, а не роняем весь прогон трейсбеком:
        # худшее, что случится, — тема, которая на самом деле уже уходила,
        # отправится ещё раз, а не пропадёт молча.
        return set()
    try:
        данные = json.loads(сырое)
    except json.JSONDecodeError:
        return set()
    отправлено = данные.get("отправлено") if isinstance(данные, dict) else None
    return set(отправлено) if isinstance(отправлено, list) else set()


def _записать_отправленные(файл: Path, идентификаторы: set[str]) -> None:
    содержимое = json.dumps({"отправлено": sorted(идентификаторы)}, ensure_ascii=False, indent=2)
    временный = файл.with_suffix(файл.suffix + ".tmp")
    временный.write_text(содержимое, encoding="utf-8")
    os.replace(временный, файл)


def _длина_utf16(текст: str) -> int:
    """Сколько code units займёт текст в UTF-16 — теми же единицами, какими
    Telegram считает лимит длины сообщения.

    Питоновский `len()` считает кодовые точки: для символов вне базовой
    многоязычной плоскости (код > U+FFFF — сюда попадает большинство
    современных эмодзи) в UTF-16 они кодируются суррогатной парой из двух
    единиц, а `len()` посчитает их за одну. Текст на таких символах прошёл
    бы проверку `len(текст) <= лимит`, но реально весил бы вдвое больше и
    получил бы от Телеграма отказ.
    """
    return sum(2 if ord(символ) > 0xFFFF else 1 for символ in текст)


def _без_висячего_модификатора(текст: str) -> str:
    """Убирает висящий соединитель/модификатор с конца обрезанного текста.

    Обрезка режет текст по сырым единицам длины и ничего не знает про
    составные эмодзи (семья из нескольких людей, эмодзи с тоном кожи —
    несколько кодовых точек, склеенных ZWJ или несущих вариационный
    селектор/комбинирующий знак). Если разрез попал сразу после такого
    соединителя или модификатора, в обрезанном тексте остаётся половина
    составного символа без пары: не крашит, но выглядит сломанным —
    висящий значок прямо перед многоточием. Отступаем назад, пока
    последний символ — соединитель или модификатор.
    """
    while текст and (
        текст[-1] == _СОЕДИНИТЕЛЬ
        # Категория Unicode "M*" — Mn/Mc/Me: комбинирующие знаки и
        # вариационные селекторы (например, U+FE0F, который просит
        # показать соседний символ эмодзи-картинкой, а не текстовым
        # символом). Ни один из них не самостоятелен без предыдущего.
        or unicodedata.category(текст[-1]).startswith("M")
    ):
        текст = текст[:-1]
    return текст


def _обрезать_до_utf16(текст: str, лимит_единиц: int) -> str:
    """Префикс текста, чей суммарный вес в UTF-16 не превышает лимит."""
    собрано: list[str] = []
    занято = 0
    for символ in текст:
        вес = 2 if ord(символ) > 0xFFFF else 1
        if занято + вес > лимит_единиц:
            break
        собрано.append(символ)
        занято += вес
    return "".join(собрано)


def _текст_сообщения(тема: str) -> str:
    """Текст сообщения — тема как есть, либо обрезанная под лимит Телеграма.

    Обрезка — только для того, что видит человек. Идентификатор темы (в
    кнопках) считается от полного, необрезанного содержимого строки банка
    — иначе задача «приём нажатий» не найдёт по нему исходную строку в
    файле.
    """
    if _длина_utf16(тема) <= ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ:
        return тема
    доступно = ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ - _длина_utf16(_МНОГОТОЧИЕ)
    обрезано = _без_висячего_модификатора(_обрезать_до_utf16(тема, доступно))
    return обрезано + _МНОГОТОЧИЕ


def _ряды_кнопок(содержимое: str) -> list:
    ид = идентификатор(содержимое)
    return [[(подпись, f"{ид}:{код}") for подпись, код in _КНОПКИ]]


def отправить_банк_тем(токен: str, chat_id, notes_root: Path) -> dict:
    """Шлёт каждую неотмеченную тему банка текущей недели отдельным сообщением.

    Возвращает словарь:
    - `отправлено` — тексты тем, ушедшие сообщением именно в этом прогоне;
    - `пропущено` — тексты тем, что были отправлены раньше (например, до
      обрыва сети на прошлом прогоне, либо это точная копия уже отправленной
      строки) — сюда не дублируем;
    - `всего` — сколько неотмеченных тем нашлось в банке всего.

    Если файла недели нет или в его банке не осталось ни одной неотмеченной
    темы — ничего не отправляет, но печатает об этом: молчание неотличимо
    от «всё уже отправлено» и от «плагин не настроен».
    """
    путь_недели = найти_файл_недели(notes_root)
    if путь_недели is None:
        print("Файл недели не найден — банк тем отправлять неоткуда.")
        return {"отправлено": [], "пропущено": [], "всего": 0}

    записи = [
        запись
        for запись in строки_банка(путь_недели.read_text(encoding="utf-8"))
        if запись["состояние"] == "не_решено"
    ]

    if not записи:
        print(
            f"В банке тем файла «{путь_недели.name}» нет ни одной "
            "неотмеченной темы — отправлять нечего."
        )
        return {"отправлено": [], "пропущено": [], "всего": 0}

    файл_состояния = _файл_состояния(путь_недели)
    уже_отправлено = _прочесть_отправленные(файл_состояния)

    отправлено_сейчас: list[str] = []
    пропущено: list[str] = []

    for запись in записи:
        тема = запись["тема"]
        содержимое = запись["содержимое"]
        ид = идентификатор(содержимое)
        if ид in уже_отправлено:
            пропущено.append(тема)
            continue
        # Ошибка сети/Телеграма здесь не гасится: то, что уже успело уйти
        # и сохраниться выше по циклу, останется сохранённым, а сама
        # ошибка уйдёт вызывающему коду — прогон прервался, а не «прошёл
        # молча наполовину».
        отправить_с_кнопками(токен, chat_id, _текст_сообщения(тема), _ряды_кнопок(содержимое))
        уже_отправлено.add(ид)
        _записать_отправленные(файл_состояния, уже_отправлено)
        отправлено_сейчас.append(тема)

    return {"отправлено": отправлено_сейчас, "пропущено": пропущено, "всего": len(записи)}
