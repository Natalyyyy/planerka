"""Приём нажатий кнопок «Беру / Подумать / Нет».

Единственное место в боте, которое трогает файл недели — а в нём лежит
недельная работа человека: отметки, план по дням, свои разделы. Такт А
отказывается переписывать файл с чужой разметкой (`runner/takt_a.py`),
такт Б владеет только двумя своими разделами и сохраняет остальное дословно
(`runner/takt_b.py`). Этот модуль держит ту же планку: правится ровно один
символ в одной строке «Банка тем», ничего больше.

## Как находится строка

`отправка.py` кладёт в `callback_data` кнопки хеш от ВСЕЙ строки банка после
чекбокса — тема плюс `· откуда: источник` (`planerka.bot.темы.идентификатор`).
Идентификатор не зависит от текущего маркера строки: строку находим по её
содержимому, какой бы маркер в ней сейчас ни стоял — свежая пустая клетка,
маркер, который бот сам поставил раньше, или маркер, который человек
проставил руками. Это и даёт контракт, зафиксированный при отправке: если
человек поправит текст уже отправленной темы, идентификатор в старой кнопке
перестанет находиться в файле — и нажатие обязано сказать об этом, а не
промолчать (см. `_ОТВЕТЫ["тема_не_найдена"]` ниже).

Строка ищется только внутри раздела «Банк тем», тем же обходом (блоки кода,
вложенные строки, границы разделов), что и `runner.decisions._разобрать`, —
переиспользуются его регулярки (`СТРОКА`, `ЗАГОЛОВОК_БАНКА`,
`ЗАГОЛОВОК_РАЗДЕЛА`, `СОСТОЯНИЕ`), чтобы не завести вторую, слегка другую
трактовку того, что вообще считается строкой банка. Чекбокс с тем же
текстом, случайно написанный человеком в другом разделе, — не банк, и
нажатие туда не полезет: `_строки_банка_с_позициями` физически не увидит
его вне раздела.

## Два одинаковых нажатия

Дважды нажатая (или нажатая, потом отменённая другой кнопкой) тема не
дублирует строку — меняется маркер той же самой строки, найденной по тому
же содержимому. Если человек успел отметить тему руками другим маркером —
нажатие всё равно побеждает: решение через бота считается более свежим,
чем то, что стояло в файле на момент нажатия. Но перезапись — не тихая:
подтверждение называет и старое, и новое решение по имени («раньше стояло
«нет», записано «беру»»). Без этого случайное нажатие по старому сообщению
в чате (человек листает переписку за неделю и задевает кнопку) молча
переворачивает обдуманное решение — а подтверждение «записано» выглядит
так же, как если бы это было первое решение по теме, и разницу узнать
неоткуда. Если в строке уже стоит именно тот маркер, который просит
нажатие, — файл не трогается вовсе: письмо «уже отмечено» подтверждает
нажатие без слова «раньше» (менять было не на что), запись не происходит,
и это самый строгий случай инварианта «не больше одного символа» — здесь
их меняется ровно ноль.

## Кнопка подтверждается всегда

`ответить_на_нажатие` вызывается в конце каждого пути — успешного,
идемпотентного и любого из отказов. Промолчавшая кнопка у человека крутится
и создаёт впечатление, что нажатие потерялось; а не найденная тема — самый
опасный случай промолчать: человек увидит, что кнопка отработала, и
подумает, что решение записалось, хотя файл не тронут.
"""
import re
from pathlib import Path

from .api import ответить_на_нажатие
from .темы import ДЛИНА_ИДЕНТИФИКАТОРА, идентификатор

try:  # planerka.bot.* — вызов из тестов и из пакета planerka
    from ..runner.decisions import ЗАГОЛОВОК_БАНКА, ЗАГОЛОВОК_РАЗДЕЛА, СОСТОЯНИЕ, СТРОКА
    from ..runner.weeks import найти_файл_недели
    from ..runner.файлы import записать_атомарно
except ImportError:  # bot.* — вызов как в run.py, планёрка добавляет свой
    # каталог в sys.path напрямую (см. run.py) — planerka тогда не общий
    # предок для bot и runner, а два независимых пакета верхнего уровня.
    from runner.decisions import (  # type: ignore[import-not-found]
        ЗАГОЛОВОК_БАНКА,
        ЗАГОЛОВОК_РАЗДЕЛА,
        СОСТОЯНИЕ,
        СТРОКА,
    )
    from runner.weeks import найти_файл_недели  # type: ignore[import-not-found]
    from runner.файлы import записать_атомарно  # type: ignore[import-not-found]

# Код кнопки (см. planerka/bot/отправка.py, _КНОПКИ) → символ маркера,
# который встаёт в чекбокс строки банка.
КОД_К_МАРКЕРУ = {"b": "x", "d": "?", "n": "-"}
ИМЯ_РЕШЕНИЯ = {"x": "беру", "?": "подумать", "-": "нет"}

_ХЕКС_ИДЕНТИФИКАТОРА = re.compile(rf"^[0-9a-f]{{{ДЛИНА_ИДЕНТИФИКАТОРА}}}$")

_ТЕКСТ_НЕВЕРНОГО_ФОРМАТА = (
    "Кнопка в неожиданном формате — решение не записано. "
    "Откройте файл недели и отметьте тему вручную."
)
_ТЕКСТ_БИТОГО_ИДЕНТИФИКАТОРА = (
    "Идентификатор темы в кнопке повреждён — решение не записано. "
    "Откройте файл недели и отметьте тему вручную."
)


class _ОшибкаНажатия(ValueError):
    """Callback_data нельзя разобрать — формат или сам идентификатор битые."""


def _разобрать_callback_data(данные: str) -> tuple[str, str]:
    """Возвращает (идентификатор, символ_маркера) или бросает `_ОшибкаНажатия`
    с текстом, который можно показать человеку как есть.

    Две разные причины отказа — разный текст: «не того формата» (нет
    двоеточия, лишние части, неизвестный код кнопки) и «идентификатор
    битый» (двоеточие и код на месте, а часть до него — не тот хеш,
    который выпускает `planerka.bot.темы.идентификатор`) — это разные
    поломки на разных концах провода, и разбираться в них тоже по-разному.
    """
    if not isinstance(данные, str):
        raise _ОшибкаНажатия(_ТЕКСТ_НЕВЕРНОГО_ФОРМАТА)
    части = данные.split(":")
    if len(части) != 2:
        raise _ОшибкаНажатия(_ТЕКСТ_НЕВЕРНОГО_ФОРМАТА)
    ид, код = части
    if код not in КОД_К_МАРКЕРУ:
        raise _ОшибкаНажатия(_ТЕКСТ_НЕВЕРНОГО_ФОРМАТА)
    if not _ХЕКС_ИДЕНТИФИКАТОРА.match(ид):
        raise _ОшибкаНажатия(_ТЕКСТ_БИТОГО_ИДЕНТИФИКАТОРА)
    return ид, КОД_К_МАРКЕРУ[код]


def _строки_банка_с_позициями(текст: str) -> list[dict]:
    """(индекс строки, сырой символ маркера, содержимое) для каждой валидной
    строки раздела «Банк тем», в порядке появления в файле.

    Обход намеренно повторяет `runner.decisions._разобрать`: блоки кода,
    вложенные (с отступом) строки и границы разделов «## ...» — те же
    правила, что решают, какая строка вообще годится в решение человека.
    Не переиспользуется сама `_разобрать` (имя с подчёркиванием — приватная
    функция чужого модуля), но регулярки и правило «что считается строкой
    банка» — общие с ней, импортированы напрямую, а не списаны заново.
    """
    lines = текст.splitlines()

    закрытые_блоки_кода: set[int] = set()
    в_блоке_кода = False
    начало_блока = None
    for i, line in enumerate(lines):
        if line.strip().startswith("```"):
            if not в_блоке_кода:
                начало_блока = i
                в_блоке_кода = True
            else:
                закрытые_блоки_кода.update(range(начало_блока, i + 1))
                в_блоке_кода = False
                начало_блока = None

    в_блоке_кода = False
    в_разделе_банка = False
    найдено: list[dict] = []

    for i, line in enumerate(lines):
        if line.strip().startswith("```"):
            в_блоке_кода = not в_блоке_кода
            continue
        if i in закрытые_блоки_кода:
            continue
        if ЗАГОЛОВОК_РАЗДЕЛА.match(line.strip()):
            в_блоке_кода = False
            в_разделе_банка = bool(ЗАГОЛОВОК_БАНКА.match(line.strip()))
            continue
        if в_блоке_кода or not в_разделе_банка:
            continue
        if line and line[0] in " \t":
            continue  # вложенная строка — не решение верхнего уровня

        м = СТРОКА.match(line.strip())
        if not м:
            continue
        маркер = м[1]
        if маркер.lower() not in СОСТОЯНИЕ:
            continue
        содержимое = м[2].strip()
        if not содержимое:
            continue
        найдено.append({"индекс": i, "маркер": маркер, "содержимое": содержимое})

    return найдено


def _заменить_маркер(строка_с_концом: str, новый_маркер: str) -> str:
    """Меняет ровно один символ — тот, что стоит между `[` и `]` — оставляя
    всё остальное в строке (включая перевод строки на конце) как есть."""
    открывающая = строка_с_концом.index("[")
    return строка_с_концом[: открывающая + 1] + новый_маркер + строка_с_концом[открывающая + 2 :]


_ОТВЕТЫ = {
    "файла_недели_нет": "Файл недели не найден — решение не записано.",
    "тема_не_найдена": (
        "Эта тема в файле недели изменилась или её больше нет — решение "
        "не записано. Откройте файл недели и проверьте вручную."
    ),
    "ошибка_чтения": (
        "Не удалось прочитать файл недели — решение не сохранено, попробуйте ещё раз."
    ),
    "ошибка_записи": (
        "Не удалось записать файл недели (занят или нет прав) — решение "
        "не сохранено, попробуйте ещё раз."
    ),
}


def принять_нажатие(токен: str, id_нажатия: str, callback_data: str, notes_root: Path) -> dict:
    """Обрабатывает одно нажатие кнопки и сразу подтверждает его человеку.

    Возвращает словарь `{"статус": ..., "файл": путь_недели | None}` —
    для вызывающего кода (будущий цикл опроса обновлений) и для тестов.
    Статусы: `записано`, `без_изменений` (в строке уже стоял тот же
    маркер — файл не тронут), `тема_не_найдена`, `файла_недели_нет`,
    `нажатие_повреждено`, `ошибка_записи` (сюда же — ошибка чтения).

    Ни один путь не бросает исключение наружу: сеть и файловая система —
    внешний мир, который может подвести в любой момент, а кнопка у
    человека должна получить понятный ответ, а не упасть в трейсбек бота.
    """
    try:
        ид, желаемый_маркер = _разобрать_callback_data(callback_data)
    except _ОшибкаНажатия as ошибка:
        ответить_на_нажатие(токен, id_нажатия, str(ошибка))
        return {"статус": "нажатие_повреждено", "файл": None}

    путь_недели = найти_файл_недели(notes_root)
    if путь_недели is None:
        ответить_на_нажатие(токен, id_нажатия, _ОТВЕТЫ["файла_недели_нет"])
        return {"статус": "файла_недели_нет", "файл": None}

    try:
        текст = путь_недели.read_text(encoding="utf-8")
    except OSError:
        ответить_на_нажатие(токен, id_нажатия, _ОТВЕТЫ["ошибка_чтения"])
        return {"статус": "ошибка_записи", "файл": путь_недели}

    записи = _строки_банка_с_позициями(текст)
    целевая = next(
        (з for з in записи if идентификатор(з["содержимое"]) == ид), None
    )
    if целевая is None:
        ответить_на_нажатие(токен, id_нажатия, _ОТВЕТЫ["тема_не_найдена"])
        return {"статус": "тема_не_найдена", "файл": путь_недели}

    текущий_маркер = целевая["маркер"].lower()
    if текущий_маркер == желаемый_маркер:
        ответить_на_нажатие(
            токен, id_нажатия,
            f"Уже отмечено как «{ИМЯ_РЕШЕНИЯ[желаемый_маркер]}» — ничего не меняю.",
        )
        return {"статус": "без_изменений", "файл": путь_недели}

    строки_с_концами = текст.splitlines(keepends=True)
    строки_с_концами[целевая["индекс"]] = _заменить_маркер(
        строки_с_концами[целевая["индекс"]], желаемый_маркер
    )
    новый_текст = "".join(строки_с_концами)

    try:
        записать_атомарно(путь_недели, новый_текст)
    except OSError:
        ответить_на_нажатие(токен, id_нажатия, _ОТВЕТЫ["ошибка_записи"])
        return {"статус": "ошибка_записи", "файл": путь_недели}

    # Прежнее решение называем по имени, только если оно вообще было — то
    # есть в строке до нажатия стоял другой маркер решения (не пустая
    # клетка). Без этого случайное нажатие по старому сообщению в чате
    # молча переворачивает то, что человек уже решил, а подтверждение
    # «записано» выглядит так же, как если бы это было первое решение —
    # разницу узнать неоткуда.
    прежнее_решение = ИМЯ_РЕШЕНИЯ.get(текущий_маркер)
    if прежнее_решение is not None:
        текст_подтверждения = (
            f"Записано: «{ИМЯ_РЕШЕНИЯ[желаемый_маркер]}». Раньше у этой темы "
            f"стояло «{прежнее_решение}» — если это случайное нажатие, "
            "поправьте в файле."
        )
    else:
        текст_подтверждения = f"Записано: «{ИМЯ_РЕШЕНИЯ[желаемый_маркер]}». Файл недели обновлён."

    ответить_на_нажатие(токен, id_нажатия, текст_подтверждения)
    return {"статус": "записано", "файл": путь_недели}
