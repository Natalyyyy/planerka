_ЗАДЕРЖКА_ПОСЛЕ_ОШИБКИ_СЕТИ = 5.0

# Имя лок-файла — точка в начале, чтобы не попадать в списки «обычных»
# файлов заметок и не путаться с файлами недели.
_ИМЯ_ФАЙЛА_БЛОКИРОВКИ = ".бот.lock"

_ДНИ_НЕДЕЛИ = {
    "понедельник": 0,
    "вторник": 1,
    "среда": 2,
    "четверг": 3,
    "пятница": 4,
    "суббота": 5,
    "воскресенье": 6,
}


def _разобрать_дедлайн(строка: str) -> tuple[int, int, int] | None:
    """«среда, 20:00» → (2, 20, 0). Не распознано — `None`, а не исключение:
    кривой конфиг не должен ронять процесс, только выключать проверку
    дедлайна (со предупреждением на старте — см. `_предупредить_о_дедлайне`)."""
    if not isinstance(строка, str) or "," not in строка:
        return None
    день_часть, _, время_часть = строка.partition(",")
    день = _ДНИ_НЕДЕЛИ.get(день_часть.strip().lower())
    if день is None:
        return None
    время_часть = время_часть.strip()
    if ":" not in время_часть:
        return None
    часы_текст, _, минуты_текст = время_часть.partition(":")
    try:
        часы, минуты = int(часы_текст), int(минуты_текст)
    except ValueError:
        return None
    if not (0 <= часы <= 23 and 0 <= минуты <= 59):
        return None
    return день, часы, минуты


def _дедлайн_для_файла(config: dict, путь_недели: Path) -> datetime | None:
    """Дедлайн такта Б как конкретный момент времени для КОНКРЕТНОГО файла
    недели — не «сегодня», а понедельник из имени этого файла плюс день
    недели и время из конфига. `None`, если посчитать нечем: поля нет в
    конфиге или строка не разобралась (`_разобрать_дедлайн`).

    Имя файла НЕ перепроверяется на соответствие шаблону недели и валидность
    даты — единственный вызывающий код (`_обработать_дедлайн`) берёт
    `путь_недели` из `найти_файл_недели`, а та уже гарантирует и совпадение
    с `weeks.ИМЯ`, и корректную дату (см. `weeks._дата`). Вызов этой функции
    с произвольным, непроверенным путём — ответственность вызывающего кода,
    не эта функция должна страховать чужой контракт молчаливым `None`.
    """
    разобранное = _разобрать_дедлайн(config.get("дедлайн_такта_б", ""))
    if разобранное is None:
        return None
    совпадение = ИМЯ.match(путь_недели.name)
    понедельник = date(int(совпадение[1]), int(совпадение[2]), int(совпадение[3]))
    день, часы, минуты = разобранное
    целевая_дата = понедельник + timedelta(days=день)
    return datetime.combine(целевая_дата, время_суток(часы, минуты))


def _файл_состояния_дедлайна(путь_недели: Path) -> Path:
    return путь_недели.parent / f"{путь_недели.stem}.дедлайн-обработан.json"


def _прочесть_маркер_дедлайна(путь_недели: Path) -> dict | None:
    """Маркер дедлайна для этого файла, если он есть и разобрался.

    Битый файл (не JSON, не словарь, недоступен) — тоже `None`: для кода
    это неотличимо от «маркера ещё нет», а значит дедлайн будет обработан
    заново — лучше лишний раз сообщить человеку, чем один раз промолчать
    из-за испорченного файла на диске."""
    файл = _файл_состояния_дедлайна(путь_недели)
    try:
        сырое = файл.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None
    try:
        данные = json.loads(сырое)
    except json.JSONDecodeError:
        return None
    return данные if isinstance(данные, dict) else None


def _записать_маркер_дедлайна(путь_недели: Path, дедлайн: datetime, сообщение: str, *, уведомлён: bool) -> None:
    записать_атомарно(
        _файл_состояния_дедлайна(путь_недели),
        json.dumps(
            {"дедлайн": дедлайн.isoformat(), "сообщение": сообщение, "уведомлён": уведомлён},
            ensure_ascii=False,
        ),
    )


def _обработать_дедлайн(
    *,
    notes_root: Path,
    config: dict,
    токен: str,
    chat_id,
    blocks_dir: Path,
    собрать_план,
    отправить_сообщение_,
    now,
) -> None:
    """Проверяет дедлайн такта Б и обрабатывает его (см. докстринг модуля —
    раздел «Дедлайн такта Б» — про то, что значит «обработать» и почему
    маркер хранит не флаг, а момент дедлайна, готовое сообщение и то,
    дошло ли оно до человека).

    Сама сборка плана (`собрать_план`, по умолчанию настоящая `takt_b`) —
    своя логика планёрки, и её падение (в том числе «ни одной взятой темы»)
    ловится здесь широко: причин упасть у неё много, а правило одно и то
    же для всех — сказать человеку, а не промолчать, и не уронить процесс.
    """
    путь_недели = найти_файл_недели(notes_root)
    if путь_недели is None:
        return

    дедлайн = _дедлайн_для_файла(config, путь_недели)
    if дедлайн is None:
        return

    # Momент фиксируется ровно один раз за проход: и для сравнения с
    # дедлайном, и (если дедлайн наступил) как «сегодня» для собрать_план —
    # два отдельных вызова `now()` в одной итерации дали бы возможность
    # разъехаться (а в тестах — исчерпали бы список подставленных значений
    # быстрее, чем есть итераций).
    момент = now()
    if момент < дедлайн:
        return

    дедлайн_iso = дедлайн.isoformat()
    маркер = _прочесть_маркер_дедлайна(путь_недели)
    маркер_актуален = isinstance(маркер, dict) and маркер.get("дедлайн") == дедлайн_iso

    if маркер_актуален and маркер.get("уведомлён"):
        return  # этот дедлайн уже полностью закрыт — сообщили, больше не трогаем

    сообщение = маркер.get("сообщение") if маркер_актуален else None
    if not isinstance(сообщение, str) or not сообщение:
        # Такт Б для ЭТОГО дедлайна ещё не пробовали (маркера нет вовсе,
        # он от другого/старого дедлайна или битый) — пробуем ровно один
        # раз и запоминаем результат ДО попытки сообщить: не получится
        # отправить — следующая итерация повторит только отправку, не
        # саму сборку плана (дорогой вызов модели).
        try:
            путь_плана = собрать_план(config, notes_root, blocks_dir, момент.date())
        except Exception as ошибка:  # noqa: BLE001 — см. докстринг: любая причина одинаково «сказать человеку»
            сообщение = f"Наступил дедлайн такта Б, но план собрать не получилось: {ошибка}"
        else:
            сообщение = f"Наступил дедлайн такта Б — план собран: {путь_плана}"
        _записать_маркер_дедлайна(путь_недели, дедлайн, сообщение, уведомлён=False)

    try:
        отправить_сообщение_(токен, chat_id, сообщение)
    except ОшибкаБота as ошибка:
        print(f"Не удалось отправить уведомление о дедлайне, попробую снова: {ошибка}", file=sys.stderr)
        return  # маркер уже хранит готовое сообщение — следующая итерация повторит только отправку

    _записать_маркер_дедлайна(путь_недели, дедлайн, сообщение, уведомлён=True)


def _предупредить_о_дедлайне(config: dict) -> None:
    """Один раз при старте — если `дедлайн_такта_б` в конфиге ЕСТЬ, но не
    разбирается, такт Б по дедлайну сам не сработает никогда, и раньше
    процесс молчал об этом полностью. Поля попросту нет — это не ошибка,
    ничего не печатаем."""
    строка = config.get("дедлайн_такта_б")
    if not строка:
        return
    if _разобрать_дедлайн(строка) is not None:
        return
    print(
        f"Дедлайн такта Б в конфиге не разобрался («{строка}») — такт Б сам "
        "по дедлайну не запустится, пока не поправите «дедлайн_такта_б» в "
        "конфиг.json (формат «день, ЧЧ:ММ», например «среда, 20:00»).",
        file=sys.stderr,
    )


def _обработать_обновление(обновление: dict, токен: str, notes_root: Path, принять_нажатие_) -> None:
    """Одно обновление из пачки `getUpdates`. Не `callback_query` — молча
    пропускается, это штатный тип обновления (например, обычное сообщение),
    который приём нажатий не касается.

    `принять_нажатие` сама не бросает исключений наружу (см. её докстринг),
    но это внешний для этого модуля контракт — здесь он подстрахован ещё
    раз широким `except`, чтобы даже неожиданное падение внутри неё не
    уронило весь цикл опроса из-за одного нажатия. Вызывающий код уже
    проверил, что `обновление` — словарь; сама структура Телеграма (что
    лежит внутри) не гарантирована ничем, кроме документации API, поэтому
    `callback.get(...)` ниже тоже внутри try — Телеграм присылает то, что
    присылает, а не то, что мы ожидаем."""
    callback = обновление.get("callback_query")
    if callback is None:
        return
    try:
        принять_нажатие_(токен, callback.get("id"), callback.get("data"), notes_root)
    except Exception as ошибка:  # noqa: BLE001 — см. докстринг функции
        print(f"Обработка нажатия упала, продолжаю: {ошибка}", file=sys.stderr)


def _файл_блокировки(notes_root: Path) -> Path:
    return notes_root / _ИМЯ_ФАЙЛА_БЛОКИРОВКИ


def _процесс_жив(pid: int) -> bool:
    """`os.kill(pid, 0)` не убивает — только проверяет, существует ли pid."""
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True  # процесс есть, просто принадлежит другому пользователю
    except OSError:
        return False
    return True


def _захватить_блокировку(notes_root: Path) -> Path:
    """Один живой процесс бота на папку заметок — не больше (см. докстринг
    модуля, раздел «Один процесс на папку заметок»).

    Бросает `RuntimeError`, если лок-файл содержит pid ЖИВОГО процесса —
    вызывающий код обязан превратить это в понятное сообщение и выход, а
    не в трейсбек. Лок от процесса, которого уже нет (сам файл остался —
    процесс убили, не дав ему выполнить `finally`), не блокирует: старый
    файл тихо перезаписывается нашим pid.
    """
    файл = _файл_блокировки(notes_root)
    try:
        существующий_pid = int(файл.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        существующий_pid = None
    if существующий_pid is not None and _процесс_жив(существующий_pid):
        raise RuntimeError(
            f"бот для этой папки заметок уже запущен в другом процессе (pid "
            f"{существующий_pid}) — два процесса на одну папку заметок дают "
            "двойные уведомления о дедлайне и конфликт на опросе Телеграма "
            "(ошибка 409), поэтому не запускаюсь. Остановите тот процесс и "
            "запустите этот заново."
        )
    записать_атомарно(файл, str(os.getpid()))
    return файл


def _освободить_блокировку(файл: Path) -> None:
    try:
        файл.unlink()
    except OSError:
        pass


def запустить_бота(
    токен: str,
    chat_id,
    notes_root: Path,
    config: dict,
    blocks_dir: Path,
    *,
    получить_обновления=получить_обновления,
    принять_нажатие=принять_нажатие,
    отправить_сообщение=отправить_сообщение,
    собрать_план=takt_b,
    now=datetime.now,
    sleep=time.sleep,
    макс_итераций: int | None = None,
) -> None:
    """Крутит long-polling, пока его не остановят.

    `макс_итераций=None` (по умолчанию, для прода) — цикл живёт вечно, до
    `Ctrl+C` или протухшего токена. Конечное число — для тестов: столько
    проходов `получить_обновления`, и функция возвращается сама, как будто
    процесс остановили.
    """
    try:
        файл_блокировки = _захватить_блокировку(notes_root)
    except RuntimeError as ошибка:
        print(str(ошибка), file=sys.stderr)
        raise SystemExit(1) from ошибка

    try:
        _предупредить_о_дедлайне(config)

        смещение: int | None = None
        итерация = 0
        print("Бот запущен — слушаю Телеграм.")

        try:
            while макс_итераций is None or итерация < макс_итераций:
                итерация += 1
                try:
                    обновления = получить_обновления(токен, смещение=смещение)
                except ОшибкаТокена as ошибка:
                    print(f"Токен недействителен — бот остановлен: {ошибка}", file=sys.stderr)
                    # Не штатная остановка (в отличие от Ctrl+C ниже) —
                    # дальше опрашивать нечем, и супервизор автозапуска
                    # (часть 3) должен это увидеть по коду выхода, а не по
                    # нулю «всё в порядке».
                    raise SystemExit(1) from ошибка
                except ОшибкаКонфликта as ошибка:
                    # 409 от Телеграма — почти всегда «этого бота уже кто-то
                    # опрашивает» (см. докстринг модуля). Печатаем понятно,
                    # но не выходим сразу: конфликт может быть переходным
                    # (например, только что остановленный процесс ещё
                    # держит соединение на стороне Телеграма несколько
                    # секунд) — ждём и пробуем снова, как при любой другой
                    # временной ошибке опроса.
                    print(str(ошибка), file=sys.stderr)
                    sleep(_ЗАДЕРЖКА_ПОСЛЕ_ОШИБКИ_СЕТИ)
                    обновления = []
                except ОшибкаБота as ошибка:
                    # Сеть/Телеграм временно подвели — не выходим, ждём и
                    # пробуем снова на следующем проходе того же цикла.
                    # Смещение здесь НЕ трогаем: оно остаётся таким, каким
                    # было после последнего успешно обработанного
                    # обновления, — иначе после обрыва Телеграм отдал бы
                    # весь неподтверждённый хвост заново.
                    print(f"Опрос Телеграма не удался, пробую ещё раз: {ошибка}", file=sys.stderr)
                    sleep(_ЗАДЕРЖКА_ПОСЛЕ_ОШИБКИ_СЕТИ)
                    обновления = []

                if not isinstance(обновления, list):
                    # Телеграм по контракту отдаёт список, но контракт —
                    # не гарантия: мусорный ответ не должен ронять процесс
                    # трейсбеком, супервизор части 3 получил бы крэш-луп.
                    print(
                        f"Опрос вернул не список обновлений ({type(обновления).__name__}) "
                        "— пропускаю этот проход",
                        file=sys.stderr,
                    )
                    обновления = []

                for обновление in обновления:
                    if not isinstance(обновление, dict):
                        print(
                            f"Обновление неожиданного вида ({type(обновление).__name__}) "
                            "— пропускаю",
                            file=sys.stderr,
                        )
                        continue
                    _обработать_обновление(обновление, токен, notes_root, принять_нажатие)
                    # Сдвигаем смещение даже если обработка выше упала —
                    # иначе то же обновление придёт на следующем опросе
                    # снова и снова, и весь цикл встанет намертво на одном
                    # сообщении.
                    ид_обновления = обновление.get("update_id")
                    if isinstance(ид_обновления, int):
                        смещение = ид_обновления + 1
                    elif ид_обновления is not None:
                        print(
                            f"update_id неожиданного вида ({ид_обновления!r}) — "
                            "смещение для этого обновления не сдвигаю",
                            file=sys.stderr,
                        )

                _обработать_дедлайн(
                    notes_root=notes_root,
                    config=config,
                    токен=токен,
                    chat_id=chat_id,
                    blocks_dir=blocks_dir,
                    собрать_план=собрать_план,
                    отправить_сообщение_=отправить_сообщение,
                    now=now,
                )
        except KeyboardInterrupt:
            print("Бот остановлен.")
            return
    finally:
        _освободить_блокировку(файл_блокировки)
