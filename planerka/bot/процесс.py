"""Долгоживущий процесс бота: опрос обновлений, приём нажатий, дедлайн такта Б.

Части 1–3 дали строительные блоки — клиент Bot API (`api.py`), отправку банка
(`отправка.py`), приём одного нажатия (`приём.py`). Этот модуль — то, что
превращает их в живой процесс: крутится, пока его не остановят, слушает
Телеграм и сам решает, когда пора собрать план недели.

## Смещение (offset getUpdates)

Телеграм не присылает одно и то же обновление дважды, если ему подтвердили
получение более раннего — подтверждение это и есть следующий вызов
`getUpdates` с `offset = update_id + 1`. Значит хранить смещение между
перезапусками процесса не нужно: как только предыдущий процесс успел
подтвердить обновление хоть одним вызовом, Телеграм сам больше не пришлёт
его новому процессу, даже если тот стартует со смещения `None`. Риск есть
только на стыке «обновление обработано, а следующий вызов getUpdates ещё не
успел уйти» — тогда после падения процесса то же обновление придёт снова.
Это не дыра, а ровно тот случай, ради которого `принять_нажатие`
идемпотентна: повторное нажатие с тем же исходом не меняет файл дважды.

Внутри одного запуска смещение сдвигается на `update_id + 1` после КАЖДОГО
обновления в пачке — даже если разбор этого конкретного обновления упал.
Иначе одно неразбираемое обновление стопорит весь опрос навсегда: Телеграм
будет присылать его снова и снова, а до обновлений после него дело никогда
не дойдёт.

## Дедлайн такта Б

Дедлайн хранится в конфиге строкой человека — `"среда, 20:00"`
(`конфиг.json`, поле `дедлайн_такта_б`, см. `skills/planerka-setup`). Имя
файла недели несёт дату понедельника той недели, когда такт А завёл файл
(`runner/weeks.py`, `runner/takt_a.начало_недели`) — от него и считается
дедлайн: понедельник файла плюс смещение на нужный день недели, в заданное
время. Это НЕ «сегодня плюс день недели» — то давало бы дедлайн для чужой
недели, если процесс проверяет дедлайн уже после того, как наступил
следующий понедельник и такт А завёл новый файл.

Дедлайн проверяется в том же цикле, что и опрос обновлений, не отдельным
потоком/таймером: процесс и так каждые несколько секунд просыпается на
`getUpdates`, отдельный таймер добавил бы гонку без выгоды.

Наступивший дедлайн обрабатывается ровно один раз на файл недели — рядом с
файлом заводится файл-спутник `<файл недели>.дедлайн-обработан.json`, тем
же приёмом, каким `отправка.py` метит уже отправленные темы своим
файлом-спутником. Отмечается «обработан» и при успехе, и при падении такта
Б: цель не в том, чтобы обязательно досчитать план, а в том, чтобы не
заспамить человека одним и тем же сообщением на каждой следующей итерации,
пока причина падения (например, ни одной взятой темы) сама не исчезнет —
для этого есть такт «план», который можно перезапустить руками. Файл-
спутник переживает и перезапуск процесса: два запуска подряд с уже
наступившим дедлайном присылают уведомление один раз, а не по разу на
каждый запуск.

## Остановка

`Ctrl+C` (`KeyboardInterrupt`) ловится вокруг всего цикла и завершает
процесс тихо — без трейсбека, с понятной строкой и, что здесь важно, с
**нулевым кодом выхода**: это штатная остановка, никто ничего не сломал.

`ОшибкаТокена` от опроса означает, что дальше опрашивать нечем (токен не
примут), и это тоже выход — но не такой же, как `Ctrl+C`. Бот в части 3
поднимается автозапуском (launchd на маке, systemd на сервере), а такой
супервизор отличает штатную остановку от аварийной ТОЛЬКО по коду выхода:
нулевой код значит «отработал и закончил», супервизор ничего не заметит и
не перезапустит. Поэтому эта ветка не просто печатает сообщение и
возвращается — она поднимает `SystemExit` с ненулевым кодом, чтобы дойти
через `run.py` до самого интерпретатора и стать настоящим кодом выхода
процесса.

Любая другая `ОшибкаБота` (обрыв сети, странный ответ, отказ Телеграма) на
опросе — временная: ждём и пробуем снова, не молча, а с сообщением в лог.

## Как гоняется долгий цикл в тестах

`макс_итераций` ограничивает число проходов `getUpdates` конечным числом —
без него `запустить_бота` не возвращается сам, и тест завис бы навсегда.
В проде (вызов из `run.py`) параметр не передаётся, и цикл живёт, пока его
не остановят `Ctrl+C` или протухший токен.
"""
from __future__ import annotations

import json
import sys
import time
from datetime import date, datetime
from datetime import time as время_суток
from datetime import timedelta
from pathlib import Path

from .api import ОшибкаБота, ОшибкаТокена, отправить_сообщение, получить_обновления
from .приём import принять_нажатие

try:  # planerka.bot.* — вызов из тестов и из пакета planerka
    from ..runner.weeks import ИМЯ, найти_файл_недели
    from ..runner.takt_b import takt_b
    from ..runner.файлы import записать_атомарно
except ImportError:  # bot.* — вызов как в run.py, планёрка добавляет свой
    # каталог в sys.path напрямую (см. run.py) — planerka тогда не общий
    # предок для bot и runner, а два независимых пакета верхнего уровня.
    from runner.weeks import ИМЯ, найти_файл_недели  # type: ignore[import-not-found]
    from runner.takt_b import takt_b  # type: ignore[import-not-found]
    from runner.файлы import записать_атомарно  # type: ignore[import-not-found]

# Сколько ждать перед повторной попыткой опроса после сетевой/телеграмной
# ошибки. Дольше обычного интервала getUpdates (таймаут долгого опроса и
# так держит соединение секундами) — чтобы не долбить упавший Телеграм
# частыми повторами, но и не молчать минутами.
_ЗАДЕРЖКА_ПОСЛЕ_ОШИБКИ_СЕТИ = 5.0

_ДНИ_НЕДЕЛИ = {
    "понедельник": 0,
    "вторник": 1,
    "среда": 2,
    "четверг": 3,
    "пятница": 4,
    "суббота": 5,
    "воскресенье": 6,
}


def _разобрать_дедлайн(строка: str) -> tuple[int, int, int] | None:
    """«среда, 20:00» → (2, 20, 0). Не распознано — `None`, а не исключение:
    кривой конфиг не должен ронять процесс, только выключать проверку
    дедлайна."""
    if not isinstance(строка, str) or "," not in строка:
        return None
    день_часть, _, время_часть = строка.partition(",")
    день = _ДНИ_НЕДЕЛИ.get(день_часть.strip().lower())
    if день is None:
        return None
    время_часть = время_часть.strip()
    if ":" not in время_часть:
        return None
    часы_текст, _, минуты_текст = время_часть.partition(":")
    try:
        часы, минуты = int(часы_текст), int(минуты_текст)
    except ValueError:
        return None
    if not (0 <= часы <= 23 and 0 <= минуты <= 59):
        return None
    return день, часы, минуты


def _дедлайн_для_файла(config: dict, путь_недели: Path) -> datetime | None:
    """Дедлайн такта Б как конкретный момент времени для КОНКРЕТНОГО файла
    недели — не «сегодня», а понедельник из имени этого файла плюс день
    недели и время из конфига. `None`, если посчитать нечем (нет поля,
    формат не разобрался, имя файла не подходит под шаблон недели)."""
    разобранное = _разобрать_дедлайн(config.get("дедлайн_такта_б", ""))
    if разобранное is None:
        return None
    совпадение = ИМЯ.match(путь_недели.name)
    if not совпадение:
        return None
    try:
        понедельник = date(int(совпадение[1]), int(совпадение[2]), int(совпадение[3]))
    except ValueError:
        return None
    день, часы, минуты = разобранное
    целевая_дата = понедельник + timedelta(days=день)
    return datetime.combine(целевая_дата, время_суток(часы, минуты))


def _файл_состояния_дедлайна(путь_недели: Path) -> Path:
    return путь_недели.parent / f"{путь_недели.stem}.дедлайн-обработан.json"


def _дедлайн_уже_обработан(путь_недели: Path) -> bool:
    файл = _файл_состояния_дедлайна(путь_недели)
    try:
        сырое = файл.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    try:
        данные = json.loads(сырое)
    except json.JSONDecodeError:
        return False
    return bool(isinstance(данные, dict) and данные.get("обработан"))


def _отметить_дедлайн_обработанным(путь_недели: Path) -> None:
    записать_атомарно(
        _файл_состояния_дедлайна(путь_недели),
        json.dumps({"обработан": True}, ensure_ascii=False),
    )


def _обработать_дедлайн(
    *,
    notes_root: Path,
    config: dict,
    токен: str,
    chat_id,
    blocks_dir: Path,
    собрать_план,
    отправить_сообщение_,
    now,
) -> None:
    """Проверяет дедлайн такта Б и обрабатывает его ровно один раз на файл.

    Сама сборка плана (`собрать_план`, по умолчанию настоящая `takt_b`) —
    своя логика планёрки, и её падение (в том числе «ни одной взятой темы»)
    ловится здесь широко: причин упасть у неё много, а правило одно и то
    же для всех — сказать человеку, а не промолчать, и не уронить процесс.
    """
    путь_недели = найти_файл_недели(notes_root)
    if путь_недели is None:
        return

    дедлайн = _дедлайн_для_файла(config, путь_недели)
    if дедлайн is None:
        return

    if now() < дедлайн:
        return

    if _дедлайн_уже_обработан(путь_недели):
        return

    try:
        путь_плана = собрать_план(config, notes_root, blocks_dir, date.today())
    except Exception as ошибка:  # noqa: BLE001 — см. докстринг: любая причина одинаково «сказать человеку»
        сообщение = (
            f"Наступил дедлайн такта Б, но план собрать не получилось: {ошибка}"
        )
    else:
        сообщение = f"Наступил дедлайн такта Б — план собран: {путь_плана}"

    try:
        отправить_сообщение_(токен, chat_id, сообщение)
    except ОшибкаБота as ошибка:
        # Не получилось сообщить человеку прямо сейчас — не повод пытаться
        # снова на каждой следующей итерации: файл-спутник всё равно
        # отметится ниже, а причину сбоя видно в логе.
        print(f"Не удалось отправить уведомление о дедлайне: {ошибка}", file=sys.stderr)

    _отметить_дедлайн_обработанным(путь_недели)


def _обработать_обновление(обновление: dict, токен: str, notes_root: Path, принять_нажатие_) -> None:
    """Одно обновление из пачки `getUpdates`. Не `callback_query` — молча
    пропускается, это штатный тип обновления (например, обычное сообщение),
    который приём нажатий не касается.

    `принять_нажатие` сама не бросает исключений наружу (см. её докстринг),
    но это внешний для этого модуля контракт — здесь он подстрахован ещё
    раз широким `except`, чтобы даже неожиданное падение внутри неё не
    уронило весь цикл опроса из-за одного нажатия."""
    callback = обновление.get("callback_query")
    if callback is None:
        return
    try:
        принять_нажатие_(токен, callback.get("id"), callback.get("data"), notes_root)
    except Exception as ошибка:  # noqa: BLE001 — см. докстринг функции
        print(f"Обработка нажатия упала, продолжаю: {ошибка}", file=sys.stderr)


def запустить_бота(
    токен: str,
    chat_id,
    notes_root: Path,
    config: dict,
    blocks_dir: Path,
    *,
    получить_обновления=получить_обновления,
    принять_нажатие=принять_нажатие,
    отправить_сообщение=отправить_сообщение,
    собрать_план=takt_b,
    now=datetime.now,
    sleep=time.sleep,
    макс_итераций: int | None = None,
) -> None:
    """Крутит long-polling, пока его не остановят.

    `макс_итераций=None` (по умолчанию, для прода) — цикл живёт вечно, до
    `Ctrl+C` или протухшего токена. Конечное число — для тестов: столько
    проходов `получить_обновления`, и функция возвращается сама, как будто
    процесс остановили.
    """
    смещение: int | None = None
    итерация = 0
    print("Бот запущен — слушаю Телеграм.")

    try:
        while макс_итераций is None or итерация < макс_итераций:
            итерация += 1
            try:
                обновления = получить_обновления(токен, смещение=смещение)
            except ОшибкаТокена as ошибка:
                print(f"Токен недействителен — бот остановлен: {ошибка}", file=sys.stderr)
                # Не штатная остановка (в отличие от Ctrl+C ниже) — дальше
                # опрашивать нечем, и супервизор автозапуска (часть 3) должен
                # это увидеть по коду выхода, а не по нулю «всё в порядке».
                raise SystemExit(1) from ошибка
            except ОшибкаБота as ошибка:
                # Сеть/Телеграм временно подвели — не выходим, ждём и
                # пробуем снова на следующем проходе того же цикла.
                print(f"Опрос Телеграма не удался, пробую ещё раз: {ошибка}", file=sys.stderr)
                sleep(_ЗАДЕРЖКА_ПОСЛЕ_ОШИБКИ_СЕТИ)
                обновления = []

            for обновление in обновления:
                _обработать_обновление(обновление, токен, notes_root, принять_нажатие)
                # Сдвигаем смещение даже если обработка выше упала — иначе
                # то же обновление придёт на следующем опросе снова и снова,
                # и весь цикл встанет намертво на одном сообщении.
                ид_обновления = обновление.get("update_id")
                if ид_обновления is not None:
                    смещение = ид_обновления + 1

            _обработать_дедлайн(
                notes_root=notes_root,
                config=config,
                токен=токен,
                chat_id=chat_id,
                blocks_dir=blocks_dir,
                собрать_план=собрать_план,
                отправить_сообщение_=отправить_сообщение,
                now=now,
            )
    except KeyboardInterrupt:
        print("Бот остановлен.")
        return
