"""Устойчивый идентификатор темы для callback_data кнопок.

Порядковый номер темы в файле для этого не годится: человек правит банк
тем между прогонами, темы сдвигаются местами или пропадают, и нажатие на
кнопку легло бы не на ту строку. Хеш от текста темы от перестановок
соседних строк не зависит — тема узнаётся по себе самой, а не по позиции.

Идентификатор нужен и задаче «отправка» (кладёт его в callback_data), и
задаче «приём нажатий» (по нему находит тему обратно в файле) — поэтому
живёт отдельным модулем, а не внутри одной из них: посчитанный в двух
местах хеш с шансом разойдётся при любой мелкой правке одной из копий,
и нажатия перестанут находить свою тему.
"""
import hashlib

# Ограничение Telegram на весь callback_data — 64 байта, а в нём кроме
# идентификатора темы ещё код состояния и разделитель (см.
# planerka/bot/отправка.py). 16 hex-символов — это 16 байт (чистый ASCII),
# заметно короче лимита самого по себе и практически не сталкивается
# (2**64 вариантов) для банка из десятков тем на неделе.
ДЛИНА_ИДЕНТИФИКАТОРА = 16


def идентификатор(тема: str) -> str:
    """Короткий устойчивый хеш от полного текста темы.

    Считается от текста как он есть, без обрезки под лимит отображения
    в сообщении: обрезанный текст перестаёт быть уникальным (у двух
    длинных тем с одинаковым началом обрежется одинаково), а задача
    «приём нажатий» ищет тему в файле по её полному тексту — идентификатор
    должен указывать именно на него.
    """
    if not isinstance(тема, str):
        raise TypeError(
            f"идентификатор темы считается от строки, получено {type(тема).__name__}"
        )
    хеш = hashlib.sha256(тема.encode("utf-8")).hexdigest()
    return хеш[:ДЛИНА_ИДЕНТИФИКАТОРА]
