# здесь, а не инлайновым python-скриптом в тексте скилла, ровно по одной
# причине: разбор .env должен быть один. Вторая, упрощённая копия разбора
# разойдётся с настоящей на первой же мелочи (кавычки вокруг значения,
# комментарий строкой), и человек получит токен вместе с кавычками.
КОМАНДЫ_НАСТРОЙКИ = ("проверить-бота", "узнать-chat-id", "защитить-env")
# «бот» — не такт: не читает и не пишет файл недели за один прогон, а живёт
# долгоживущим процессом (planerka/bot/процесс.py) и сам решает, когда
# позвать такт «план» — по дедлайну. Поэтому в ТАКТЫ не кладётся, а
# добавляется отдельной командой сюда же, в список допустимых значений CLI.
КОМАНДЫ = sorted(ТАКТЫ) + ["бот"] + list(КОМАНДЫ_НАСТРОЙКИ)

# Переменные окружения, из которых команда «бот» берёт токен и chat_id.
# Полноценная загрузка `.env` (файл, откуда эти переменные обычно и
# попадают в окружение) и автоматическое узнавание chat_id из первого
# сообщения человека боту — отдельная задача; здесь же нужен минимальный
# рабочий контракт, чтобы команда «бот» вообще могла запуститься.
_ПЕРЕМЕННАЯ_ТОКЕНА = "TELEGRAM_BOT_TOKEN"
_ПЕРЕМЕННАЯ_CHAT_ID = "TELEGRAM_CHAT_ID"

# Сколько секунд «узнать-chat-id» ждёт сообщение в длинном опросе. На другом
# конце живой человек в середине интервью: без потолка команда висела бы, а
# слишком короткий потолок не даёт дойти сообщению, которое человек только
# что отправил. Не хватило — интервью зовёт команду ещё раз, это дешевле,
# чем молча стоять минуту.
_ТАЙМАУТ_ОПРОСА_CHAT_ID = 10


def _умереть(сообщение: str) -> None:
    print(сообщение, file=sys.stderr)
    raise SystemExit(1)


def _прочесть_указатель() -> Path | None:
    try:
        строка = УКАЗАТЕЛЬ.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    return Path(строка).expanduser() if строка else None


def _записать_указатель(папка: Path) -> None:
    try:
        УКАЗАТЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
        УКАЗАТЕЛЬ.write_text(str(папка) + "\n", encoding="utf-8")
    except OSError:
        pass  # не смогли запомнить — не повод ронять прогон


def _прочесть_переменную_окружения(имя: str) -> str | None:
    значение = os.environ.get(имя)
    return значение.strip() if значение and значение.strip() else None


def _прочесть_env_файл(путь: Path) -> dict[str, str]:
    """Минимальный `.env`: строки `КЛЮЧ=значение`, пустые и начинающиеся с
    `#` — пропускаются, кавычки вокруг значения снимаются. Не парсер
    полного синтаксиса dotenv (экранирование, многострочные значения,
    `export`) — ровно тот минимум, которого достаточно для токена и
    chat_id; полноценная загрузка `.env` — отдельная задача."""
    результат: dict[str, str] = {}
    try:
        строки = путь.read_text(encoding="utf-8").splitlines()
    except OSError:
        return результат
    for строка in строки:
        голая = строка.strip()
        if not голая or голая.startswith("#") or "=" not in голая:
            continue
        ключ, _, значение = голая.partition("=")
        ключ = ключ.strip()
        значение = значение.strip().strip('"').strip("'")
        if ключ and значение:  # пустое значение — как будто ключа и не было
            результат[ключ] = значение
    return результат


def _разрешить_переменную_бота(notes_root: Path, имя: str) -> tuple[str | None, str]:
    """Значение переменной («TELEGRAM_BOT_TOKEN» и т. п.) и то, откуда оно
    взято — `"env_файл"` (`.env` в самой папке заметок) или `"окружение"`
    (переменная окружения процесса). Приоритет за `.env` папки заметок:
    окружение процесса — общее на весь шелл человека, и там может годами
    жить токен другого бота от другой задачи; `.env` папки заметок —
    прицельно для планёрки. `.env` папки заметок не даёт значения (файла
    нет, ключа нет, значение пустое) — падаем на переменную окружения."""
    из_файла = _прочесть_env_файл(notes_root / ".env").get(имя)
    if из_файла:
        return из_файла, "env_файл"
    return _прочесть_переменную_окружения(имя), "окружение"


# Что дописывается в `.gitignore` папки заметок и с каким пояснением.
# Строка ровно `.env` — так же, как её пишут руками: гит понимает и её, и
# `/.env`, но `.env` привычнее и читается однозначно.
_СТРОКА_ГИТИГНОРА = ".env"
_КОММЕНТАРИЙ_ГИТИГНОРА = "# токен телеграм-бота планёрки — в гит не отдавать"
# Записи, при которых `.env` уже спрятан и дописывать нечего.
_УЖЕ_ПРЯЧУТ_ENV = {".env", "/.env", ".env*", "*.env", "**/.env"}


def _папка_под_гитом(папка: Path) -> bool:
    """Лежит ли папка заметок внутри рабочего дерева гита.

    `.git` бывает и каталогом (обычный репозиторий), и файлом (worktree,
    сабмодуль) — проверяется существование, не тип. Смотрим вверх по
    родителям: волт целиком может быть подпапкой большого репозитория.
    """
    for кандидат in (папка, *папка.parents):
        if (кандидат / ".git").exists():
            return True
    return False


def _env_уже_спрятан(гитигнор: Path) -> bool:
    try:
        строки = гитигнор.read_text(encoding="utf-8").splitlines()
    except OSError:
        return False
    return any(строка.strip() in _УЖЕ_ПРЯЧУТ_ENV for строка in строки)


def _спрятать_env_от_гита(папка: Path) -> str | None:
    """Дописывает `.env` в `.gitignore` ПАПКИ ЗАМЕТОК, заводя файл при нужде.

    Токен живёт в `.env` папки заметок, а `.gitignore` со строкой `.env`
    лежал только в репозитории самого плагина — другое дерево, к папке
    заметок отношения не имеющее. У человека папка заметок — обычно волт
    под гитом, который коммитится сам, и первый же прогон с настроенным
    ботом положил бы боевой токен в историю.

    Возвращает строку о том, что сделано, или `None`, если делать было
    нечего (правило уже есть). Чужой `.gitignore` не переписывается —
    только дописывается в конец.
    """
    гитигнор = папка / ".gitignore"
    if _env_уже_спрятан(гитигнор):
        return None
    прежнее = ""
    if гитигнор.is_file():
        try:
            прежнее = гитигнор.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            прежнее = ""
    # Чужой файл мог кончаться без перевода строки — иначе наше правило
    # склеится с последней чужой строкой и не сработает ни одно из двух.
    отступ = "" if (not прежнее or прежнее.endswith("\n")) else "\n"
    try:
        with гитигнор.open("a", encoding="utf-8") as файл:
            файл.write(f"{отступ}{_КОММЕНТАРИЙ_ГИТИГНОРА}\n{_СТРОКА_ГИТИГНОРА}\n")
    except OSError as ошибка:
        return (f"Внимание: не вышло дописать «{_СТРОКА_ГИТИГНОРА}» в {гитигнор} "
                f"({ошибка}). Допишите строку сами — иначе токен бота уедет в гит.")
    return (f"В {гитигнор} дописана строка «{_СТРОКА_ГИТИГНОРА}» — "
            "токен бота в гит не попадёт.")


def _прикрыть_env_попутно(папка: Path) -> None:
    """Сеть безопасности на каждый запуск: интервью ведёт живая модель, и шаг
    «спрятать .env» она может пропустить. Молчит, когда прятать нечего
    (бота не настраивали) или когда правило уже стоит, — лишний файл в чужой
    папке не заводится, и в еженедельный вывод ничего не добавляется."""
    if not (папка / ".env").is_file():
        return
    сказать = _спрятать_env_от_гита(папка)
    if сказать:
        print(сказать)


def _защитить_env(папка: Path) -> None:
    """Команда «защитить-env»: прячет `.env` папки заметок от гита и говорит
    об этом вслух — интервью зовёт её до того, как запишет туда токен."""
    сказанное = _спрятать_env_от_гита(папка)
    print(сказанное if сказанное
          else f"В {папка / '.gitignore'} строка «{_СТРОКА_ГИТИГНОРА}» уже есть — "
               "ничего не меняю.")
    if _папка_под_гитом(папка):
        print("Папка заметок под гитом: проверьте `git status` — .env в списке "
              "изменений быть не должно.")
    else:
        print("Папка заметок не под контролем версий — прятать пока не от кого, "
              "правило записано на будущее. Файл всё равно секретный: у кого "
              "токен, тот и есть ваш бот.")


def _запустить_команду_бота(конфиг: dict, notes_root: Path, *, обойти_блокировку: bool = False) -> None:
    """Команда «бот»: своя обработка, не идёт через ТАКТЫ и не завершается
    сама (см. planerka/bot/процесс.py) — этот вызов возвращается только
    когда процесс сам решил остановиться (Ctrl+C, протухший токен)."""
    токен, _ = _разрешить_переменную_бота(notes_root, _ПЕРЕМЕННАЯ_ТОКЕНА)
    if not токен:
        _умереть(
            f"Не найден токен бота: задайте переменную окружения {_ПЕРЕМЕННАЯ_ТОКЕНА} "
            "(или положите её в .env папки заметок) и запустите команду ещё раз."
        )
    chat_id, _ = _разрешить_переменную_бота(notes_root, _ПЕРЕМЕННАЯ_CHAT_ID)
    if not chat_id:
        _умереть(
            f"Не известен chat_id получателя: задайте переменную окружения "
            f"{_ПЕРЕМЕННАЯ_CHAT_ID} (или положите её в .env папки заметок) "
            "и запустите команду ещё раз."
        )
    запустить_бота(токен, chat_id, notes_root, конфиг, КОРЕНЬ / "blocks",
                    обойти_блокировку=обойти_блокировку)


def _токен_для_команды_настройки(папка: Path) -> str:
    токен, _ = _разрешить_переменную_бота(папка, _ПЕРЕМЕННАЯ_ТОКЕНА)
    if not токен:
        _умереть(
            f"Не найден токен бота. Положите строку {_ПЕРЕМЕННАЯ_ТОКЕНА}=... "
            f"в файл .env папки {папка} и запустите команду ещё раз."
        )
    return токен


def _проверить_бота(папка: Path) -> None:
    """Команда «проверить-бота»: getMe и имя бота с собачкой.

    Имя — единственный способ поймать чужой, но исправный токен: сам по себе
    он ошибки не даст, и банк тем молча уедет не туда. Сам токен не печатаем
    ни при каком исходе: у кого он есть, тот и есть бот."""
    токен = _токен_для_команды_настройки(папка)
    try:
        имя = проверить_токен(токен)
    except ОшибкаБота as ошибка:
        _умереть(f"Токен не проверен: {ошибка}")
    print(f"Токен принят, это бот {имя}")


def _узнать_chat_id(папка: Path) -> None:
    """Команда «узнать-chat-id»: айди из первого сообщения человека боту.

    Спрашивать chat_id у человека нельзя — своего айди он про себя не знает.
    Пусто — не ошибка и не повод для ненулевого кода выхода: сообщение могло
    не успеть дойти за время опроса, и правильный ход тут — позвать команду
    ещё раз, а не считать настройку сломанной."""
    токен = _токен_для_команды_настройки(папка)
    try:
        обновления = получить_обновления(токен, таймаут=_ТАЙМАУТ_ОПРОСА_CHAT_ID)
    except ОшибкаБота as ошибка:
        _умереть(f"Не вышло забрать сообщения: {ошибка}")

    найдено: dict = {}
    for обновление in обновления:
        if not isinstance(обновление, dict):
            continue
        сообщение = обновление.get("message") or обновление.get("edited_message") or {}
        чат = сообщение.get("chat") if isinstance(сообщение, dict) else None
        if not isinstance(чат, dict) or чат.get("id") is None:
            continue
        # setdefault, а не присваивание: одно и то же имя от повторных
        # сообщений не должно давать дубль строки в выводе.
        найдено.setdefault(чат["id"], чат.get("title") or чат.get("first_name") or "")

    if not найдено:
        print("Сообщений пока нет. Попросите написать боту ещё раз и повторите команду.")
        return
    for айди, кто in найдено.items():
        строка = f"{_ПЕРЕМЕННАЯ_CHAT_ID}={айди}"
        print(f"{строка}  — {кто}" if кто else строка)


def main(аргументы: list[str] | None = None) -> None:
    парсер = argparse.ArgumentParser(
        prog="run.py", description="Планёрка: такт «темы», такт «план» или команда «бот»")
    парсер.add_argument("такт", choices=КОМАНДЫ,
                        help="темы — собрать банк тем, план — собрать план недели, "
                             "бот — запустить телеграм-бота (не завершается сам), "
                             "проверить-бота — назвать бота по токену из .env, "
                             "узнать-chat-id — взять chat_id из первого сообщения боту, "
                             "защитить-env — спрятать .env папки заметок от гита")
    парсер.add_argument("--папка", help="папка заметок, где лежит конфиг.json")
    парсер.add_argument(
        "--пересобрать", action="store_true",
        help="такт «темы»: собрать банк заново поверх файла недели, "
             "в котором уже есть ваша разметка (прежний файл сохранится копией)")
    парсер.add_argument(
        "--обойти-блокировку", action="store_true",
        help="команда «бот»: захватить лок безусловно, не проверяя чужой pid — "
             "для случая, когда предыдущий процесс завис, а автоматика "
             "(устаревание лока по времени) его не признаёт")
    разобрано = парсер.parse_args(аргументы)

    if разобрано.такт in КОМАНДЫ_НАСТРОЙКИ and (разобрано.пересобрать
                                                or разобрано.обойти_блокировку):
        _умереть(f"Команда «{разобрано.такт}» не принимает флагов тактов и бота: "
                 "она только смотрит .env и спрашивает Телеграм.")

    if разобрано.пересобрать and разобрано.такт != "темы":
        _умереть("Флаг --пересобрать работает только с тактом «темы»: "
                 "такт «план» файл недели и так не переписывает.")

    if разобрано.обойти_блокировку and разобрано.такт != "бот":
        _умереть("Флаг --обойти-блокировку работает только с командой «бот»: "
                 "такты «темы» и «план» никакой блокировки не берут.")

    названа = bool(разобрано.папка)
    папка = Path(разобрано.папка).expanduser() if названа else _прочесть_указатель()
    if папка is None:
        _умереть(
            "Не знаю, где папка заметок: указателя "
            f"{УКАЗАТЕЛЬ} нет. Запустите ещё раз и передайте путь: "
            "--папка /путь/к/заметкам")

    # Команды настройки разбираются здесь, до конфига: интервью зовёт их в
    # блоке 2, а конфиг.json появляется только в самом конце интервью.
    # Указатель ~/.planerka/папка.txt они тоже не пишут — у человека может
    # быть вторая папка заметок, и молча переключать его на сегодняшнюю
    # диагностическая команда права не имеет.
    if разобрано.такт in КОМАНДЫ_НАСТРОЙКИ:
        if not папка.is_dir():
            _умереть(f"Папка заметок не найдена: {папка}")
        if разобрано.такт != "защитить-env":
            _прикрыть_env_попутно(папка)
        {"проверить-бота": _проверить_бота,
         "узнать-chat-id": _узнать_chat_id,
         "защитить-env": _защитить_env}[разобрано.такт](папка)
        return

    конфиг_файл = папка / "конфиг.json"
    if not конфиг_файл.is_file():
        _умереть(f"В папке {папка} нет конфиг.json — планёрка там ещё не настроена")

    try:
        конфиг = json.loads(конфиг_файл.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as ошибка:
        _умереть(f"Не читается {конфиг_файл}: {ошибка}")

    if not конфиг.get("модель"):
        _умереть(f"В {конфиг_файл} нет поля «модель» — допишите его или перенастройте планёрку")

    notes_root = Path(конфиг.get("папка_заметок") or папка).expanduser()
    if not notes_root.is_dir():
        _умереть(f"Папка заметок из конфига не найдена: {notes_root}")

    _прикрыть_env_попутно(notes_root)

    if названа:
        _записать_указатель(папка)

    if разобрано.такт == "бот":
        _запустить_команду_бота(конфиг, notes_root, обойти_блокировку=разобрано.обойти_блокировку)
        return

    доп = {"пересобрать": True} if разобрано.пересобрать else {}
    if разобрано.такт == "темы":
        # Такт «темы» сам отправляет свежий банк в телеграм, если бот
        # настроен (см. planerka/runner/takt_a.py) — «план» этого не
        # делает, лишние kwargs он бы не принял. Приоритет источника —
        # .env папки заметок, окружение процесса — запасной путь (см.
        # _разрешить_переменную_бота); такт А сам скажет человеку, если
        # токен взят из окружения, а не из .env, — на этот случай в доп
        # уходит и флаг источника.
        бот_токен, источник_токена = _разрешить_переменную_бота(notes_root, _ПЕРЕМЕННАЯ_ТОКЕНА)
        бот_chat_id, _ = _разрешить_переменную_бота(notes_root, _ПЕРЕМЕННАЯ_CHAT_ID)
        if бот_токен and бот_chat_id:
            доп["бот_токен"] = бот_токен
            доп["бот_chat_id"] = бот_chat_id
            доп["бот_токен_из_окружения"] = источник_токена == "окружение"
    try:
        путь = ТАКТЫ[разобрано.такт](
            конфиг, notes_root, КОРЕНЬ / "blocks", date.today(), **доп)
    except РаботаЧеловека as отказ:
        # Не авария, а отказ трогать чужую работу: человеку нужна строка,
        # которую можно прочесть и понять, а не трейсбек.
        _умереть(str(отказ))
    print(f"Готово. Файл недели: {путь}")


if __name__ == "__main__":
    main()
