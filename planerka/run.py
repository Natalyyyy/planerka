#!/usr/bin/env python3
"""Точка входа планёрки: один такт за запуск.

    python3 run.py темы  --папка /путь/к/заметкам
    python3 run.py план

Файл лежит в корне плагина, и путь к нему скилл подставляет сам —
`${CLAUDE_PLUGIN_ROOT}/run.py`. Пакет здесь не импортируется по имени:
после установки каталог плагина лежит в кэше Claude Code, родителя пакета на
`sys.path` нет, и `import planerka` даёт ModuleNotFoundError. Поэтому в путь
кладётся собственный каталог, а модули берутся из него.

Где лежит папка заметок, знает либо аргумент `--папка`, либо указатель
`~/.planerka/папка.txt`, который пишется при первом запуске с аргументом.
Круг «конфиг лежит в папке заметок, а путь к папке заметок лежит в конфиге»
разрывается именно тут: угадывать путь нечем и незачем.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import date
from pathlib import Path

# Проверка версии стоит до импорта раннера намеренно. Код планёрки написан на
# синтаксисе 3.10 (`date | None`), а `python3` на маке из коробки — 3.9: без
# этой проверки человек получает TypeError из середины чужого файла и не
# понимает ни при чём тут он, ни что делать дальше.
if sys.version_info < (3, 10):
    сейчас = ".".join(str(ч) for ч in sys.version_info[:3])
    print(f"Планёрке нужен Python 3.10 или новее, а этот — {сейчас} ({sys.executable}). "
          "Поставьте свежий Python и запустите команду им.", file=sys.stderr)
    raise SystemExit(1)

КОРЕНЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(КОРЕНЬ))

from runner.takt_a import РаботаЧеловека, takt_a  # noqa: E402
from runner.takt_b import takt_b  # noqa: E402
from bot.процесс import запустить_бота  # noqa: E402

УКАЗАТЕЛЬ = Path.home() / ".planerka" / "папка.txt"
ТАКТЫ = {"темы": takt_a, "план": takt_b}
# «бот» — не такт: не читает и не пишет файл недели за один прогон, а живёт
# долгоживущим процессом (planerka/bot/процесс.py) и сам решает, когда
# позвать такт «план» — по дедлайну. Поэтому в ТАКТЫ не кладётся, а
# добавляется отдельной командой сюда же, в список допустимых значений CLI.
КОМАНДЫ = sorted(ТАКТЫ) + ["бот"]

# Переменные окружения, из которых команда «бот» берёт токен и chat_id.
# Полноценная загрузка `.env` (файл, откуда эти переменные обычно и
# попадают в окружение) и автоматическое узнавание chat_id из первого
# сообщения человека боту — отдельная задача; здесь же нужен минимальный
# рабочий контракт, чтобы команда «бот» вообще могла запуститься.
_ПЕРЕМЕННАЯ_ТОКЕНА = "TELEGRAM_BOT_TOKEN"
_ПЕРЕМЕННАЯ_CHAT_ID = "TELEGRAM_CHAT_ID"


def _умереть(сообщение: str) -> None:
    print(сообщение, file=sys.stderr)
    raise SystemExit(1)


def _прочесть_указатель() -> Path | None:
    try:
        строка = УКАЗАТЕЛЬ.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    return Path(строка).expanduser() if строка else None


def _записать_указатель(папка: Path) -> None:
    try:
        УКАЗАТЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
        УКАЗАТЕЛЬ.write_text(str(папка) + "\n", encoding="utf-8")
    except OSError:
        pass  # не смогли запомнить — не повод ронять прогон


def _прочесть_переменную_окружения(имя: str) -> str | None:
    значение = os.environ.get(имя)
    return значение.strip() if значение and значение.strip() else None


def _запустить_команду_бота(конфиг: dict, notes_root: Path) -> None:
    """Команда «бот»: своя обработка, не идёт через ТАКТЫ и не завершается
    сама (см. planerka/bot/процесс.py) — этот вызов возвращается только
    когда процесс сам решил остановиться (Ctrl+C, протухший токен)."""
    токен = _прочесть_переменную_окружения(_ПЕРЕМЕННАЯ_ТОКЕНА)
    if not токен:
        _умереть(
            f"Не найден токен бота: задайте переменную окружения {_ПЕРЕМЕННАЯ_ТОКЕНА} "
            "(обычно через .env) и запустите команду ещё раз."
        )
    chat_id = _прочесть_переменную_окружения(_ПЕРЕМЕННАЯ_CHAT_ID)
    if not chat_id:
        _умереть(
            f"Не известен chat_id получателя: задайте переменную окружения "
            f"{_ПЕРЕМЕННАЯ_CHAT_ID} и запустите команду ещё раз."
        )
    запустить_бота(токен, chat_id, notes_root, конфиг, КОРЕНЬ / "blocks")


def main(аргументы: list[str] | None = None) -> None:
    парсер = argparse.ArgumentParser(
        prog="run.py", description="Планёрка: такт «темы», такт «план» или команда «бот»")
    парсер.add_argument("такт", choices=КОМАНДЫ,
                        help="темы — собрать банк тем, план — собрать план недели, "
                             "бот — запустить телеграм-бота (не завершается сам)")
    парсер.add_argument("--папка", help="папка заметок, где лежит конфиг.json")
    парсер.add_argument(
        "--пересобрать", action="store_true",
        help="такт «темы»: собрать банк заново поверх файла недели, "
             "в котором уже есть ваша разметка (прежний файл сохранится копией)")
    разобрано = парсер.parse_args(аргументы)

    if разобрано.пересобрать and разобрано.такт != "темы":
        _умереть("Флаг --пересобрать работает только с тактом «темы»: "
                 "такт «план» файл недели и так не переписывает.")

    названа = bool(разобрано.папка)
    папка = Path(разобрано.папка).expanduser() if названа else _прочесть_указатель()
    if папка is None:
        _умереть(
            "Не знаю, где папка заметок: указателя "
            f"{УКАЗАТЕЛЬ} нет. Запустите ещё раз и передайте путь: "
            "--папка /путь/к/заметкам")

    конфиг_файл = папка / "конфиг.json"
    if not конфиг_файл.is_file():
        _умереть(f"В папке {папка} нет конфиг.json — планёрка там ещё не настроена")

    try:
        конфиг = json.loads(конфиг_файл.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as ошибка:
        _умереть(f"Не читается {конфиг_файл}: {ошибка}")

    if not конфиг.get("модель"):
        _умереть(f"В {конфиг_файл} нет поля «модель» — допишите его или перенастройте планёрку")

    notes_root = Path(конфиг.get("папка_заметок") or папка).expanduser()
    if not notes_root.is_dir():
        _умереть(f"Папка заметок из конфига не найдена: {notes_root}")

    if названа:
        _записать_указатель(папка)

    if разобрано.такт == "бот":
        _запустить_команду_бота(конфиг, notes_root)
        return

    доп = {"пересобрать": True} if разобрано.пересобрать else {}
    if разобрано.такт == "темы":
        # Такт «темы» сам отправляет свежий банк в телеграм, если бот
        # настроен (см. planerka/runner/takt_a.py) — «план» этого не
        # делает, лишние kwargs он бы не принял.
        бот_токен = _прочесть_переменную_окружения(_ПЕРЕМЕННАЯ_ТОКЕНА)
        бот_chat_id = _прочесть_переменную_окружения(_ПЕРЕМЕННАЯ_CHAT_ID)
        if бот_токен and бот_chat_id:
            доп["бот_токен"] = бот_токен
            доп["бот_chat_id"] = бот_chat_id
    try:
        путь = ТАКТЫ[разобрано.такт](
            конфиг, notes_root, КОРЕНЬ / "blocks", date.today(), **доп)
    except РаботаЧеловека as отказ:
        # Не авария, а отказ трогать чужую работу: человеку нужна строка,
        # которую можно прочесть и понять, а не трейсбек.
        _умереть(str(отказ))
    print(f"Готово. Файл недели: {путь}")


if __name__ == "__main__":
    main()
