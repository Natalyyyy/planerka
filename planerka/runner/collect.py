"""Сбор контекста из подключённых источников.

Пустой источник остаётся пустой строкой; недоступный настроенный источник
сопровождается предупреждением, чтобы его не путали с пустым содержимым.
"""
import os
import re
import warnings
from datetime import date, timedelta
from pathlib import Path

ДАТА = re.compile(r"(\d{4})-(\d{2})-(\d{2})")


def _дата_из_имени(имя: str) -> date | None:
    совпадения = list(ДАТА.finditer(имя))
    if not совпадения:
        return None
    м = совпадения[-1]  # берём последнее совпадение
    try:
        return date(int(м[1]), int(м[2]), int(м[3]))
    except ValueError:
        return None


def _кусок(файл: Path, граница: date | None) -> str | None:
    """Один файл в виде куска промпта. None — файл не подошёл или не прочёлся."""
    д = _дата_из_имени(файл.name)
    if граница and д and д < граница:
        return None
    try:
        return f"### {файл.name}\n{файл.read_text(encoding='utf-8')}"
    except (UnicodeDecodeError, OSError):
        return None


def collect(config: dict, notes_root: Path, today: date) -> dict[str, str]:
    собрано: dict[str, str] = {}
    for источник in config.get("источники", []):
        путь = notes_root / источник["путь"]
        окно = источник.get("окно_дней")
        граница = today - timedelta(days=окно) if окно else None

        # Источник — это либо папка, либо один файл. Журнал сделанного живёт
        # одним файлом в папке заметок, и требование «только директория»
        # молча отдавало по нему пустоту: тихая пустота хуже ошибки, потому
        # что выглядит как «на этой неделе ничего не было».
        #
        # Расширение при этом фильтруется по-разному, и это намеренно.
        # Прямой путь на файл человек назвал сам в интервью — значит имел в
        # виду именно его, каким бы ни было расширение (выгрузка .csv, лог
        # .txt). В папке же лежит что попало, и брать оттуда всё подряд —
        # это тащить в промпт мусор, поэтому там только *.md. Нечитаемое
        # как текст (PDF, xlsx) в обеих ветках даёт пустоту, а не падение.
        if путь.is_file():
            дата = _дата_из_имени(путь.name)
            if граница and дата and дата < граница:
                собрано[источник["имя"]] = ""
                continue
            кусок = _кусок(путь, граница)
            if кусок is None:
                warnings.warn(
                    f"Источник «{источник['имя']}» не прочитан: {путь}",
                    UserWarning,
                    stacklevel=2,
                )
            собрано[источник["имя"]] = кусок or ""
            continue

        if not путь.is_dir():
            warnings.warn(
                f"Источник «{источник['имя']}» не найден: {путь}",
                UserWarning,
                stacklevel=2,
            )
            собрано[источник["имя"]] = ""
            continue

        куски = []

        def сообщить_ошибку_каталога(ошибка: OSError) -> None:
            warnings.warn(
                f"Источник «{источник['имя']}»: не удалось прочесть каталог "
                f"{ошибка.filename or путь}: {ошибка}",
                UserWarning,
                stacklevel=2,
            )

        # Path.rglob пропускает OSError при обходе дерева, поэтому недоступная
        # подпапка выглядела как обычная пустота. os.walk передаёт ошибки в
        # onerror; отдельные файлы читаются по одному, так что ошибка одного
        # файла не мешает добавить остальные.
        for каталог, подпапки, имена in os.walk(путь, onerror=сообщить_ошибку_каталога):
            подпапки.sort()
            for имя in sorted(имена):
                if not имя.endswith(".md"):
                    continue
                файл = Path(каталог) / имя
                дата = _дата_из_имени(файл.name)
                if граница and дата and дата < граница:
                    continue
                кусок = _кусок(файл, граница)
                if кусок is None:
                    warnings.warn(
                        f"Источник «{источник['имя']}»: файл не прочитан: {файл}",
                        UserWarning,
                        stacklevel=2,
                    )
                else:
                    куски.append(кусок)
        собрано[источник["имя"]] = "\n\n".join(куски)
    return собрано
