"""Личный контекст человека: язык, частота площадок, файл о голосе.

Блок 4 интервью («о чём я пишу, какие темы мои, на что не соглашусь»)
собирается дольше всех остальных вместе взятых. Пока этот файл никто не
читал, планёрка выдавала ровно тот генерик, против которого блок заведён.
Здесь он превращается в раздел промпта — одинаково для обоих тактов.

Файла нет, он пуст или не читается — работаем без него и не падаем: это
нормальное состояние сразу после установки.
"""
from pathlib import Path

ФАЙЛ_ГОЛОСА = "о-чём-я-пишу.md"


def _прочесть(путь: Path) -> str:
    if not путь.is_file():
        return ""
    try:
        return путь.read_text(encoding="utf-8").strip()
    except (UnicodeDecodeError, OSError):
        return ""


def личный_контекст(config: dict, notes_root: Path) -> str:
    куски: list[str] = []

    # Конфиг человек правит руками, и поле приезжает в любом виде. Раздел,
    # который не собрать из того, что пришло, просто не выводится: молчание
    # честнее падения посреди недельного прогона.
    сырой_язык = config.get("язык")
    язык = сырой_язык.strip() if isinstance(сырой_язык, str) else ""
    if язык:
        куски.append(
            f"## Язык\n\nВесь вывод — на языке: {язык}. Формулировки тем, вопросы "
            "в «Додумать» и план по дням тоже на нём. Названия разделов оставь "
            "как в инструкции выше."
        )

    частота = config.get("частота_площадок")
    if isinstance(частота, dict) and частота:
        строки = "\n".join(f"- {площадка}: {как}" for площадка, как in частота.items())
        куски.append(
            "## Частота по площадкам\n\n"
            "Человек сам назвал это в интервью — не переспрашивай в «Додумать» "
            "и не назначай другую:\n\n" + строки
        )

    голос = _прочесть(notes_root / ФАЙЛ_ГОЛОСА)
    if голос:
        куски.append(
            "## О чём я пишу\n\n"
            "Ответы человека про его территории и голос. Тема, которая идёт "
            "против этого раздела, в банк не попадает; закрытые темы не "
            "предлагаются заново.\n\n" + голос
        )

    return "\n\n".join(куски)
