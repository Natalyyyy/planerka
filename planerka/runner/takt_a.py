class РаботаЧеловека(RuntimeError):
    """Файл недели занят работой человека — переписывать его молча нельзя.

    Отдельный класс, а не голый RuntimeError, чтобы точка входа могла
    показать это человеку сообщением, а не аварией: это не поломка прогона,
    а отказ от разрушительного действия.
    """


def начало_недели(день: date) -> date:
    return день - timedelta(days=день.weekday())


def _черновик(путь: Path) -> Path:
    """Куда лечь новому банку, если файл недели трогать нельзя.

    Имя нарочно не подходит под шаблон файла недели: такт Б черновик не
    увидит и в оборот не возьмёт. Человек переносит из него руками то, что
    захочет, или не переносит ничего.
    """
    return путь.with_name(f"{путь.stem} (новый банк){путь.suffix}")


def _сохранить_копию(путь: Path) -> Path:
    """Копия файла недели в «недели/архив» перед тем, как его переписать.

    Архив лежит подпапкой: `файлы_недель` смотрит только в саму «недели»,
    и копии в поиск файла недели не попадают.
    """
    архив = путь.parent / "архив"
    архив.mkdir(parents=True, exist_ok=True)
    копия = архив / путь.name
    номер = 2
    while копия.exists():
        копия = архив / f"{путь.stem} ({номер}){путь.suffix}"
        номер += 1
    shutil.copy2(путь, копия)
    return копия


def _занят_человеком(путь: Path) -> dict[str, list[str]] | None:
    """Работа человека в файле недели, если она там есть."""
    if not путь.is_file():
        return None
    try:
        текст = путь.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        # Прочесть не смогли — тем более не переписываем: что в файле,
        # неизвестно, а неизвестное может быть неделей решений.
        return {"отметки": [], "разделы": []}
    найдено = работа_человека(текст)
    return найдено if (найдено["отметки"] or найдено["разделы"]) else None


def _текст_отказа(путь: Path, найдено: dict[str, list[str]], черновик: Path) -> str:
    что = []
    if найдено["отметки"]:
        что.append(f"проставленных отметок: {len(найдено['отметки'])}")
    if найдено["разделы"]:
        что.append("свои разделы: " + ", ".join(f"«{р}»" for р in найдено["разделы"]))
    if not что:
        что.append("файл не читается")
    return (
        f"Внимание: файл недели «{путь.name}» не тронут — в нём ваша работа "
        f"({'; '.join(что)}). Новый банк тем лежит рядом черновиком: "
        f"{черновик} — перенесите из него в свой файл то, что нужно. "
        "Если банк нужно собрать заново поверх, запустите такт «темы» "
        "с флагом --пересобрать: прежний файл сохранится копией "
        "в «недели/архив»."
    )


def _сказать_про_прошлую_неделю(notes_root: Path, новый: Path,
                                копия: Path | None = None) -> None:
    """Предупредить, что нерешённые темы прошлого файла никуда не поехали.

    Такт А пишет банк с нуля и прошлую неделю не переносит. Пока он об этом
    молчал, неделя размеченных решений просто оставалась мёртвой, и человек
    узнавал об этом только сам, случайно, открыв старый файл.

    Отдельная ветка — когда прошлый файл и новый один и тот же: повторный
    прогон той же недели. Раньше именно тут функция молчала, то есть ровно
    в самом опасном случае: темы не «оставались в прошлом файле», а
    исчезали вместе с ним.
    """
    прошлый = найти_файл_недели(notes_root)
    if прошлый is None:
        return
    осталось = неразобранное(прошлый)
    if not осталось:
        return
    сколько = ", ".join(
        f"{'не отмечено' if вид == 'не_решено' else 'отложено'}: {len(темы)}"
        for вид, темы in осталось.items()
    )
    примеры = "; ".join([т for темы in осталось.values() for т in темы][:3])
    if прошлый == новый:
        # Путь копии печатается строкой выше, целиком; здесь он не повторяется,
        # чтобы длинный путь не вытеснил из вида сами нерешённые темы.
        где = " Прежний вариант файла сохранён копией (путь строкой выше)." if копия else ""
        print(
            f"Внимание: файл «{новый.name}» переписан новым банком, а в прежнем "
            f"оставались нерешённые темы ({сколько}) — в новый банк они не "
            f"перенесены.{где} Например: {примеры}"
        )
        return
    print(
        f"Внимание: в прошлом файле «{прошлый.name}» остались нерешённые темы "
        f"({сколько}). Они никуда не переносятся — решите их там или "
        f"перенесите в новый файл руками. Например: {примеры}"
    )


def takt_a(config: dict, notes_root: Path, blocks_dir: Path, today: date,
           зов=run_claude, пересобрать: bool = False,
           бот_токен: str | None = None, бот_chat_id=None,
           бот_токен_из_окружения: bool = False) -> Path:
    промпт = assemble(config, blocks_dir)
    личное = личный_контекст(config, notes_root)
    if личное:
        промпт += "\n\n" + личное
    контекст = collect(config, notes_root, today)
    for имя, текст in контекст.items():
        промпт += f"\n\n## Источник: {имя}\n{текст}" if текст else f"\n\n## Источник: {имя}\n(пусто)"

    ответ = зов(промпт, model=config["модель"])
    if not ответ or not ответ.strip():
        raise RuntimeError("пустой ответ модели — файл недели не тронут")

    каталог = notes_root / "недели"
    каталог.mkdir(parents=True, exist_ok=True)
    путь = каталог / f"неделя – {начало_недели(today)}.md"
    содержимое = ответ.strip() + "\n"

    # Файл недели — работа человека: он неделю ставит в нём отметки и пишет
    # свои разделы. Прогон такта А не может стоить ему этой работы, а сам
    # скилл предлагает прогон перезапускать. Поэтому файл с отметками или
    # чужими разделами переписывается только по явной просьбе.
    найдено = _занят_человеком(путь)
    if найдено is not None and not пересобрать:
        черновик = _черновик(путь)
        черновик.write_text(содержимое, encoding="utf-8")
        raise РаботаЧеловека(_текст_отказа(путь, найдено, черновик))

    копия = _сохранить_копию(путь) if путь.is_file() else None
    if копия is not None:
        print(f"Прежний файл недели сохранён копией: {копия}")

    _сказать_про_прошлую_неделю(notes_root, путь, копия)
    записать_атомарно(путь, содержимое)

    # Бот не настроен (нет токена или chat_id) — молчим и ничего не шлём,
    # такт А работает ровно так же, как до появления бота. Настроен, но
    # отправка упала (сеть, протухший токен, Телеграм лёг) — файл недели
    # уже записан и не теряется; человеку нужно узнать, что кнопки в
    # телеграме не появились, а не тихо ждать сообщения, которое не придёт.
    if бот_токен and бот_chat_id:
        if бот_токен_из_окружения:
            # Токен взят из переменной окружения процесса, не из .env
            # папки заметок (см. run.py, _разрешить_переменную_бота) — в
            # шелле человека может годами жить токен ДРУГОГО бота от
            # другой задачи, и банк тем уйдёт не туда молча. Называем
            # бота по имени (проверить_токен зовёт getMe), чтобы человек
            # увидел, куда именно отправляется, ДО того как решит, что
            # что-то пошло не так.
            try:
                имя_бота = проверить_токен(бот_токен)
                print(
                    f"Токен бота взят из переменной окружения TELEGRAM_BOT_TOKEN, "
                    f"не из .env папки заметок — отправляю банк тем боту {имя_бота}. "
                    "Не тот бот — положите правильный токен в .env папки заметок."
                )
            except ОшибкаБота:
                pass  # не смогли даже узнать имя бота — саму отправку это не должно останавливать
        try:
            итог = отправить_банк_тем(бот_токен, бот_chat_id, notes_root)
        except ОшибкаБота as ошибка:
            ушло = getattr(ошибка, ПОЛЕ_УШЕДШИХ, [])
            if ушло:
                # Часть тем уже в чате — сказать «не ушёл» значит соврать
                # человеку про то, что у него на экране телефона.
                print(
                    f"Банк тем собран ({путь.name}), но в телеграм ушёл не "
                    f"целиком: {len(ушло)} тем из {getattr(ошибка, ПОЛЕ_ВСЕГО, len(ушло))}. "
                    f"Оборвалось на этом: {ошибка} — запустите такт «темы» "
                    "ещё раз (уже отправленные темы не продублируются) или "
                    "отметьте остальные прямо в файле недели."
                )
            else:
                print(
                    f"Банк тем собран ({путь.name}), но в телеграм не ушёл: {ошибка} "
                    "— откройте файл недели и отметьте темы вручную."
                )
        else:
            # Скиллу еженедельного прогона нужно, что пересказать человеку:
            # молчание на успехе означало, что про двадцать сообщений с
            # кнопками он узнаёт, только открыв телеграм.
            if итог["отправлено"]:
                хвост = (f" (ещё {len(итог['пропущено'])} отправлялись раньше и "
                         "повторно не ушли)") if итог["пропущено"] else ""
                print(
                    f"В телеграм ушло тем с кнопками: {len(итог['отправлено'])} "
                    f"из {итог['всего']}{хвост}. Решения можно принимать "
                    "кнопками в телеграме или галочками в файле недели."
                )
            elif итог["пропущено"]:
                print(
                    f"Все темы банка ({len(итог['пропущено'])}) уже отправлялись "
                    "в телеграм раньше — повторно не шлю."
                )

    return путь
