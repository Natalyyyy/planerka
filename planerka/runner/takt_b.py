"""Такт Б: план недели из тем, которые человек взял."""
import re
from datetime import date
from pathlib import Path

from .assemble import assemble
from .decisions import parse_decisions
from .файлы import записать_атомарно, прочесть_как_есть
from .llm import run_claude
from .person import личный_контекст
from .weeks import найти_файл_недели

ЗАГОЛОВОК = "## Неделя по дням"
ЗАГОЛОВОК_ПРОПУЩЕННЫХ = "## Пропущенные пометки"
ВЛАДЕЕТ_ТАКТ_Б = (ЗАГОЛОВОК, ЗАГОЛОВОК_ПРОПУЩЕННЫХ)

# Заголовок раздела — это "## ..." строго в начале строки. Именно поэтому
# нельзя резать текст поиском литеральной подстроки: человек может упомянуть
# "Неделя по дням" внутри обычного предложения где угодно в файле, и это не
# должно считаться границей раздела.
_ЗАГОЛОВОК_RE = re.compile(r"^(## .*)$", re.MULTILINE)


def _разбить_на_разделы(текст: str) -> list[str]:
    """Разбивает документ на разделы по заголовкам "## ..." в начале строки.

    Раздел — это сам заголовок плюс всё до следующего такого заголовка.
    Первый элемент списка — текст до первого заголовка (обычно пустая
    строка); он не отбрасывается, чтобы реконструкция была точной.
    """
    части = _ЗАГОЛОВОК_RE.split(текст)
    разделы = [части[0]]
    for i in range(1, len(части), 2):
        заголовок = части[i]
        тело = части[i + 1] if i + 1 < len(части) else ""
        разделы.append(заголовок + тело)
    return разделы


def _заголовок_раздела(раздел: str) -> str:
    return раздел.split("\n", 1)[0].rstrip()


def _чужой(раздел: str) -> bool:
    """Раздел, который такт Б не вправе трогать — не его собственный вывод."""
    return _заголовок_раздела(раздел) not in ВЛАДЕЕТ_ТАКТ_Б


def _соединить(блоки: list[str]) -> str:
    текст = ""
    for блок in блоки:
        if not блок:
            continue
        if текст:
            текст = текст.rstrip("\n") + "\n\n"
        текст += блок
    return текст.rstrip("\n") + "\n" if текст else ""


def _вырезать_раздел_недели(ответ: str) -> str:
    """Из ответа модели — только раздел «Неделя по дням», от заголовка.

    Модель устойчиво добавляет перед заголовком вводную фразу («Конечно! Вот
    план:»). Вклеенная в файл, она прилипала к предыдущему разделу и копилась
    по строке за прогон, а галочка внутри такой преамбулы на следующем
    прогоне разбиралась как решение человека — в план приезжала тема, которую
    человек не отмечал. Ответ вовсе без заголовка раньше уходил в файл
    молча и раздела не давал никогда.
    """
    м = re.search(rf"^{re.escape(ЗАГОЛОВОК)}\s*$", ответ, re.MULTILINE)
    if not м:
        raise RuntimeError(
            "в ответе модели нет заголовка «" + ЗАГОЛОВОК + "» — "
            "файл недели не тронут")
    return ответ[м.start():].strip() + "\n"


def _дописать_отклонённые(notes_root: Path, темы: list[str], today: date) -> None:
    """Копия отклонённых тем в «отклонённые.md» — без повторов.

    Строка банка `[-]` остаётся на месте: такт Б банк не трогает и ничего
    никуда не переносит, он именно копирует. Значит, второй прогон по тому
    же файлу видит те же отклонённые темы — и раньше дописывал их заново,
    так что файл заполнялся одной и той же строкой. Уже записанную тему за
    ту же дату пропускаем; та же тема в другой день — новый факт и новая
    строка.
    """
    отклонённые = notes_root / "отклонённые.md"
    прежнее = (отклонённые.read_text(encoding="utf-8")
               if отклонённые.exists() else "# Отклонённые темы\n")
    уже = {с.strip() for с in прежнее.splitlines()}
    новые: list[str] = []
    for тема in темы:
        строка = f"- {тема} · {today}"
        if строка in уже:
            continue
        уже.add(строка)
        новые.append(строка)
    if not новые:
        return
    записать_атомарно(отклонённые, f"{прежнее.rstrip()}\n" + "\n".join(новые) + "\n")


def takt_b(config: dict, notes_root: Path, blocks_dir: Path, today: date, зов=run_claude) -> Path:
    # Файл ищется, а не вычисляется из сегодняшней даты: между тактами стоит
    # неделя паузы, и пауза, пересёкшая понедельник, иначе ломает цикл.
    путь = найти_файл_недели(notes_root)
    if путь is None:
        raise FileNotFoundError(
            f"нет файла недели с банком тем в {notes_root / 'недели'} — "
            "сначала соберите темы")

    текст = прочесть_как_есть(путь)
    разделы = _разбить_на_разделы(текст)

    # Такт Б владеет ровно двумя разделами — "Неделя по дням" и "Пропущенные
    # пометки". Всё остальное (в т.ч. написанное человеком) — чужое, его
    # никогда не трогаем: сохраняется дословно и на своём месте. Решения
    # разбираем только по чужому тексту — иначе собственный прошлый вывод
    # такта Б (чек-лист по дням, разбор пропущенного) снова попадёт в
    # parse_decisions и будет объявлен пропущенной пометкой человека, хотя
    # человек её не писал.
    решения = parse_decisions("".join(р for р in разделы if _чужой(р)))
    if not решения["беру"]:
        raise RuntimeError("ни одной взятой темы — план собирать не из чего")

    промпт = assemble(config, blocks_dir, ядро="core-план.md", с_источниками=False)
    личное = личный_контекст(config, notes_root)
    if личное:
        промпт += "\n\n" + личное
    промпт += "\n\n## Взятые темы\n" + "\n".join(f"- {t}" for t in решения["беру"])
    if решения["подумать"]:
        промпт += "\n\n## Отложенные\n" + "\n".join(f"- {t}" for t in решения["подумать"])

    ответ = зов(промпт, model=config["модель"])
    if not ответ or not ответ.strip():
        raise RuntimeError("пустой ответ модели — файл недели не тронут")

    неделя_блок = _вырезать_раздел_недели(ответ)

    # Гонка: модель может думать десятки секунд, а за это время приём
    # нажатий (или сам человек) мог поменять файл — банк тем такт Б не
    # трогает, но реконструкция всё равно собирается из разделов,
    # прочитанных ДО вызова модели. Перечитываем файл заново прямо здесь,
    # уже после ответа модели, и собираем и разделы, и решения из СВЕЖЕГО
    # текста — иначе такт Б молча откатывает любое изменение, случившееся
    # за время вызова модели, тем же самым write_text, которым сам же
    # честно думает, что просто дописывает план.
    текст = прочесть_как_есть(путь)
    разделы = _разбить_на_разделы(текст)
    решения = parse_decisions("".join(р for р in разделы if _чужой(р)))

    # Пятый ключ parse_decisions — "пропущено": пометки, которые выглядели как
    # решение, но не разобрались (галочка вне "Банка тем", вложенная строка,
    # пустая тема, неизвестный маркер). Раньше такая строка исчезала молча —
    # кладём её в сам файл недели дословно, чтобы решение не терялось и было
    # видно и исправимо.
    пропущенные_блок = None
    if решения["пропущено"]:
        строки = "\n".join(f"- `{s}`" for s in решения["пропущено"])
        пропущенные_блок = (
            f"{ЗАГОЛОВОК_ПРОПУЩЕННЫХ}\n\n"
            "Эти строки в «Банке тем» выглядели как решение, но не были посчитаны — "
            "проверьте вручную и поправьте маркер или отступ:\n\n"
            f"{строки}\n"
        )

    # Каждый владеемый раздел переписывается ровно там, где стоял — не единым
    # блоком на месте первого из них. Иначе всё, что человек держал между
    # "Неделя по дням" и "Пропущенные пометки", выталкивается за оба разом.
    итог: list[str] = []
    неделя_вставлена = False
    пропущенные_вставлены = False
    for раздел in разделы:
        заголовок = _заголовок_раздела(раздел)
        if заголовок == ЗАГОЛОВОК:
            if not неделя_вставлена:
                итог.append(неделя_блок)
                неделя_вставлена = True
            continue
        if заголовок == ЗАГОЛОВОК_ПРОПУЩЕННЫХ:
            if пропущенные_блок is not None and not пропущенные_вставлены:
                итог.append(пропущенные_блок)
                пропущенные_вставлены = True
            continue
        итог.append(раздел)

    if not неделя_вставлена:
        итог.append(неделя_блок)
    if пропущенные_блок is not None and not пропущенные_вставлены:
        итог.append(пропущенные_блок)

    записать_атомарно(путь, _соединить(итог))

    if решения["нет"]:
        _дописать_отклонённые(notes_root, решения["нет"], today)

    return путь
