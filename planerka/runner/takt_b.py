"""Такт Б: план недели из тем, которые человек взял."""
import os
import re
from datetime import date
from pathlib import Path

from .assemble import assemble
from .decisions import parse_decisions
from .llm import run_claude
from .takt_a import начало_недели

ЗАГОЛОВОК = "## Неделя по дням"
ЗАГОЛОВОК_ПРОПУЩЕННЫХ = "## Пропущенные пометки"
ВЛАДЕЕТ_ТАКТ_Б = (ЗАГОЛОВОК, ЗАГОЛОВОК_ПРОПУЩЕННЫХ)

# Заголовок раздела — это "## ..." строго в начале строки. Именно поэтому
# нельзя резать текст поиском литеральной подстроки: человек может упомянуть
# "Неделя по дням" внутри обычного предложения где угодно в файле, и это не
# должно считаться границей раздела.
_ЗАГОЛОВОК_RE = re.compile(r"^(## .*)$", re.MULTILINE)


def _разбить_на_разделы(текст: str) -> list[str]:
    """Разбивает документ на разделы по заголовкам "## ..." в начале строки.

    Раздел — это сам заголовок плюс всё до следующего такого заголовка.
    Первый элемент списка — текст до первого заголовка (обычно пустая
    строка); он не отбрасывается, чтобы реконструкция была точной.
    """
    части = _ЗАГОЛОВОК_RE.split(текст)
    разделы = [части[0]]
    for i in range(1, len(части), 2):
        заголовок = части[i]
        тело = части[i + 1] if i + 1 < len(части) else ""
        разделы.append(заголовок + тело)
    return разделы


def _заголовок_раздела(раздел: str) -> str:
    return раздел.split("\n", 1)[0].rstrip()


def _чужой(раздел: str) -> bool:
    """Раздел, который такт Б не вправе трогать — не его собственный вывод."""
    return _заголовок_раздела(раздел) not in ВЛАДЕЕТ_ТАКТ_Б


def _соединить(блоки: list[str]) -> str:
    текст = ""
    for блок in блоки:
        if not блок:
            continue
        if текст:
            текст = текст.rstrip("\n") + "\n\n"
        текст += блок
    return текст.rstrip("\n") + "\n" if текст else ""


def _записать_атомарно(путь: Path, содержимое: str) -> None:
    временный = путь.with_suffix(путь.suffix + ".tmp")
    временный.write_text(содержимое, encoding="utf-8")
    os.replace(временный, путь)


def takt_b(config: dict, notes_root: Path, blocks_dir: Path, today: date, зов=run_claude) -> Path:
    путь = notes_root / "недели" / f"неделя – {начало_недели(today)}.md"
    if not путь.exists():
        raise FileNotFoundError(f"нет файла недели: ждали {путь}")

    текст = путь.read_text(encoding="utf-8")
    разделы = _разбить_на_разделы(текст)

    # Такт Б владеет ровно двумя разделами — "Неделя по дням" и "Пропущенные
    # пометки". Всё остальное (в т.ч. написанное человеком) собираем отдельно
    # и никогда не трогаем: сохраняется дословно, на своём месте, в прежнем
    # порядке относительно друг друга. Решения разбираем только по этому
    # "чужому" тексту — иначе собственный прошлый вывод такта Б (чек-лист по
    # дням, разбор пропущенного) снова попадёт в parse_decisions и будет
    # объявлен пропущенной пометкой человека, хотя человек её не писал.
    остальные: list[str] = []
    вставить_на = None
    for раздел in разделы:
        if _чужой(раздел):
            остальные.append(раздел)
        elif вставить_на is None:
            вставить_на = len(остальные)

    решения = parse_decisions("".join(остальные))
    if not решения["беру"]:
        raise RuntimeError("ни одной взятой темы — план собирать не из чего")

    промпт = assemble(config, blocks_dir, ядро="core-план.md")
    промпт += "\n\n## Взятые темы\n" + "\n".join(f"- {t}" for t in решения["беру"])
    if решения["подумать"]:
        промпт += "\n\n## Отложенные\n" + "\n".join(f"- {t}" for t in решения["подумать"])

    ответ = зов(промпт, model=config["модель"])
    if not ответ or not ответ.strip():
        raise RuntimeError("пустой ответ модели — файл недели не тронут")

    новые_разделы = [ответ.strip() + "\n"]

    # Пятый ключ parse_decisions — "пропущено": пометки, которые выглядели как
    # решение, но не разобрались (галочка вне "Банка тем", вложенная строка,
    # пустая тема, неизвестный маркер). Раньше такая строка исчезала молча —
    # кладём её в сам файл недели дословно, чтобы решение не терялось и было
    # видно и исправимо.
    if решения["пропущено"]:
        строки = "\n".join(f"- `{s}`" for s in решения["пропущено"])
        новые_разделы.append(
            f"{ЗАГОЛОВОК_ПРОПУЩЕННЫХ}\n\n"
            "Эти строки в «Банке тем» выглядели как решение, но не были посчитаны — "
            "проверьте вручную и поправьте маркер или отступ:\n\n"
            f"{строки}\n"
        )

    позиция = вставить_на if вставить_на is not None else len(остальные)
    итог = остальные[:позиция] + новые_разделы + остальные[позиция:]
    _записать_атомарно(путь, _соединить(итог))

    if решения["нет"]:
        отклонённые = notes_root / "отклонённые.md"
        прежнее = отклонённые.read_text(encoding="utf-8") if отклонённые.exists() else "# Отклонённые темы\n"
        новое = "\n".join(f"- {t} · {today}" for t in решения["нет"])
        _записать_атомарно(отклонённые, f"{прежнее.rstrip()}\n{новое}\n")

    return путь
