"""Файлы недели: как их найти и что в них осталось нерешённым.

Раньше оба такта вычисляли имя файла из своей сегодняшней даты — такт А по
понедельнику пятницы, такт Б по понедельнику своего дня. Между тактами
стоит неделя паузы, которую интервью обещает человеку, и любая пауза через
границу недели ломала цикл: такт Б искал файл, которого нет, а такт А в
новый понедельник заводил новый файл поверх непрочитанной недели решений.

Поэтому имя файла вычисляется ровно один раз — тактом А, при создании.
Всё остальное ищет **существующий** файл.
"""
import re
from datetime import date
from pathlib import Path

from .decisions import parse_decisions

ИМЯ = re.compile(r"^неделя – (\d{4})-(\d{2})-(\d{2})\.md$")
# «Разобрать решение» — значит поставить [x] или [-]. Пустая галочка и
# «подумать» остаются вопросом к человеку, и молчать о них нельзя.
НЕРАЗОБРАННЫЕ = ("не_решено", "подумать")
ЛЮБЫЕ = ("беру", "подумать", "нет", "не_решено")

# Разделы, которые в файле недели заводит сам такт А (см. blocks/core.md).
# Любой другой заголовок — либо раздел такта Б, либо написанный человеком:
# и то и другое — работа, которой прогон такта А стоить не должен.
РАЗДЕЛЫ_ТАКТА_А = ("банк тем", "додумать")
ЗАГОЛОВОК_РАЗДЕЛА = re.compile(r"^##\s+(.+?)\s*$")
# Проставленная отметка — любая, кроме пустой: [x], [?], [-]. Пустая [ ] —
# это то, что такт А написал сам, и работой человека она не является.
ПРОСТАВЛЕННАЯ = re.compile(r"^[-*]\s*\[[xX?\-]\]")


def _дата(файл: Path) -> date | None:
    м = ИМЯ.match(файл.name)
    if not м:
        return None
    try:
        return date(int(м[1]), int(м[2]), int(м[3]))
    except ValueError:
        return None


def файлы_недель(notes_root: Path) -> list[Path]:
    """Файлы недель от свежайшего к старому. Чужие имена не берём."""
    каталог = notes_root / "недели"
    if not каталог.is_dir():
        return []
    пары = [(д, ф) for ф in каталог.glob("*.md") if (д := _дата(ф)) is not None]
    return [ф for _, ф in sorted(пары, key=lambda п: п[0], reverse=True)]


def _решения(файл: Path) -> dict[str, list[str]] | None:
    try:
        return parse_decisions(файл.read_text(encoding="utf-8"))
    except (UnicodeDecodeError, OSError):
        return None


def найти_файл_недели(notes_root: Path) -> Path | None:
    """Свежайший файл недели с непустым банком тем.

    Файл без единой темы пропускается: такт А мог упасть или выдать пустой
    банк, и это не повод объявлять «не из чего собирать план» поверх живой
    размеченной недели, которая лежит рядом.
    """
    for файл in файлы_недель(notes_root):
        решения = _решения(файл)
        if решения and any(решения[к] for к in ЛЮБЫЕ):
            return файл
    return None


def неразобранное(файл: Path) -> dict[str, list[str]]:
    """Темы файла, по которым человек так и не принял решения."""
    решения = _решения(файл)
    if not решения:
        return {}
    осталось = {к: решения[к] for к in НЕРАЗОБРАННЫЕ if решения[к]}
    return осталось


def работа_человека(текст: str) -> dict[str, list[str]]:
    """Что в файле недели принадлежит человеку, а не такту А.

    Две вещи: проставленные отметки (`[x]`, `[?]`, `[-]`) и разделы, которых
    такт А не заводит, — свои заметки человека и разделы такта Б с уже
    собранным планом. Считаем без оглядки на блоки кода и отступы:
    ошибиться тут можно только в одну сторону — лишний раз не переписать
    файл, и эта сторона дешевле.
    """
    отметки: list[str] = []
    разделы: list[str] = []
    for строка in текст.splitlines():
        голая = строка.strip()
        заголовок = ЗАГОЛОВОК_РАЗДЕЛА.match(голая)
        if заголовок:
            имя = заголовок[1].strip()
            if имя.lower() not in РАЗДЕЛЫ_ТАКТА_А:
                разделы.append(имя)
            continue
        if ПРОСТАВЛЕННАЯ.match(голая):
            отметки.append(голая)
    return {"отметки": отметки, "разделы": разделы}
