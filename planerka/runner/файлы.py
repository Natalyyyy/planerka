"""Атомарная запись и точное чтение файла недели — общие для всех, кто его
трогает.

Файл недели — это неделя работы человека: отметки в банке тем, план по
дням, собственные разделы. Запись «в лоб» (`write_text` поверх старого
файла) на середине падения процесса или диска оставляет файл наполовину
переписанным — и тогда пропадает не то, что писал прогон, а то, что уже
отметил человек.

`os.replace` на одной файловой системе — атомарная операция подмены: кто
угодно, кто в этот момент читает файл, видит либо старое содержимое
целиком, либо новое целиком, никогда середину. Пишем во временный файл
рядом, а подменяем — одним системным вызовом.

Раньше эта же пара строк была продублирована в `takt_a.py` и в
`takt_b.py` — по одной копии на модуль. Когда третья копия понадобилась
приёму нажатий кнопок (`bot/приём.py` — единственное место в боте, которое
трогает файл недели), пришло время вынести: три независимые копии одной и
той же защиты рано или поздно разъедутся при правке одной из них, а
разойтись здесь — значит один из путей записи перестанет быть атомарным
именно там, где на кону неделя чужой работы.

## Имя временного файла — не фиксированное

Первая версия называла временный файл всегда `<файл>.tmp` — одинаково для
любого писателя. Пока писателей было двое (такт А и такт Б) и они писали
в разное время, это сходило с рук. Приём нажатий добавил третьего
писателя, который может сработать в любой момент, включая тот самый,
когда пишет такт Б, — и общее фиксированное имя означает, что оба
писателя претендуют на один и тот же временный файл: один может дописать
поверх временного файла другого, или `os.replace` одного унесёт файл,
который другой ещё не закончил заполнять. `tempfile.mkstemp` даёт каждому
вызову уникальное имя в той же папке — атомарность `os.replace` защищает
только переход «временный → целевой», а не право эксклюзивно писать во
временный файл, и уникальное имя эту дыру закрывает.

## Переводы строк — как в файле, а не как решит Python

`Path.read_text`/`write_text` по умолчанию работают в режиме universal
newlines: при чтении `\r\n` схлопывается в `\n`, при записи `\n` может
превратиться в системный разделитель строк. Для файла недели это не
безобидная деталь — Windows-редактор или синхронизация с Windows-машины
кладёт `\r\n`, и обещание «нажатие меняет только один символ» (приём
нажатий) или «чужой раздел остаётся дословно» (такт Б) становится ложным:
меняется КАЖДАЯ строка файла, не та единственная, которую действительно
хотели поправить. `newline=""` при открытии файла на чтение и на запись
выключает эту трансляцию — что было записано на диске, то и приходит
строкой, и что просят записать, то и уходит на диск, без интерпретации.
"""
import os
import tempfile
from pathlib import Path


def записать_атомарно(путь: Path, содержимое: str) -> None:
    """Пишет `содержимое` во временный файл рядом и атомарно подменяет `путь`.

    Временный файл получает уникальное имя (`tempfile.mkstemp`), а не
    фиксированное `<путь>.tmp` — см. докстринг модуля про конкурентных
    писателей. Записывается без перевода строк (`newline=""`): что лежит
    в строке `содержимое`, то и уходит на диск байт в байт.

    Если запись временного файла или подмена упадёт (диск, права, файл
    занят) — исключение уходит вызывающему коду как есть: он ближе к
    человеку и знает, как объяснить отказ понятно. Мусор от временного
    файла при таком падении не подчищается — это осознанно оставлено вне
    задачи этой функции.
    """
    дескриптор, временный_путь = tempfile.mkstemp(
        dir=путь.parent, prefix=f"{путь.name}.", suffix=".tmp"
    )
    with os.fdopen(дескриптор, "w", encoding="utf-8", newline="") as поток:
        поток.write(содержимое)
    os.replace(временный_путь, путь)


def прочесть_как_есть(путь: Path) -> str:
    """Читает файл без перевода строк — `\\r\\n` остаётся `\\r\\n`.

    В отличие от `Path.read_text(encoding="utf-8")` (universal newlines,
    схлопывает `\\r\\n` в `\\n` при чтении), этот способ нужен там, где
    прочитанный текст потом частично уходит обратно в файл дословно —
    приём нажатий кнопок и такт Б. Ошибки чтения (файла нет, нет прав,
    диск отвалился) — `OSError` как есть, вызывающий код решает, что
    сказать человеку.
    """
    with open(путь, "r", encoding="utf-8", newline="") as поток:
        return поток.read()
