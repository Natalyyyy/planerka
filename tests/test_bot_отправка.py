def test_три_неотмеченные_темы_уезжают_тремя_сообщениями(заметки):
    _написать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [ ] Тема первая · откуда: заметка\n"
        "- [x] Взятая тема, её не шлём\n"
        "- [ ] Тема вторая · откуда: чат\n"
        "- [ ] Тема третья · откуда: разговор\n",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    assert отправить.call_count == 3
    ожидаемое = [
        ("Тема первая", "Тема первая · откуда: заметка"),
        ("Тема вторая", "Тема вторая · откуда: чат"),
        ("Тема третья", "Тема третья · откуда: разговор"),
    ]
    assert отправить.call_args_list == [
        call(ТОКЕН, CHAT_ID, тема, _кнопки_ряд(содержимое)) for тема, содержимое in ожидаемое
    ]
    assert итог["отправлено"] == [тема for тема, _ in ожидаемое]
    assert итог["пропущено"] == []
    assert итог["всего"] == 3


def test_у_каждого_сообщения_три_кнопки_в_одном_ряду(заметки):
    _написать_неделю(заметки, "## Банк тем\n\n- [ ] Единственная тема\n")

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    _, _, _, ряды = отправить.call_args[0]
    assert len(ряды) == 1
    ряд = ряды[0]
    assert [подпись for подпись, _ in ряд] == ["Беру", "Подумать", "Нет"]
    ид = идентификатор("Единственная тема")
    assert [данные for _, данные in ряд] == [f"{ид}:b", f"{ид}:d", f"{ид}:n"]


