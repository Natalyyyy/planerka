def test_ноль_неотмеченных_тем_ничего_не_шлём_но_говорим_вслух(заметки, capsys):
    _написать_неделю(
        заметки,
        "## Банк тем\n\n- [x] Взятая тема\n- [-] Отклонённая тема\n",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    отправить.assert_not_called()
    assert итог["отправлено"] == []
    assert итог["всего"] == 0
    вывод = capsys.readouterr().out
    assert вывод.strip() != ""  # не молчим


def test_тема_длиннее_лимита_обрезается_а_идентификатор_от_полного_текста(заметки):
    # .rstrip() — разбор банка тем обрезает пробелы по краям строки (см.
    # planerka/runner/decisions.py), значит и «полный текст» темы, от
    # которого считается идентификатор, — уже без хвостового пробела.
    длинная_тема = ("длинная тема без остановки " * 200).rstrip()  # заведомо больше лимита
    assert len(длинная_тема) > ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ
    _написать_неделю(заметки, f"## Банк тем\n\n- [ ] {длинная_тема}\n")

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    _, _, отправленный_текст, ряды = отправить.call_args[0]
    assert len(отправленный_текст) == ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ
    assert отправленный_текст.endswith("…")
    assert отправленный_текст != длинная_тема

    ожидаемый_ид = идентификатор(длинная_тема)
    полученный_ид = ряды[0][0][1].split(":")[0]
    assert полученный_ид == ожидаемый_ид


