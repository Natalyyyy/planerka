def test_сеть_отвалилась_на_середине_пачки_не_теряем_и_не_дублируем(заметки):
    путь = _написать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [ ] Тема раз\n"
        "- [ ] Тема два\n"
        "- [ ] Тема три\n",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить.side_effect = [None, None, ОшибкаСети("обрыв связи")]
        with pytest.raises(ОшибкаСети):
            отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    assert отправить.call_count == 3
    отправленные_тексты = [вызов.args[2] for вызов in отправить.call_args_list]
    assert отправленные_тексты == ["Тема раз", "Тема два", "Тема три"]

    # Файл-спутник состояния хранит то, что реально ушло, а не всю пачку.
    файл_состояния = путь.parent / f"{путь.stem}.отправлено.json"
    assert файл_состояния.is_file()
    сохранённое = json.loads(файл_состояния.read_text(encoding="utf-8"))
    assert set(сохранённое["отправлено"]) == {идентификатор("Тема раз"), идентификатор("Тема два")}

    # Повторный запуск: первые две темы не дублируются, третья дошла.
    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить_снова:
        отправить_снова.return_value = None
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    отправить_снова.assert_called_once()
    assert отправить_снова.call_args[0][2] == "Тема три"
    assert итог["отправлено"] == ["Тема три"]
    assert итог["пропущено"] == ["Тема раз", "Тема два"]
    assert итог["всего"] == 3


def test_повторный_запуск_без_сети_вообще_ничего_не_шлёт_если_всё_уже_ушло(заметки):
    путь = _написать_неделю(заметки, "## Банк тем\n\n- [ ] Единственная тема\n")
    файл_состояния = путь.parent / f"{путь.stem}.отправлено.json"
    файл_состояния.write_text(
        json.dumps({"отправлено": [идентификатор("Единственная тема")]}),
        encoding="utf-8",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    отправить.assert_not_called()
    assert итог["отправлено"] == []
    assert итог["пропущено"] == ["Единственная тема"]


