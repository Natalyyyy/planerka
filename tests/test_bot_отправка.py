    _написать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [ ] Тема про запуск курса · откуда: чат\n"
        "- [ ] Тема про запуск курса · откуда: чат\n",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    отправить.assert_called_once()
    assert итог["отправлено"] == ["Тема про запуск курса"]
    assert итог["пропущено"] == ["Тема про запуск курса"]
    assert итог["всего"] == 2


