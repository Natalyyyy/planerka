"""Тесты отправки банка тем в Телеграм.

Токены — выдуманные строки, сеть везде замокана через `отправить_с_кнопками`:
прогон не должен ходить наружу. Проверяем и сам разбор банка тем, и то, как
модуль переживает обрыв сети на середине пачки сообщений.
"""
import json
from pathlib import Path
from unittest.mock import call, patch

import pytest

from planerka.bot.api import ОшибкаСети
from planerka.bot.отправка import ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ, отправить_банк_тем
from planerka.bot.темы import идентификатор

ТОКЕН = "222222:ВЫДУМАННЫЙ-ТОКЕН-НЕ-НАСТОЯЩИЙ"
CHAT_ID = 12345


@pytest.fixture
def заметки(tmp_path) -> Path:
    (tmp_path / "недели").mkdir()
    return tmp_path


def _написать_неделю(заметки: Path, текст: str, имя: str = "неделя – 2026-09-07.md") -> Path:
    путь = заметки / "недели" / имя
    путь.write_text(текст, encoding="utf-8")
    return путь


def _кнопки_ряд(тема: str) -> list:
    ид = идентификатор(тема)
    return [[("Беру", f"{ид}:b"), ("Подумать", f"{ид}:d"), ("Нет", f"{ид}:n")]]


# --- happy path ------------------------------------------------------


def test_три_неотмеченные_темы_уезжают_тремя_сообщениями(заметки):
    _написать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [ ] Тема первая · откуда: заметка\n"
        "- [x] Взятая тема, её не шлём\n"
        "- [ ] Тема вторая · откуда: чат\n"
        "- [ ] Тема третья · откуда: разговор\n",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    assert отправить.call_count == 3
    ожидаемые_темы = ["Тема первая", "Тема вторая", "Тема третья"]
    assert отправить.call_args_list == [
        call(ТОКЕН, CHAT_ID, тема, _кнопки_ряд(тема)) for тема in ожидаемые_темы
    ]
    assert итог["отправлено"] == ожидаемые_темы
    assert итог["пропущено"] == []
    assert итог["всего"] == 3


def test_у_каждого_сообщения_три_кнопки_в_одном_ряду(заметки):
    _написать_неделю(заметки, "## Банк тем\n\n- [ ] Единственная тема\n")

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    _, _, _, ряды = отправить.call_args[0]
    assert len(ряды) == 1
    ряд = ряды[0]
    assert [подпись for подпись, _ in ряд] == ["Беру", "Подумать", "Нет"]
    ид = идентификатор("Единственная тема")
    assert [данные for _, данные in ряд] == [f"{ид}:b", f"{ид}:d", f"{ид}:n"]


