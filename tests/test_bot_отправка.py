def test_файл_состояния_с_битым_utf8_не_роняет_прогон(заметки):
    # Файл-спутник — наш собственный, но мало ли: диск может подсунуть
    # обрывок записи после сбоя питания, или кто-то руками тронет файл.
    # Невалидные UTF-8-байты не должны ронять весь прогон необработанным
    # трейсбеком — тема просто считается ещё не отправленной и уходит.
    путь = _написать_неделю(заметки, "## Банк тем\n\n- [ ] Единственная тема\n")
    файл_состояния = путь.parent / f"{путь.stem}.отправлено.json"
    файл_состояния.write_bytes(b"\xff\xfe\x80\x81\x20\xc0\xaf")  # невалидные UTF-8 байты

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        итог = отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    отправить.assert_called_once()
    assert итог["отправлено"] == ["Единственная тема"]
    assert итог["пропущено"] == []

    # После успешной отправки файл-спутник перезаписан валидным JSON.
    сохранённое = json.loads(файл_состояния.read_text(encoding="utf-8"))
    assert сохранённое["отправлено"] == [идентификатор("Единственная тема")]


