def test_отмеченные_темы_не_отправляются_повторно(заметки):
    _написать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [x] Уже взятая\n"
        "- [?] Ещё думаю\n"
        "- [-] Уже отклонённая\n"
        "- [ ] Единственная неотмеченная\n",
    )

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    отправить.assert_called_once()
    отправленные_тексты = [вызов.args[2] for вызов in отправить.call_args_list]
    assert отправленные_тексты == ["Единственная неотмеченная"]
    assert "Уже взятая" not in отправленные_тексты
    assert "Ещё думаю" not in отправленные_тексты
    assert "Уже отклонённая" not in отправленные_тексты


