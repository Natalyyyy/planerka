def test_тема_длиннее_лимита_обрезается_а_идентификатор_от_полного_текста(заметки):
    # .rstrip() — разбор банка тем обрезает пробелы по краям строки (см.
    # planerka/runner/decisions.py), значит и «полный текст» темы, от
    # которого считается идентификатор, — уже без хвостового пробела.
    длинная_тема = ("длинная тема без остановки " * 200).rstrip()  # заведомо больше лимита
    assert len(длинная_тема) > ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ
    _написать_неделю(заметки, f"## Банк тем\n\n- [ ] {длинная_тема}\n")

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    _, _, отправленный_текст, ряды = отправить.call_args[0]
    assert len(отправленный_текст) == ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ
    assert отправленный_текст.endswith("…")
    assert отправленный_текст != длинная_тема

    ожидаемый_ид = идентификатор(длинная_тема)
    полученный_ид = ряды[0][0][1].split(":")[0]
    assert полученный_ид == ожидаемый_ид


def _длина_utf16_для_теста(текст: str) -> int:
    """Независимая от модуля реализация подсчёта UTF-16 code units — чтобы
    тест реально проверял поведение, а не совпадение с той же формулой,
    списанной из кода."""
    return len(текст.encode("utf-16-le")) // 2


def test_тема_с_эмодзи_обрезается_по_utf16_единицам_а_не_по_символам(заметки):
    # Каждый ракетный эмодзи — символ вне базовой плоскости Unicode
    # (U+1F680 > U+FFFF): в UTF-16 он весит 2 code unit, а в питоновском
    # len() — один символ. Реальный лимит Telegram — 4096 UTF-16 units.
    тема = "🚀" * 3000
    assert len(тема) < ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ  # по символам — с запасом ниже лимита
    assert _длина_utf16_для_теста(тема) > ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ  # а по UTF-16 — уже выше
    _написать_неделю(заметки, f"## Банк тем\n\n- [ ] {тема}\n")

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    _, _, отправленный_текст, _ = отправить.call_args[0]
    assert _длина_utf16_для_теста(отправленный_текст) <= ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ
    assert отправленный_текст.endswith("…")


def test_обрезка_не_оставляет_висячий_соединитель_составного_эмодзи(заметки):
    # Семья из четырёх человек — один составной эмодзи из четырёх «людских»
    # символов, склеенных тремя ZERO WIDTH JOINER (‍). Подбираем длину
    # заполнителя так, чтобы разрез по UTF-16-лимиту пришёлся ровно после
    # соединителя — наивная обрезка оставила бы висящий ‍ перед многоточием.
    заполнитель = "а" * (ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ - len("…") - 3)  # -3: 2 unit «👨» + 1 unit ZWJ
    семья = "👨" + "‍" + "👩" + "‍" + "👧" + "‍" + "👦"
    тема = заполнитель + семья
    _написать_неделю(заметки, f"## Банк тем\n\n- [ ] {тема}\n")

    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить_банк_тем(ТОКЕН, CHAT_ID, заметки)

    _, _, отправленный_текст, _ = отправить.call_args[0]
    assert отправленный_текст == заполнитель + "👨" + "…"
    assert "‍" not in отправленный_текст
    assert _длина_utf16_для_теста(отправленный_текст) <= ЛИМИТ_ДЛИНЫ_СООБЩЕНИЯ


