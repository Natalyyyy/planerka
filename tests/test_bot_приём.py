# --- инвариант — обязательный тест ------------------------------------


def test_инвариант_меняется_ровно_один_символ_остальное_дословно(заметки):
    путь = _написать_неделю(заметки, БОГАТЫЙ_ФАЙЛ)
    ид = идентификатор("Тема вторая · откуда: трендвотчинг")

    with patch("planerka.bot.приём.ответить_на_нажатие"):
        итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)

    assert итог["статус"] == "записано"
    стало = путь.read_text(encoding="utf-8")
    отличия = _единственное_отличие(БОГАТЫЙ_ФАЙЛ, стало)
    assert len(отличия) == 1, f"изменилось символов: {len(отличия)}, а не 1"
    позиция = отличия[0]
    assert БОГАТЫЙ_ФАЙЛ[позиция] == " "
    assert стало[позиция] == "x"
    # Разделы человека и других тактов — дословно на месте.
    for кусок in (
        "Свободный текст до первого заголовка — как есть.",
        "## Неделя по дням\n\nПн — Взятая вручную",
        "## Пропущенные пометки",
        "- `- [x] что-то не то`",
        "## Додумать\n\n- пункт додумать",
        "## Мои заметки\n\nсвой текст человека, второй абзац",
    ):
        assert кусок in стало


def test_инвариант_не_путает_чекбокс_вне_банка_тем(заметки):
    """Строка-чекбокс вне «Банка тем» текстуально совпадает с темой банка,
    но идентификатор для неё никогда не выпускался — приём не имеет права
    решить, что это она, и потрогать чужой раздел."""
    текст = (
        "## Банк тем\n\n- [ ] Настоящая тема · откуда: чат\n\n"
        "## Мои заметки\n\n- [ ] Настоящая тема · откуда: чат\n"
    )
    путь = _написать_неделю(заметки, текст)
    ид = идентификатор("Настоящая тема · откуда: чат")

    # Раз в файле ДВЕ строки с одинаковым содержимым (в банке и вне его),
    # приём обязан взять именно банковскую и не тронуть копию в заметках.
    with patch("planerka.bot.приём.ответить_на_нажатие"):
        итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)

    assert итог["статус"] == "записано"
    стало = путь.read_text(encoding="utf-8")
    assert "## Банк тем\n\n- [x] Настоящая тема · откуда: чат" in стало
    assert "## Мои заметки\n\n- [ ] Настоящая тема · откуда: чат" in стало


