def test_нажатие_по_теме_отмеченной_человеком_вручную_другим_маркером(заметки):
    # Человек сам поставил [-] (отказался), а нажатие пришло по старой
    # кнопке «Беру» — считаем, что решение через бота актуальнее, и оно
    # перезаписывает то, что было проставлено руками. Но перезапись должна
    # быть видна человеку — иначе случайное нажатие по старому сообщению
    # молча переворачивает обдуманное решение, и узнать об этом неоткуда.
    путь = _написать_неделю(заметки, "## Банк тем\n\n- [-] Тема · откуда: чат\n")
    ид = идентификатор("Тема · откуда: чат")

    with patch("planerka.bot.приём.ответить_на_нажатие") as ответить:
        итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)

    assert путь.read_text(encoding="utf-8") == "## Банк тем\n\n- [x] Тема · откуда: чат\n"
    assert итог["статус"] == "записано"
    текст_ответа = ответить.call_args[0][2].lower()
    assert "беру" in текст_ответа
    assert "нет" in текст_ответа  # прежнее решение названо по имени
    assert "раньше" in текст_ответа or "было" in текст_ответа
    # Перезапись прежнего решения — модальное окно, не полоска.
    assert ответить.call_args.kwargs.get("show_alert") is True


