def test_файл_занят_или_нет_прав_понятное_сообщение_файл_не_испорчен(заметки):
    исходный = "## Банк тем\n\n- [ ] Тема · откуда: чат\n"
    путь = _написать_неделю(заметки, исходный)
    ид = идентификатор("Тема · откуда: чат")

    каталог = заметки / "недели"
    старые_права = stat.S_IMODE(os.stat(каталог).st_mode)
    os.chmod(каталог, stat.S_IRUSR | stat.S_IXUSR)  # r-x — без права записи
    try:
        with patch("planerka.bot.приём.ответить_на_нажатие") as ответить:
            итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)
    finally:
        os.chmod(каталог, старые_права)

    assert итог["статус"] == "ошибка_записи"
    текст_ответа = ответить.call_args[0][2].lower()
    assert "не удалось" in текст_ответа or "занят" in текст_ответа or "прав" in текст_ответа
    assert путь.read_text(encoding="utf-8") == исходный


