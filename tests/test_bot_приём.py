def test_инвариант_держится_на_crlf_файле(заметки):
    # Ревью: Path.read_text по умолчанию схлопывает \r\n в \n при чтении —
    # без newline="" при чтении/записи «меняется ровно один символ»
    # превращалось бы в «меняется каждая строка файла». Файл целиком на
    # CRLF (как из Windows-редактора), и диффим байты, а не str, чтобы
    # схлопывание было видно, если оно случится.
    исходный = (
        "Текст до заголовка.\r\n\r\n"
        "## Банк тем\r\n\r\n"
        "- [ ] Тема · откуда: чат\r\n"
        "- [x] Другая тема · откуда: заметка\r\n\r\n"
        "## Мои заметки\r\n\r\n"
        "Первая строка.\r\n"
        "Вторая строка.\r\n"
    )
    путь = заметки / "недели" / "неделя – 2026-09-07.md"
    путь.write_bytes(исходный.encode("utf-8"))
    ид = идентификатор("Тема · откуда: чат")

    with patch("planerka.bot.приём.ответить_на_нажатие"):
        итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)

    assert итог["статус"] == "записано"
    стало = путь.read_bytes().decode("utf-8")
    отличия = _единственное_отличие(исходный, стало)
    assert len(отличия) == 1, f"изменилось символов: {len(отличия)}, а не 1 (CRLF схлопнулся?)"
    assert исходный[отличия[0]] == " " and стало[отличия[0]] == "x"
    # \r\n не схлопнулись в \n нигде в файле.
    assert стало.count("\r\n") == исходный.count("\r\n")
    assert "\r\n\n" not in стало and "\n\n" not in стало.replace("\r\n\r\n", "")


