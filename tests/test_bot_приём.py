"""Тесты приёма нажатий кнопок «Беру / Подумать / Нет».

Это единственное место в боте, которое трогает файл недели — а в нём лежит
недельная работа человека. Инвариант держит весь модуль: одно нажатие меняет
ровно один символ в одной строке банка, всё остальное — разделы человека,
«Неделя по дням», «Пропущенные пометки», «Додумать», текст до первого
заголовка, порядок разделов — остаётся дословно.

Токены и id нажатий — выдуманные строки, сеть замокана через
`ответить_на_нажатие`: прогон не должен ходить наружу.
"""
import os
import stat
from pathlib import Path
from unittest.mock import call, patch

import pytest

from planerka.bot.приём import принять_нажатие
from planerka.bot.темы import идентификатор

ТОКЕН = "333333:ВЫДУМАННЫЙ-ТОКЕН-НЕ-НАСТОЯЩИЙ"
ID_НАЖАТИЯ = "callback-1"

# Богатый файл недели: раздел банка с несколькими темами плюс всё, что
# принадлежит человеку и другим тактам — используется и в happy-тестах, и
# в отдельном тесте на инвариант «меняется ровно один символ».
БОГАТЫЙ_ФАЙЛ = (
    "Свободный текст до первого заголовка — как есть.\n\n"
    "## Банк тем\n\n"
    "- [ ] Тема первая · откуда: чат\n"
    "- [x] Взятая вручную · откуда: заметка\n"
    "- [ ] Тема вторая · откуда: трендвотчинг\n\n"
    "## Неделя по дням\n\n"
    "Пн — Взятая вручную\n\n"
    "## Пропущенные пометки\n\n"
    "Эти строки выглядели как решение, но не были посчитаны — "
    "проверьте вручную:\n\n"
    "- `- [x] что-то не то`\n\n"
    "## Додумать\n\n"
    "- пункт додумать\n\n"
    "## Мои заметки\n\n"
    "свой текст человека, второй абзац\n"
)


@pytest.fixture
def заметки(tmp_path) -> Path:
    (tmp_path / "недели").mkdir()
    return tmp_path


def _написать_неделю(заметки: Path, текст: str, имя: str = "неделя – 2026-09-07.md") -> Path:
    путь = заметки / "недели" / имя
    путь.write_text(текст, encoding="utf-8")
    return путь


def _единственное_отличие(до: str, после: str) -> list[int]:
    """Индексы символов, которыми `после` отличается от `до`.

    Считает по символам, не по строкам, — именно так проверяется
    инвариант «меняется ровно один символ», а не «одна строка».
    """
    if len(до) != len(после):
        # Разная длина — заведомо больше одного изменения (замена символа
        # на символ длину не меняет); явно провалить, а не молча урезать.
        return list(range(max(len(до), len(после))))
    return [i for i, (a, b) in enumerate(zip(до, после)) if a != b]


# --- happy path ------------------------------------------------------


def test_нажатие_беру_проставляет_x(заметки):
    путь = _написать_неделю(заметки, "## Банк тем\n\n- [ ] Тема · откуда: чат\n")
    ид = идентификатор("Тема · откуда: чат")

    with patch("planerka.bot.приём.ответить_на_нажатие") as ответить:
        итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)

    assert путь.read_text(encoding="utf-8") == "## Банк тем\n\n- [x] Тема · откуда: чат\n"
    assert итог["статус"] == "записано"
    ответить.assert_called_once()
    вызов_токен, вызов_id, вызов_текст = ответить.call_args[0]
    assert вызов_токен == ТОКЕН
    assert вызов_id == ID_НАЖАТИЯ
    assert "беру" in вызов_текст.lower()


