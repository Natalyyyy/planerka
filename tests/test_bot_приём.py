def test_гонка_такт_б_дописал_план_пока_приём_готовил_запись_не_затираем(заметки):
    # Critical: приём читает файл в начале и пишет собранный из него текст
    # в конце — между этими двумя точками такт Б (или кто угодно) мог
    # успеть реально записать файл, например дописать свежий план. Если
    # приём пишет не глядя, план пропадает, а человек слышит «Записано».
    исходный = "## Банк тем\n\n- [ ] Тема · откуда: чат\n"
    путь = _написать_неделю(заметки, исходный)
    ид = идентификатор("Тема · откуда: чат")

    план_такта_б = исходный + "\n## Неделя по дням\n\nПн — Тема\n"
    вызовы = {"счётчик": 0}

    def подмена_чтения(п):
        вызовы["счётчик"] += 1
        if вызовы["счётчик"] == 1:
            return исходный
        # Второе чтение приёма — прямо перед записью. Имитируем, что
        # конкурентный такт Б успел реально записать файл на диск между
        # первым и вторым чтением приёма.
        путь.write_text(план_такта_б, encoding="utf-8")
        return план_такта_б

    with patch("planerka.bot.приём.прочесть_как_есть", side_effect=подмена_чтения), \
         patch("planerka.bot.приём.ответить_на_нажатие") as ответить:
        итог = принять_нажатие(ТОКЕН, ID_НАЖАТИЯ, f"{ид}:b", заметки)

    стало = путь.read_text(encoding="utf-8")
    assert стало == план_такта_б  # план такта Б не затёрт
    assert итог["статус"] == "файл_изменился"
    текст_ответа = ответить.call_args[0][2].lower()
    assert "измен" in текст_ответа or "ещё раз" in текст_ответа or "повтор" in текст_ответа
    assert ответить.call_args.kwargs.get("show_alert") is True


