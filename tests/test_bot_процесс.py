def test_дедлайн_считается_от_понедельника_файла_а_не_от_сегодня(мир_с_блоками):
    """Дедлайн — понедельник ИМЕНИ ФАЙЛА плюс день недели из конфига, не
    сегодняшняя дата процесса. Файл датирован давно ушедшей неделей
    (2026-08-24, тоже понедельник) — если бы дедлайн считался от «сегодня»
    (реального календаря на момент прогона тестов), он попал бы в будущее
    и это тесто прошло бы даже на сломанном коде — поэтому `now` здесь
    стоит именно между дедлайном СТАРОЙ недели файла и тем, что получилось
    бы, если код перепутал её с текущей."""
    заметки, блоки = мир_с_блоками
    путь = _записать_неделю(
        заметки, "## Банк тем\n\n- [x] Взятая тема · откуда: чат\n",
        имя="неделя – 2026-08-24.md",
    )
    config = {"модель": "claude-sonnet-5", "дедлайн_такта_б": "среда, 20:00"}
    отправить = Mock()
    # Дедлайн файла — 2026-08-26, 20:00 (среда той же недели). Момент ниже
    # уже позже него, но задолго до 2026-09-07 — то есть до понедельника,
    # которым помечен файл, если бы код по ошибке считал «сегодня».
    now = Mock(return_value=datetime(2026, 8, 26, 20, 0, 1))

    запустить_бота(
        ТОКЕН, CHAT_ID, заметки, config, блоки,
        получить_обновления=Mock(return_value=[]),
        отправить_сообщение=отправить,
        собрать_план=_план_с_фейковой_моделью,
        now=now,
        макс_итераций=1,
    )

    отправить.assert_called_once()
    assert путь.name in отправить.call_args[0][2]


