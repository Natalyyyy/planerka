def test_собрать_план_получает_дату_из_now_а_не_системную(мир_с_блоками):
    """Единственное место в модуле, где раньше дата бралась мимо
    инжектируемого `now` (`date.today()`), — ровно та ловушка, на которой
    уже спотыкались с самим дедлайном (см. тест выше про понедельник файла).
    now здесь стоит намеренно далеко от реальной системной даты прогона."""
    заметки, блоки = мир_с_блоками
    _записать_неделю(заметки, "## Банк тем\n\n- [x] Взятая тема · откуда: чат\n")
    config = {"модель": "claude-sonnet-5", "дедлайн_такта_б": "среда, 20:00"}
    видел = {}

    def собрать_план(config, notes_root, blocks_dir, today):
        видел["today"] = today
        return _план_с_фейковой_моделью(config, notes_root, blocks_dir, today)

    запустить_бота(
        ТОКЕН, CHAT_ID, заметки, config, блоки,
        получить_обновления=Mock(return_value=[]),
        отправить_сообщение=Mock(),
        собрать_план=собрать_план,
        now=Mock(return_value=datetime(2099, 1, 1, 0, 0, 1)),
        макс_итераций=1,
    )
    assert видел["today"] == datetime(2099, 1, 1).date()


