def test_ошибка_токена_даёт_ненулевой_код_выхода(заметки, capsys):
    """Бот будет подниматься автозапуском (launchd/systemd) — супервизор
    отличает штатную остановку от аварийной только по коду выхода. Протухший
    токен — не штатно, дальше опрашивать нечем, супервизор должен это
    заметить и не считать процесс «отработавшим нормально»."""
    получить = Mock(side_effect=ОшибкаТокена("протух"))
    with pytest.raises(SystemExit) as вылет:
        запустить_бота(
            ТОКЕН, CHAT_ID, заметки, {"модель": "claude-sonnet-5"}, заметки / "blocks",
            получить_обновления=получить,
            макс_итераций=5,
        )
    assert вылет.value.code != 0
    assert получить.call_count == 1  # не пытается снова — выходим сразу
    вывод = capsys.readouterr()
    assert "токен" in (вывод.out + вывод.err).lower()


def test_ctrl_c_останавливает_чисто_без_трейсбека_и_с_нулевым_кодом(заметки, capsys):
    получить = Mock(side_effect=KeyboardInterrupt())
    # Если KeyboardInterrupt не поймана внутри — pytest сам получит трейсбек
    # и тест провалится с ошибкой, а не с ассертом; сам факт, что мы дошли
    # до ассерта, уже доказывает «без трейсбека». Функция при этом не должна
    # поднимать SystemExit вовсе — иначе она сама этот вызов и провалила бы:
    # штатная остановка (в отличие от протухшего токена) обязана дать
    # нулевой код выхода, а без исключения вызывающий код (run.py, дальше —
    # интерпретатор на __main__) естественно завершится с кодом 0.
    запустить_бота(
        ТОКЕН, CHAT_ID, заметки, {"модель": "claude-sonnet-5"}, заметки / "blocks",
        получить_обновления=получить,
        макс_итераций=5,
    )
    вывод = capsys.readouterr()
    assert "остановлен" in (вывод.out + вывод.err).lower()


