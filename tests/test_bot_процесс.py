"""Тесты долгоживущего процесса бота: опрос обновлений, приём нажатий, дедлайн такта Б.

Сеть везде замокана через параметры `получить_обновления` / `отправить_сообщение`
самого `запустить_бота` (и, где нужен настоящий приём нажатий, через
`planerka.bot.приём.ответить_на_нажатие`) — прогон тестов не должен ходить
наружу. Долгий цикл гоняется конечное число раз через `макс_итераций`:
без этого параметра `запустить_бота` не возвращается сам, и тест завис бы
навсегда — с ним функция делает ровно столько проходов long-polling'а,
сколько сказано, и возвращается, как будто её остановили.

Такт Б внутри дедлайна не подделывается целиком (это своя логика планёрки,
не внешний мир) — берётся настоящая `takt_b`, а подделывается только вызов
модели внутри неё (`зов`), как это уже делает `tests/test_takt_b.py`.
Исключение — тест на генерик-падение такта Б: там `собрать_план` подменяется
целиком, потому что проверяется не то, как именно такт Б падает, а как
`процесс.py` реагирует на любое падение вызванной функции.
"""
