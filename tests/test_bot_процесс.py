CHAT_ID = 999999


@pytest.fixture
def заметки(tmp_path) -> Path:
    """Папка заметок с пустой «недели/» — без файла недели: для тестов цикла
    опроса, которым не нужен ни банк тем, ни настоящий такт Б."""
    (tmp_path / "недели").mkdir()
    return tmp_path


@pytest.fixture
def мир_с_блоками(tmp_path):
    """Полный набор для настоящего такта Б: блоки промпта плюс папка заметок —
    как в tests/test_takt_b.py."""
    блоки = tmp_path / "blocks"
    (блоки / "sources").mkdir(parents=True)
    (блоки / "platforms").mkdir()
    (блоки / "core.md").write_text("ЯДРО", encoding="utf-8")
    (блоки / "core-план.md").write_text("ЯДРО-ПЛАН", encoding="utf-8")
    заметки = tmp_path / "notes"
    (заметки / "недели").mkdir(parents=True)
    return заметки, блоки


def _записать_неделю(заметки: Path, текст: str, имя: str = "неделя – 2026-09-07.md") -> Path:
    путь = заметки / "недели" / имя
    путь.write_text(текст, encoding="utf-8")
    return путь


def _план_с_фейковой_моделью(config, notes_root, blocks_dir, today):
    """Настоящий такт Б с подделанным только внешним вызовом модели."""
    return takt_b(
        config, notes_root, blocks_dir, today,
        зов=lambda *a, **k: "## Неделя по дням\n\nПн — Взятая тема",
    )


