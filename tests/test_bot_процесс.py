def test_три_нажатия_подряд_обработаны_смещение_сдвигается(заметки):
    путь = _записать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [ ] Тема раз · откуда: чат\n"
        "- [ ] Тема два · откуда: чат\n"
        "- [ ] Тема три · откуда: чат\n",
    )
    ид1 = идентификатор("Тема раз · откуда: чат")
    ид2 = идентификатор("Тема два · откуда: чат")
    ид3 = идентификатор("Тема три · откуда: чат")

    получить = Mock(side_effect=[
        [{"update_id": 100, "callback_query": {"id": "c1", "data": f"{ид1}:b"}}],
        [{"update_id": 101, "callback_query": {"id": "c2", "data": f"{ид2}:n"}}],
        [{"update_id": 102, "callback_query": {"id": "c3", "data": f"{ид3}:d"}}],
    ])

    with patch("planerka.bot.приём.ответить_на_нажатие"):
        запустить_бота(
            ТОКЕН, CHAT_ID, заметки, {"модель": "claude-sonnet-5"}, заметки / "blocks",
            получить_обновления=получить,
            макс_итераций=3,
        )

    assert путь.read_text(encoding="utf-8") == (
        "## Банк тем\n\n"
        "- [x] Тема раз · откуда: чат\n"
        "- [-] Тема два · откуда: чат\n"
        "- [?] Тема три · откуда: чат\n"
    )
    вызовы = получить.call_args_list
    assert вызовы[0].kwargs["смещение"] is None
    assert вызовы[1].kwargs["смещение"] == 101
    assert вызовы[2].kwargs["смещение"] == 102


