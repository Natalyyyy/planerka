def test_три_нажатия_подряд_обработаны_смещение_сдвигается(заметки):
    путь = _записать_неделю(
        заметки,
        "## Банк тем\n\n"
        "- [ ] Тема раз · откуда: чат\n"
        "- [ ] Тема два · откуда: чат\n"
        "- [ ] Тема три · откуда: чат\n",
    )
    ид1 = идентификатор("Тема раз · откуда: чат")
