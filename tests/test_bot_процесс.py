def _загрузить_run_модуль():
    """Импортирует run.py напрямую, как это делает точка входа плагина, а не
    через `import planerka.run` — так же, как run.py сам импортирует свои
    модули после установки (см. docstring run.py)."""
    путь = Path(__file__).resolve().parents[1] / "planerka" / "run.py"
    spec = importlib.util.spec_from_file_location("planerka_run_для_теста_бота", путь)
