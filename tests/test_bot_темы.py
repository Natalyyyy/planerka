"""Тесты устойчивого идентификатора темы для callback_data кнопок.

Порядковый номер темы в файле не годится: человек правит банк тем между
прогонами, темы сдвигаются, и нажатие ляжет не на ту тему. Идентификатор —
хеш от текста, устойчивый к любым перестановкам соседних строк.
"""
import pytest

from planerka.bot.темы import идентификатор


# --- happy path ------------------------------------------------------


def test_одинаковый_текст_даёт_одинаковый_идентификатор():
    a = идентификатор("Тема про запуск нового курса")
    b = идентификатор("Тема про запуск нового курса")
    assert a == b


def test_разные_темы_дают_разные_идентификаторы():
    a = идентификатор("Тема про запуск нового курса")
    b = идентификатор("Тема про отзывы учеников")
    assert a != b


def test_идентификатор_это_непустая_строка_из_ascii_символов():
    ид = идентификатор("Обычная тема")
    assert ид
    assert ид.isascii()


# --- edge --------------------------------------------------------------


def test_пустая_тема_не_падает_и_даёт_идентификатор():
    ид = идентификатор("")
    assert ид


def test_очень_длинная_тема_даёт_короткий_идентификатор():
    длинная = "тема " * 5000
    ид = идентификатор(длинная)
    # 64 байта — лимит Telegram на весь callback_data, а в нём кроме
    # идентификатора ещё код состояния и разделитель — идентификатор
    # должен быть заметно короче лимита сам по себе.
    assert len(ид.encode("utf-8")) <= 32


def test_тема_с_переносом_регистра_и_пробелами_даёт_другой_идентификатор():
    # Не нормализуем сами — раз тексты в файле разные (даже на пробел),
    # значит и хеш должен различаться, а не подгонять их искусственно
    # под одно и то же.
    a = идентификатор("Тема")
    b = идентификатор("тема")
    assert a != b


def test_тема_с_эмодзи_и_кириллицей_не_падает():
    ид = идентификатор("Запуск 🚀 нового курса — стоит ли? 😅")
    assert ид


# --- error ---------------------------------------------------------------


def test_не_строка_бросает_понятную_ошибку():
    with pytest.raises(TypeError):
        идентификатор(None)


def test_число_вместо_строки_бросает_понятную_ошибку():
    with pytest.raises(TypeError):
        идентификатор(123)
