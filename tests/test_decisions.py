from planerka.runner.decisions import parse_decisions

БАНК = """## Банк тем

- [x] Первая тема · откуда: встреча
- [?] Вторая тема · откуда: чат
- [-] Третья тема · откуда: заметка
- [ ] Четвёртая тема · откуда: архив

## Додумать

- Какой-то вопрос
"""


def test_разбирает_четыре_состояния():
    out = parse_decisions(БАНК)
    assert out["беру"] == ["Первая тема"]
    assert out["подумать"] == ["Вторая тема"]
    assert out["нет"] == ["Третья тема"]
    assert out["не_решено"] == ["Четвёртая тема"]


def test_откуда_отрезается():
    out = parse_decisions("## Банк тем\n- [x] Тема · откуда: файл")
    assert out["беру"] == ["Тема"]


def test_пустой_текст_даёт_пустые_списки():
    out = parse_decisions("")
    assert out == {"беру": [], "подумать": [], "нет": [], "не_решено": [], "пропущено": []}


def test_ни_одной_галочки_не_проставлено():
    out = parse_decisions("## Банк тем\n- [ ] Раз\n- [ ] Два")
    assert out["беру"] == [] and len(out["не_решено"]) == 2


def test_все_темы_отклонены():
    out = parse_decisions("## Банк тем\n- [-] Раз\n- [-] Два")
    assert out["беру"] == [] and len(out["нет"]) == 2


def test_дубль_темы_сохраняется_дважды():
    out = parse_decisions("## Банк тем\n- [x] Тема\n- [x] Тема")
    assert out["беру"] == ["Тема", "Тема"]


def test_строки_вне_банка_не_попадают():
    text = """## Банк тем
- [x] Это беру

## Додумать
- [x] Это не беру

вне разделов
- [x] И это не беру"""
    out = parse_decisions(text)
    assert out["беру"] == ["Это беру"]
    assert out["пропущено"] != []  # галочки вне Банка попадают в пропущено


def test_неизвестный_маркер_игнорируется():
    out = parse_decisions("## Банк тем\n- [z] Тема")
    assert all(len(v) == 0 for k, v in out.items() if k != "пропущено")
    assert len(out["пропущено"]) > 0


def test_регистр_маркера_не_важен():
    out = parse_decisions("## Банк тем\n- [X] Тема")
    assert out["беру"] == ["Тема"]


def test_тема_с_точкой_посередине():
    """Critical 1: режет только по литералу '· откуда:', не по любому ·"""
    text = """## Банк тем
- [x] Идея для эфира · с гостем · откуда: чат"""
    out = parse_decisions(text)
    assert out["беру"] == ["Идея для эфира · с гостем"]


def test_маркер_звездочка_вместо_минуса():
    """Critical 2: принимаем оба маркера - и *"""
    text = """## Банк тем
* [x] Первая
- [x] Вторая"""
    out = parse_decisions(text)
    assert out["беру"] == ["Первая", "Вторая"]


def test_вложенная_строка_с_отступом():
    """Critical 2: вложенный подпункт не считается отдельной темой"""
    text = """## Банк тем
- [x] Основная тема
  - [x] Уточнение к теме"""
    out = parse_decisions(text)
    assert out["беру"] == ["Основная тема"]
    assert any("Уточнение к теме" in s for s in out["пропущено"])


def test_галочка_в_разделе_додумать():
    """Critical 2: разбираем только внутри 'Банк тем'"""
    text = """## Банк тем
- [x] Это беру

## Додумать
- [x] Это не беру"""
    out = parse_decisions(text)
    assert out["беру"] == ["Это беру"]
    assert "- [x] Это не беру" in out["пропущено"]


def test_галочка_в_блоке_кода():
    """Critical 2: пропускаем содержимое блоков кода"""
    text = """## Банк тем
- [x] Реальная тема

```
- [x] Это пример в блоке кода
```"""
    out = parse_decisions(text)
    assert out["беру"] == ["Реальная тема"]
    # пример из кода не попадает ни в список, ни в пропущено


def test_пустая_тема():
    """Important: пустая тема не попадает в список, а в пропущено"""
    text = """## Банк тем
- [x]
- [x] · откуда: файл"""
    out = parse_decisions(text)
    assert out["беру"] == []
    assert len(out["пропущено"]) == 2


def test_неизвестный_маркер_в_пропущено():
    """Critical 3: неизвестные маркеры попадают в пропущено"""
    text = """## Банк тем
- [z] Неизвестный маркер"""
    out = parse_decisions(text)
    assert out["пропущено"] == ["- [z] Неизвестный маркер"]
    assert all(len(v) == 0 for k, v in out.items() if k != "пропущено")


def test_строка_вне_разделов():
    """Critical 2: строки с галочкой вне раздела Банк тем попадают в пропущено"""
    text = """случайный текст
- [x] Это не в разделе"""
    out = parse_decisions(text)
    assert out["беру"] == []
    assert out["пропущено"] == ["- [x] Это не в разделе"]


def test_галочка_без_единого_заголовка_уходит_в_пропущено():
    """Critical: строка с галочкой без раздела Банк тем не исчезает"""
    out = parse_decisions("- [x] Бесхозная")
    assert out["беру"] == []
    assert out["пропущено"] == ["- [x] Бесхозная"]


def test_галочка_выше_раздела_банк_тем():
    """Critical: строка с галочкой ДО раздела Банк тем не игнорируется"""
    text = """- [x] До раздела

## Банк тем
- [x] В разделе"""
    out = parse_decisions(text)
    assert out["беру"] == ["В разделе"]
    assert "- [x] До раздела" in out["пропущено"]
