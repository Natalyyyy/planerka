import pytest

from planerka.runner.decisions import parse_decisions, строки_банка

БАНК = """## Банк тем

- [x] Первая тема · откуда: встреча
- [?] Вторая тема · откуда: чат
- [-] Третья тема · откуда: заметка
- [ ] Четвёртая тема · откуда: архив

## Додумать

- Какой-то вопрос
"""


def test_разбирает_четыре_состояния():
    out = parse_decisions(БАНК)
    assert out["беру"] == ["Первая тема"]
    assert out["подумать"] == ["Вторая тема"]
    assert out["нет"] == ["Третья тема"]
    assert out["не_решено"] == ["Четвёртая тема"]


def test_откуда_отрезается():
    out = parse_decisions("## Банк тем\n- [x] Тема · откуда: файл")
    assert out["беру"] == ["Тема"]


def test_пустой_текст_даёт_пустые_списки():
    out = parse_decisions("")
    assert out == {"беру": [], "подумать": [], "нет": [], "не_решено": [], "пропущено": []}


def test_ни_одной_галочки_не_проставлено():
    out = parse_decisions("## Банк тем\n- [ ] Раз\n- [ ] Два")
    assert out["беру"] == [] and len(out["не_решено"]) == 2


def test_все_темы_отклонены():
    out = parse_decisions("## Банк тем\n- [-] Раз\n- [-] Два")
    assert out["беру"] == [] and len(out["нет"]) == 2


def test_дубль_темы_сохраняется_дважды():
    out = parse_decisions("## Банк тем\n- [x] Тема\n- [x] Тема")
    assert out["беру"] == ["Тема", "Тема"]


def test_строки_вне_банка_не_попадают():
    text = """## Банк тем
- [x] Это беру

## Додумать
- [x] Это не беру

вне разделов
- [x] И это не беру"""
    out = parse_decisions(text)
    assert out["беру"] == ["Это беру"]
    assert out["пропущено"] != []  # галочки вне Банка попадают в пропущено


def test_неизвестный_маркер_игнорируется():
    out = parse_decisions("## Банк тем\n- [z] Тема")
    assert all(len(v) == 0 for k, v in out.items() if k != "пропущено")
    assert len(out["пропущено"]) > 0


def test_регистр_маркера_не_важен():
    out = parse_decisions("## Банк тем\n- [X] Тема")
    assert out["беру"] == ["Тема"]


def test_тема_с_точкой_посередине():
    """Critical 1: режет только по литералу '· откуда:', не по любому ·"""
    text = """## Банк тем
- [x] Идея для эфира · с гостем · откуда: чат"""
    out = parse_decisions(text)
    assert out["беру"] == ["Идея для эфира · с гостем"]


def test_маркер_звездочка_вместо_минуса():
    """Critical 2: принимаем оба маркера - и *"""
    text = """## Банк тем
* [x] Первая
- [x] Вторая"""
    out = parse_decisions(text)
    assert out["беру"] == ["Первая", "Вторая"]


def test_вложенная_строка_с_отступом():
    """Critical 2: вложенный подпункт не считается отдельной темой"""
    text = """## Банк тем
- [x] Основная тема
  - [x] Уточнение к теме"""
    out = parse_decisions(text)
    assert out["беру"] == ["Основная тема"]
    assert any("Уточнение к теме" in s for s in out["пропущено"])


def test_галочка_в_разделе_додумать():
    """Critical 2: разбираем только внутри 'Банк тем'"""
    text = """## Банк тем
- [x] Это беру

## Додумать
- [x] Это не беру"""
    out = parse_decisions(text)
    assert out["беру"] == ["Это беру"]
    assert "- [x] Это не беру" in out["пропущено"]


def test_галочка_в_блоке_кода():
    """Critical 2: пропускаем содержимое блоков кода"""
    text = """## Банк тем
- [x] Реальная тема

```
- [x] Это пример в блоке кода
```"""
    out = parse_decisions(text)
    assert out["беру"] == ["Реальная тема"]
    assert out["пропущено"] == []


def test_пустая_тема():
    """Important: пустая тема не попадает в список, а в пропущено"""
    text = """## Банк тем
- [x]
- [x] · откуда: файл"""
    out = parse_decisions(text)
    assert out["беру"] == []
    assert len(out["пропущено"]) == 2


def test_неизвестный_маркер_в_пропущено():
    """Critical 3: неизвестные маркеры попадают в пропущено"""
    text = """## Банк тем
- [z] Неизвестный маркер"""
    out = parse_decisions(text)
    assert out["пропущено"] == ["- [z] Неизвестный маркер"]
    assert all(len(v) == 0 for k, v in out.items() if k != "пропущено")


def test_строка_вне_разделов():
    """Critical 2: строки с галочкой вне раздела Банк тем попадают в пропущено"""
    text = """случайный текст
- [x] Это не в разделе"""
    out = parse_decisions(text)
    assert out["беру"] == []
    assert out["пропущено"] == ["- [x] Это не в разделе"]


def test_галочка_без_единого_заголовка_уходит_в_пропущено():
    """Critical: строка с галочкой без раздела Банк тем не исчезает"""
    out = parse_decisions("- [x] Бесхозная")
    assert out["беру"] == []
    assert out["пропущено"] == ["- [x] Бесхозная"]


def test_галочка_выше_раздела_банк_тем():
    """Critical: строка с галочкой ДО раздела Банк тем не игнорируется"""
    text = """- [x] До раздела

## Банк тем
- [x] В разделе"""
    out = parse_decisions(text)
    assert out["беру"] == ["В разделе"]
    assert "- [x] До раздела" in out["пропущено"]


def test_незакрытый_блок_кода_внутри_раздела():
    """Critical: незакрытый блок кода теряет строки молча"""
    text = """## Банк тем

- [x] До блока
```
- [x] После открытия блока"""
    out = parse_decisions(text)
    assert out["беру"] == ["До блока"]
    assert "- [x] После открытия блока" in out["пропущено"]


def test_незакрытый_блок_кода_до_раздела():
    """Critical: незакрытый блок, открытый до раздела, не блокирует разбор"""
    text = """```
- [x] Это в блоке

## Банк тем
- [x] Это должно быть в беру
- [x] Это тоже"""
    out = parse_decisions(text)
    # Раздел должен быть найден несмотря на открытый блок до него
    # Строка в открытом блоке идёт в пропущено (она незакрытого блока)
    assert out["беру"] == ["Это должно быть в беру", "Это тоже"]
    assert "- [x] Это в блоке" in out["пропущено"]


def test_заголовок_строчными_буквами():
    """Important: заголовок распознаётся без учёта регистра"""
    text = """## банк тем
- [x] Первая
- [?] Вторая"""
    out = parse_decisions(text)
    assert out["беру"] == ["Первая"]
    assert out["подумать"] == ["Вторая"]


def test_заголовок_с_двойным_пробелом():
    """Important: заголовок распознаётся с любым количеством пробелов"""
    text = """##  Банк тем
- [x] Первая"""
    out = parse_decisions(text)
    assert out["беру"] == ["Первая"]


# --- строки_банка --------------------------------------------------------
#
# parse_decisions отдаёт только очищенный текст темы (без "· откуда:
# источник") — этого достаточно для группировки по решению, но не хватает,
# если важна вся строка целиком: например, два одинаковых текста темы из
# разных источников после очистки становятся неотличимы друг от друга.


def test_строки_банка_совпадает_с_parse_decisions_по_количеству_и_порядку():
    out = parse_decisions(БАНК)
    подробности = строки_банка(БАНК)
    assert len(подробности) == sum(len(out[к]) for к in ("беру", "подумать", "нет", "не_решено"))
    # Порядок и состав тем в подробности — те же, что и в parse_decisions,
    # сгруппированные по состоянию в порядке появления в файле.
    по_состояниям: dict[str, list[str]] = {"беру": [], "подумать": [], "нет": [], "не_решено": []}
    for з in подробности:
        по_состояниям[з["состояние"]].append(з["тема"])
    assert по_состояниям == {к: out[к] for к in по_состояниям}


def test_содержимое_включает_источник_а_тема_очищена():
    out = строки_банка("## Банк тем\n- [ ] Моя тема · откуда: чат")
    [запись] = out
    assert запись["тема"] == "Моя тема"
    assert запись["содержимое"] == "Моя тема · откуда: чат"


def test_без_источника_содержимое_равно_теме():
    out = строки_банка("## Банк тем\n- [ ] Тема без источника")
    [запись] = out
    assert запись["тема"] == "Тема без источника"
    assert запись["содержимое"] == "Тема без источника"


def test_одинаковая_тема_разные_источники_дают_разное_содержимое():
    text = (
        "## Банк тем\n"
        "- [ ] Тема про запуск курса · откуда: чат\n"
        "- [ ] Тема про запуск курса · откуда: трендвотчинг\n"
    )
    записи = строки_банка(text)
    assert [з["тема"] for з in записи] == ["Тема про запуск курса", "Тема про запуск курса"]
    содержимое = [з["содержимое"] for з in записи]
    assert содержимое[0] != содержимое[1]


def test_строки_банка_пустой_текст_даёт_пустой_список():
    assert строки_банка("") == []


def test_строки_банка_нестроковый_текст_бросает_ошибку_как_и_parse_decisions():
    # строки_банка и parse_decisions разбирают текст одним и тем же
    # внутренним проходом — оба одинаково не защищены от нестрокового
    # входа (это не контракт, который меняет эта задача).
    with pytest.raises(AttributeError):
        строки_банка(None)
