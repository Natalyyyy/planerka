"""Личный контекст: кривой конфиг не убивает прогон.

SKILL.md прямо зовёт править конфиг руками, значит поля приезжают в любом
виде. Раздел, который не собрать, просто не выводится.
"""
from pathlib import Path

import pytest

from planerka.runner.person import личный_контекст


@pytest.mark.parametrize("частота", [
    ["телеграм: 2 поста"],           # список вместо словаря
    "телеграм: 2 поста",             # строка
    None,                            # пусто
    0,                               # число
])
def test_кривая_частота_площадок_не_роняет(tmp_path, частота):
    out = личный_контекст({"частота_площадок": частота}, tmp_path)
    assert "Частота по площадкам" not in out


def test_нормальная_частота_выводится(tmp_path):
    out = личный_контекст({"частота_площадок": {"телеграм": "два поста"}}, tmp_path)
    assert "Частота по площадкам" in out and "два поста" in out


def test_кривой_язык_не_роняет(tmp_path):
    assert "## Язык" not in личный_контекст({"язык": None}, tmp_path)
    assert "## Язык" not in личный_контекст({"язык": ["ru"]}, tmp_path)


def test_пустой_конфиг_даёт_пустую_строку(tmp_path):
    assert личный_контекст({}, tmp_path) == ""
