"""Тесты общей атомарной записи/чтения файла недели.

Раньше одна и та же пара строк («написать во временный файл рядом, потом
os.replace») была продублирована в takt_a.py, takt_b.py, отправке и приёме
нажатий — здесь общий модуль, и здесь же держится то, что защищает работу
человека: атомарность записи под конкурентными писателями и точное
сохранение переводов строк при чтении.
"""
import threading
from pathlib import Path

import pytest

from planerka.runner.файлы import записать_атомарно, прочесть_как_есть


# --- happy path ------------------------------------------------------


def test_записать_атомарно_создаёт_файл_с_содержимым(tmp_path):
    путь = tmp_path / "файл.md"
    записать_атомарно(путь, "содержимое\n")
    assert путь.read_text(encoding="utf-8") == "содержимое\n"


def test_записать_атомарно_заменяет_существующий_файл(tmp_path):
    путь = tmp_path / "файл.md"
    путь.write_text("старое\n", encoding="utf-8")
    записать_атомарно(путь, "новое\n")
    assert путь.read_text(encoding="utf-8") == "новое\n"


def test_прочесть_как_есть_читает_обычный_lf_файл(tmp_path):
    путь = tmp_path / "файл.md"
    путь.write_text("строка раз\nстрока два\n", encoding="utf-8")
    assert прочесть_как_есть(путь) == "строка раз\nстрока два\n"


# --- edge --------------------------------------------------------------


def test_прочесть_как_есть_сохраняет_crlf_дословно(tmp_path):
    путь = tmp_path / "файл.md"
    путь.write_bytes("строка раз\r\nстрока два\r\n".encode("utf-8"))
    # Без newline="" universal-newlines чтение схлопнуло бы \r\n в \n —
    # именно этот дефект и чинится прочесть_как_есть.
    assert прочесть_как_есть(путь) == "строка раз\r\nстрока два\r\n"


def test_записать_атомарно_не_переводит_переводы_строк(tmp_path):
    путь = tmp_path / "файл.md"
    # Содержимое уже несёт «родные» \r\n (например, было прочитано
    # прочесть_как_есть с CRLF-файла) — запись не должна их менять.
    содержимое = "строка\r\nдругая строка\r\n"
    записать_атомарно(путь, содержимое)
    assert путь.read_bytes() == содержимое.encode("utf-8")


def test_два_писателя_подряд_не_рвут_атомарность_общим_tmp_именем(tmp_path):
    """Раньше временный файл всегда назывался `<файл>.tmp` — одинаково для
    приёма, такта А и такта Б. Два писателя, попавших в одно и то же окно,
    делят один и тот же временный файл: один вызов может дописывать во
    временный файл, который другой уже подменил или удалил под собой —
    получается либо половинчатое содержимое, либо `FileNotFoundError`
    у одного из писателей. `tempfile.mkstemp` даёт каждому писателю
    собственное уникальное имя — гонки быть не должно."""
    путь = tmp_path / "неделя – 2026-09-07.md"
    путь.write_text("исходное\n", encoding="utf-8")

    содержимое_a = "A" * 50_000 + "\n"
    содержимое_b = "B" * 50_000 + "\n"
    ошибки: list[Exception] = []

    def писать(содержимое: str) -> None:
        try:
            записать_атомарно(путь, содержимое)
        except Exception as ошибка:  # фиксируем, а не роняем поток теста
            ошибки.append(ошибка)

    поток_a = threading.Thread(target=писать, args=(содержимое_a,))
    поток_b = threading.Thread(target=писать, args=(содержимое_b,))
    поток_a.start()
    поток_b.start()
    поток_a.join()
    поток_b.join()

    assert ошибки == [], f"писатели упали: {ошибки}"
    итог = путь.read_text(encoding="utf-8")
    # Итог — полностью содержимое ОДНОГО из писателей, не смесь и не огрызок.
    assert итог in (содержимое_a, содержимое_b), (
        f"содержимое длиной {len(итог)} — не совпадает целиком ни с одним "
        "из писателей, значит запись где-то смешалась"
    )


# --- error ---------------------------------------------------------------


def test_прочесть_как_есть_файла_нет_бросает_os_error(tmp_path):
    with pytest.raises(OSError):
        прочесть_как_есть(tmp_path / "нет-такого.md")
