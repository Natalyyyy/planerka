def test_бот_настроен_отправляет_банк_в_телеграм(мир):
    """Такт А — единственное место, откуда вообще уходит отправка банка:
    без этого вызова кнопки в телеграме не появятся никогда, даже если
    клиент Bot API и отправка банка полностью готовы и оттестированы
    сами по себе (задача 2)."""
    конфиг, заметки, блоки = мир
    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        путь = takt_a(
            конфиг, заметки, блоки, date(2026, 9, 5),
            зов=lambda *a, **k: "## Банк тем\n\n- [ ] Тема · откуда: заметки",
            бот_токен="333333:ВЫДУМАННЫЙ-ТОКЕН-НЕ-НАСТОЯЩИЙ", бот_chat_id=12345,
        )
    отправить.assert_called_once()
    assert путь.exists()


