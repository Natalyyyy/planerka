def test_отправка_упала_файл_недели_не_теряется(мир, capsys):
    """Файл недели — работа, которую нельзя потерять из-за сети. Сеть
    подводит уже ПОСЛЕ записи файла, и это должно быть видно человеку, а
    не проглочено молча."""
    конфиг, заметки, блоки = мир
    with patch("planerka.bot.отправка.отправить_с_кнопками") as отправить:
        отправить.side_effect = ОшибкаСети("обрыв")
        путь = takt_a(
            конфиг, заметки, блоки, date(2026, 9, 5),
            зов=lambda *a, **k: "## Банк тем\n\n- [ ] Тема · откуда: заметки",
            бот_токен="333333:ВЫДУМАННЫЙ-ТОКЕН-НЕ-НАСТОЯЩИЙ", бот_chat_id=12345,
        )
    assert путь.exists()
    assert "- [ ] Тема · откуда: заметки" in путь.read_text(encoding="utf-8")
    вывод = capsys.readouterr()
    assert "не ушёл" in вывод.out.lower()


