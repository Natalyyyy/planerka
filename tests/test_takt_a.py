def test_токен_из_окружения_называет_бота_при_отправке(мир, capsys):
    """Пункт 3: токен пришёл из окружения процесса, не из .env папки
    заметок — человек должен увидеть, какому боту уходит банк тем, ДО
    того как решит, что что-то пошло не так."""
    конфиг, заметки, блоки = мир
    with patch("planerka.bot.отправка.отправить_с_кнопками"), \
         patch("planerka.runner.takt_a.проверить_токен", return_value="@my_test_bot"):
        takt_a(
            конфиг, заметки, блоки, date(2026, 9, 5),
            зов=lambda *a, **k: "## Банк тем\n\n- [ ] Тема · откуда: заметки",
            бот_токен="333333:ВЫДУМАННЫЙ-ТОКЕН-НЕ-НАСТОЯЩИЙ", бот_chat_id=12345,
            бот_токен_из_окружения=True,
        )
    вывод = capsys.readouterr()
    assert "@my_test_bot" in вывод.out
    assert "TELEGRAM_BOT_TOKEN" in вывод.out
    assert ".env" in вывод.out


