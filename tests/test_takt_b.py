# --- Раунд починки 1: раздел вместо split по литеральной подстроке ---
# Critical: повторный прогон стирал разделы человека после "Неделя по дням".
# Important: split ловил "Неделя по дням" как подстроку где угодно в тексте,
# а не только как заголовок; "Пропущенные пометки" сам себя подпитывал на
# втором прогоне, потому что чек-лист по дням из прошлого ответа модели лежал
# вне "Банка тем" и попадал в parse_decisions как решение человека.

def test_раздел_после_недели_по_дням_цел_после_второго_прогона(мир):
    конфиг, заметки, блоки = мир
    файл_недели = заметки / "недели" / "неделя – 2026-08-31.md"
    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nПервый")

    текст = файл_недели.read_text(encoding="utf-8")
    текст += "\n\n## Личные заметки человека\n\nЭто моя важная приписка, не трогать!\n"
    файл_недели.write_text(текст, encoding="utf-8")

    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nВторой")
    итог = путь.read_text(encoding="utf-8")
    assert "Это моя важная приписка, не трогать!" in итог
    assert "## Личные заметки человека" in итог
    assert "Второй" in итог


def test_раздел_между_банком_и_неделей_по_дням_цел(мир):
    # Заметка стоит и до заголовка "Неделя по дням", и после него — старый
    # `text.split(ЗАГОЛОВОК)` рвёт файл ровно на первом вхождении литерала и
    # теряет всё, что было после реального заголовка (в т.ч. "Другую заметку"
    # ниже). Без второй заметки после заголовка тест проходит и на голом split
    # (заметка-то до заголовка не трогается), поэтому не отличает старый код
    # от нового — этого мало.
    конфиг, заметки, блоки = мир
    файл_недели = заметки / "недели" / "неделя – 2026-08-31.md"
    файл_недели.write_text(
        "## Банк тем\n\n- [x] Взятая тема\n- [?] Спорная тема\n- [-] Ненужная тема\n"
        "\n## Личные заметки человека\n\nВажная приписка между разделами.\n"
        "\n## Неделя по дням\n\nСтарый план\n"
        "\n## Другая заметка человека\n\nЕщё один кусок текста после старого плана.\n",
        encoding="utf-8")
    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nНовый план")
    итог = путь.read_text(encoding="utf-8")
    assert "Важная приписка между разделами." in итог
    assert "Ещё один кусок текста после старого плана." in итог
    assert (
        итог.index("## Банк тем")
        < итог.index("## Личные заметки человека")
        < итог.index("## Неделя по дням")
        < итог.index("## Другая заметка человека")
    )


