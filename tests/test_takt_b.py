def test_повторный_прогон_обновляет_список_пропущенных_без_дублей(мир):
    # Между прогонами человек сам правит "Банк тем": старая непонятная строка
    # ушла, появилась новая, другого рода (не вложенная, а неизвестный
    # маркер) — раздел "Пропущенные пометки" должен отражать текущий источник,
    # а не просто не задваивать заголовок на неизменных данных.
    конфиг, заметки, блоки = мир
    файл_недели = заметки / "недели" / "неделя – 2026-08-31.md"
    файл_недели.write_text(
        "## Банк тем\n\n- [x] Взятая тема\n  - [x] Первая вложенная\n",
        encoding="utf-8")
    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nПервый")

    текст_после_первого = файл_недели.read_text(encoding="utf-8")
    текст_после_первого = текст_после_первого.replace(
        "  - [x] Первая вложенная\n", "- [ф] Новый неизвестный маркер\n"
    )
    файл_недели.write_text(текст_после_первого, encoding="utf-8")

    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nВторой")
    текст = путь.read_text(encoding="utf-8")
    assert текст.count("## Пропущенные пометки") == 1
    assert "Первая вложенная" not in текст
    assert "Новый неизвестный маркер" in текст


