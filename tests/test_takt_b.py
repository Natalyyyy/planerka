def test_три_прогона_подряд_файл_не_растёт_и_не_теряет(мир):
    # Между первым и вторым прогоном человек дописывает свой раздел ПОСЛЕ
    # "Неделя по дням" — без этого файл не содержит посторонних разделов
    # после владеемого, и тест не отличает старый split (который стирает всё
    # после заголовка) от нового кода: и там, и там нечему теряться.
    конфиг, заметки, блоки = мир
    файл_недели = заметки / "недели" / "неделя – 2026-08-31.md"

    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nПервый")
    текст = файл_недели.read_text(encoding="utf-8")
    текст += "\n\n## Заметка человека\n\nЭту приписку три прогона подряд трогать нельзя.\n"
    файл_недели.write_text(текст, encoding="utf-8")

    for метка in ("Второй", "Третий"):
        путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 5),
                       зов=lambda *a, м=метка, **k: f"## Неделя по дням\n\n{м}")
    итог = путь.read_text(encoding="utf-8")
    assert итог.count("## Банк тем") == 1
    assert итог.count("## Неделя по дням") == 1
    assert итог.count("## Заметка человека") == 1
    assert "Третий" in итог and "Первый" not in итог and "Второй" not in итог
    assert "Взятая тема" in итог
    assert "Эту приписку три прогона подряд трогать нельзя." in итог
    assert итог.index("## Неделя по дням") < итог.index("## Заметка человека")


