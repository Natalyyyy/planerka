# --- Пропущенные пометки (пятый ключ parse_decisions, не описан в брифе) ---
# Требование: если из "Банка тем" не разобралась какая-то строка, человек должен
# узнать об этом из самого файла недели, а не потерять пометку молча.

def test_пропущенные_пометки_дописываются_в_файл_недели(мир):
    конфиг, заметки, блоки = мир
    файл_недели = заметки / "недели" / "неделя – 2026-08-31.md"
    файл_недели.write_text(
        "## Банк тем\n\n"
        "- [x] Взятая тема\n"
        "- [ ] Никакая\n"
        "  - [x] Вложенная строка\n"
        "- [q] Неизвестный маркер\n",
        encoding="utf-8")
    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=lambda *a, **k: "## Неделя по дням\n\nПн — Взятая тема")
    текст = путь.read_text(encoding="utf-8")
    assert "## Пропущенные пометки" in текст
    # строки приведены дословно, чтобы человек мог найти их в исходном файле
    assert "  - [x] Вложенная строка" in текст
    assert "- [q] Неизвестный маркер" in текст


