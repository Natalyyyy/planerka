"""Сторож стыка «что ядро велит вывести» ↔ «что разбор умеет прочесть».

Дефект, ради которого тест написан: core.md велел модели выводить банк под
«### Банк тем», а parse_decisions ищет «## Банк тем». Все темы уходили в
«пропущено», такт Б падал. Остальные тесты этого не видели, потому что
хардкодят «## Банк тем» — контракт, которого не было в инструкции,
уезжающей в модель.

Поэтому здесь заголовки не пишутся руками: они достаются из настоящих
файлов блоков.
"""
import re
from pathlib import Path

from planerka.runner.decisions import parse_decisions
from planerka.runner.takt_b import ЗАГОЛОВОК

БЛОКИ = Path(__file__).resolve().parent.parent / "planerka" / "blocks"


def _заголовок(файл: str, название: str) -> str:
    текст = (БЛОКИ / файл).read_text(encoding="utf-8")
    найдено = re.findall(rf"^#+\s*{название}\s*$", текст, re.MULTILINE)
    assert найдено, f"в {файл} нет заголовка «{название}» — инструкция изменилась"
    return найдено[0].strip()


def test_заголовок_банка_из_ядра_распознаётся_разбором():
    банк = _заголовок("core.md", "Банк тем")
    решения = parse_decisions(
        f"{банк}\n\n- [x] Тема одна · откуда: заметка\n- [-] Тема два\n"
    )
    assert решения["беру"] == ["Тема одна"], решения
    assert решения["нет"] == ["Тема два"], решения
    assert решения["пропущено"] == [], решения


def test_заголовок_додумать_из_ядра_закрывает_банк():
    банк = _заголовок("core.md", "Банк тем")
    додумать = _заголовок("core.md", "Додумать")
    решения = parse_decisions(
        f"{банк}\n\n- [x] Настоящая тема\n\n{додумать}\n\n- [x] Не тема, а вопрос\n"
    )
    assert решения["беру"] == ["Настоящая тема"], решения


def test_заголовок_плана_из_ядра_совпадает_с_тем_что_ищет_такт_б():
    план = _заголовок("core-план.md", "Неделя по дням")
    assert план == ЗАГОЛОВОК


def test_в_ядрах_нет_заголовков_глубже_второго_уровня():
    """Разбор считает границей раздела только «## ...» в начале строки.
    Заголовок третьего уровня в ядре — это заголовок, который модель
    выведет, а разбор не увидит."""
    for файл in ("core.md", "core-план.md"):
        текст = (БЛОКИ / файл).read_text(encoding="utf-8")
        глубокие = [с for с in текст.splitlines() if re.match(r"^#{3,}\s", с)]
        assert not глубокие, f"{файл}: {глубокие}"


def test_сквозной_цикл_на_настоящих_блоках(tmp_path):
    """Такт А выводит банк ровно так, как велит настоящий core.md, — и такт Б
    обязан этот банк прочесть. Проверка стыка целиком, без хардкода
    заголовков: именно её отсутствие пропустило «### Банк тем»."""
    from datetime import date
    from planerka.runner.takt_a import takt_a
    from planerka.runner.takt_b import takt_b

    банк = _заголовок("core.md", "Банк тем")
    конфиг = {"источники": [], "площадки": [], "модель": "claude-sonnet-5"}
    заметки = tmp_path / "notes"
    заметки.mkdir()

    takt_a(конфиг, заметки, БЛОКИ, date(2026, 9, 5),
           зов=lambda *a, **k: f"{банк}\n\n- [x] Первая тема · откуда: заметка\n- [ ] Вторая тема")

    # человек ничего не переписывал — файл ровно такой, каким его оставил такт А
    видел = {}

    def зов(prompt, model, **k):
        видел["промпт"] = prompt
        return "## Неделя по дням\n\nПн — Первая тема"

    путь = takt_b(конфиг, заметки, БЛОКИ, date(2026, 9, 5), зов=зов)
    assert "Первая тема" in видел["промпт"], "взятая тема не доехала до такта Б"
    assert "Вторая тема" not in видел["промпт"]
    assert "## Неделя по дням" in путь.read_text(encoding="utf-8")
