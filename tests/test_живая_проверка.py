"""Сторож сценария живой проверки (`docs/живая-проверка.md`).

Живая проверка — единственное место, где бот встречается с настоящим
Телеграмом: автотесты гоняют его на подменённой сети. Поэтому цена ошибки в
самом сценарии выше обычной документации: неверное имя файла-спутника
объявляет исправную систему сломанной, а пропущенный шаг оставляет дыру
именно там, где её и должны были закрыть руками.

Финальное ревью части 2 нашло ровно это: сценарий назвал спутники именами,
которых код не создаёт (`.md.отправлено.json` вместо `.отправлено.json`), и
не проверял ни защиту `.env` от гита, ни самый вероятный сбой первой недели
— нажатие кнопки при незапущенном процессе.
"""
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
СЦЕНАРИЙ = (КОРЕНЬ / "docs" / "живая-проверка.md").read_text(encoding="utf-8")

СПУТНИК_В_ТЕКСТЕ = re.compile(r"неделя – [^`«»\n]*?\.json")


def _шаги() -> dict[str, str]:
    части = re.split(r"^## ", СЦЕНАРИЙ, flags=re.MULTILINE)
    шаги = {ч.splitlines()[0].strip(): ч for ч in части if ч.startswith("Шаг ")}
    assert шаги, "в сценарии не нашлось ни одного шага"
    return шаги


def имена_спутников_из_кода() -> set[str]:
    from planerka.bot.отправка import _файл_состояния
    from planerka.bot.процесс import _файл_состояния_дедлайна

    образец = Path("недели") / "неделя – ГГГГ-ММ-ДД.md"
    return {_файл_состояния(образец).name, _файл_состояния_дедлайна(образец).name}


def test_имена_спутников_из_сценария_совпадают_с_кодом():
    из_сценария = set(СПУТНИК_В_ТЕКСТЕ.findall(СЦЕНАРИЙ))
    assert из_сценария, "сценарий не называет ни одного файла-спутника"
    выдуманные = из_сценария - имена_спутников_из_кода()
    assert not выдуманные, (
        f"сценарий объявляет провалом отсутствие файла с именем, которого код "
        f"не создаёт: {sorted(выдуманные)}")


def test_сценарий_не_приписывает_спутнику_расширение_файла_недели():
    """`.md.отправлено.json` — то самое имя, из-за которого исправная система
    читалась как сломанная."""
    assert ".md.отправлено.json" not in СЦЕНАРИЙ
    assert ".md.дедлайн-обработан.json" not in СЦЕНАРИЙ


def test_есть_шаг_про_гит():
    """У человека папка заметок — обычно волт под гитом, и `.env` с боевым
    токеном там первым же коммитом уезжает в историю."""
    подходят = [
        имя for имя, текст in _шаги().items()
        if "git status" in текст and ".env" in текст
    ]
    assert подходят, "в сценарии нет шага, проверяющего, что .env не виден гиту"


def test_есть_шаг_про_незапущенный_процесс():
    """Такт А шлёт банк напрямую: кнопки приходят и без запущенного процесса,
    а нажатие тогда не делает ничего. Самый вероятный сбой первой недели —
    и до ревью он не проверялся ничем."""
    подходят = [
        имя for имя, текст in _шаги().items()
        if "остановит" in текст.lower() and "не запущен" in текст.lower()
    ]
    assert подходят, (
        "в сценарии нет шага «остановить процесс, нажать кнопку, убедиться, "
        "что ничего не произошло»")


def test_шаг_про_нажатия_говорит_что_проверить_первым_делом():
    шаг = [т for и, т in _шаги().items() if "кнопк" in и.lower() and "нажать" in и.lower()]
    assert шаг, "в сценарии нет шага про нажатие кнопок"
    низом = шаг[0].lower()
    assert "терминал" in низом, (
        "шаг про нажатия не говорит проверить, жив ли терминал с ботом")
    assert "первым делом" in низом or "сначала посмотрите" in низом, (
        "шаг про нажатия не говорит, что терминал с ботом проверяют ПЕРВЫМ "
        "делом — иначе живой человек начнёт с токена и настроек")


def test_сценарий_предупреждает_про_полночь():
    """«Дедлайн через 5–10 минут» ломается около полуночи: день недели в
    конфиге тот же, а момент уезжает на сутки назад."""
    низом = СЦЕНАРИЙ.lower()
    assert "полноч" in низом or "полуноч" in низом, (
        "сценарий не оговаривает, что приём с дедлайном через 5–10 минут "
        "не работает около полуночи")
