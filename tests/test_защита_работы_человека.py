"""Такт А не имеет права молча переписать файл, в котором работал человек.

Файл недели — это работа человека: он неделю расставляет в нём галочки и
дописывает свои разделы. Такт А писал этот файл с нуля при каждом прогоне,
а скилл сам предлагает прогон перезапустить. Разметка, собранный план и
собственный текст человека исчезали без единой строки в выводе.

Здесь проверяется вся защита: отказ, внятная строка, черновик нового банка
рядом, намеренная пересборка флагом и то, что чистый повторный прогон
(файл без отметок и без чужих разделов) работает ровно как раньше.
"""
import json
import os
import shutil
import subprocess
import sys
from datetime import date, timedelta
from pathlib import Path

import pytest

from planerka.runner.takt_a import takt_a
from planerka.runner.weeks import найти_файл_недели

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПЛАГИН = КОРЕНЬ / "planerka"
README = (КОРЕНЬ / "README.md").read_text(encoding="utf-8")
СКИЛЛ = (ПЛАГИН / "skills" / "planerka" / "SKILL.md").read_text(encoding="utf-8")

ПОНЕДЕЛЬНИК = date(2026, 8, 31)

С_РАБОТОЙ_ЧЕЛОВЕКА = (
    "## Банк тем\n\n"
    "- [x] Взятая тема · откуда: заметка\n"
    "- [ ] Нерешённая тема\n\n"
    "## Неделя по дням\n\n"
    "Пн — Взятая тема\n\n"
    "## Мои заметки\n\n"
    "созвон в четверг, про него тоже надо написать\n"
)


@pytest.fixture
def мир(tmp_path):
    блоки = tmp_path / "blocks"
    (блоки / "sources").mkdir(parents=True)
    (блоки / "platforms").mkdir()
    (блоки / "core.md").write_text("ЯДРО", encoding="utf-8")
    заметки = tmp_path / "notes"
    (заметки / "недели").mkdir(parents=True)
    конфиг = {"источники": [], "площадки": [], "модель": "claude-sonnet-5"}
    return конфиг, заметки, блоки


def _неделя(заметки: Path, дата: str, текст: str) -> Path:
    файл = заметки / "недели" / f"неделя – {дата}.md"
    файл.write_text(текст, encoding="utf-8")
    return файл


def _новый_банк(*a, **k):
    return "## Банк тем\n\n- [ ] Новая тема · откуда: заметка"


def test_файл_с_отметками_человека_не_перезаписывается(мир):
    конфиг, заметки, блоки = мир
    файл = _неделя(заметки, "2026-08-31", С_РАБОТОЙ_ЧЕЛОВЕКА)

    with pytest.raises(RuntimeError, match="пересобрать"):
        takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК, зов=_новый_банк)

    assert файл.read_text(encoding="utf-8") == С_РАБОТОЙ_ЧЕЛОВЕКА


def test_отказ_называет_файл_и_то_что_в_нём_нашлось(мир):
    конфиг, заметки, блоки = мир
    _неделя(заметки, "2026-08-31", С_РАБОТОЙ_ЧЕЛОВЕКА)

    with pytest.raises(RuntimeError) as упало:
        takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК, зов=_новый_банк)

    сообщение = str(упало.value)
    assert "Внимание" in сообщение
    assert "неделя – 2026-08-31.md" in сообщение
    assert "Мои заметки" in сообщение
    assert "--пересобрать" in сообщение


def test_чужой_раздел_защищает_файл_даже_без_единой_отметки(мир):
    """Отметок нет, но человек дописал свой раздел — это тоже его работа."""
    конфиг, заметки, блоки = мир
    было = ("## Банк тем\n\n- [ ] Тема\n\n"
            "## Мои заметки\n\nсвой текст\n")
    файл = _неделя(заметки, "2026-08-31", было)

    with pytest.raises(RuntimeError, match="пересобрать"):
        takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК, зов=_новый_банк)

    assert файл.read_text(encoding="utf-8") == было


def test_одной_отложенной_отметки_хватает_чтобы_не_трогать_файл(мир):
    конфиг, заметки, блоки = мир
    было = "## Банк тем\n\n- [?] Спорная тема\n- [ ] Другая\n"
    файл = _неделя(заметки, "2026-08-31", было)

    with pytest.raises(RuntimeError, match="пересобрать"):
        takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК, зов=_новый_банк)

    assert файл.read_text(encoding="utf-8") == было


def test_новый_банк_ложится_рядом_черновиком_и_такт_б_его_не_подхватит(мир):
    """Прогон к модели уже сделан — его результат не выбрасывается, но и в
    оборот не попадает: черновик лежит рядом для переноса руками."""
    конфиг, заметки, блоки = мир
    файл = _неделя(заметки, "2026-08-31", С_РАБОТОЙ_ЧЕЛОВЕКА)

    with pytest.raises(RuntimeError):
        takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК, зов=_новый_банк)

    черновик = заметки / "недели" / "неделя – 2026-08-31 (новый банк).md"
    assert черновик.exists()
    assert "Новая тема" in черновик.read_text(encoding="utf-8")
    assert найти_файл_недели(заметки) == файл


def test_пересобрать_переписывает_банк_и_сохраняет_прежний_файл(мир, capsys):
    конфиг, заметки, блоки = мир
    файл = _неделя(заметки, "2026-08-31", С_РАБОТОЙ_ЧЕЛОВЕКА)

    путь = takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК,
                  зов=_новый_банк, пересобрать=True)

    assert путь == файл
    стало = файл.read_text(encoding="utf-8")
    assert "Новая тема" in стало
    assert "Мои заметки" not in стало

    копии = list((заметки / "недели" / "архив").glob("*.md"))
    assert len(копии) == 1
    assert копии[0].read_text(encoding="utf-8") == С_РАБОТОЙ_ЧЕЛОВЕКА
    assert копии[0].name in capsys.readouterr().out


def test_вторая_пересборка_не_затирает_первую_копию(мир):
    конфиг, заметки, блоки = мир
    _неделя(заметки, "2026-08-31", С_РАБОТОЙ_ЧЕЛОВЕКА)

    takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК, зов=_новый_банк, пересобрать=True)
    takt_a(конфиг, заметки, блоки, ПОНЕДЕЛЬНИК,
           зов=lambda *a, **k: "## Банк тем\n\n- [ ] Третья тема", пересобрать=True)

    копии = sorted((заметки / "недели" / "архив").glob("*.md"))
    assert len(копии) == 2
    тексты = [к.read_text(encoding="utf-8") for к in копии]
    assert any("Мои заметки" in т for т in тексты)
    assert any("Новая тема" in т for т in тексты)


