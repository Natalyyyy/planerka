# --- Тот же отказ, но через настоящий запуск run.py ---
# Внятная строка — это то, что человек видит в терминале, а не текст внутри
# исключения: отказ обязан выглядеть сообщением, а не трейсбеком.

ЗАГЛУШКА = """#!/bin/sh
cat > /dev/null
printf '## Банк тем\\n\\n- [ ] Тема из заглушки\\n'
"""


@pytest.fixture
def установка(tmp_path):
    корень = tmp_path / "кэш-плагинов" / "planerka-7c21"
    корень.parent.mkdir(parents=True)
    shutil.copytree(ПЛАГИН, корень,
                    ignore=shutil.ignore_patterns("__pycache__", ".pytest_cache"))

    заметки = tmp_path / "мои-заметки"
    (заметки / "недели").mkdir(parents=True)
    (заметки / "конфиг.json").write_text(json.dumps({
        "папка_заметок": str(заметки),
        "модель": "claude-sonnet-5",
        "источники": [],
        "площадки": [],
    }, ensure_ascii=False), encoding="utf-8")

    бин = tmp_path / "бин"
    бин.mkdir()
    (бин / "claude").write_text(ЗАГЛУШКА, encoding="utf-8")
    (бин / "claude").chmod(0o755)

    дом = tmp_path / "дом"
    дом.mkdir()

    def запустить(*аргументы):
        окружение = {**os.environ,
                     "PATH": f"{бин}:{os.environ['PATH']}",
                     "HOME": str(дом)}
        окружение.pop("PYTHONPATH", None)
        return subprocess.run(
            [sys.executable, str(корень / "run.py"), *аргументы],
            cwd=tmp_path, env=окружение, capture_output=True, text=True, timeout=120)

    return запустить, заметки


def _файл_этой_недели(заметки: Path) -> Path:
    сегодня = date.today()
    начало = сегодня - timedelta(days=сегодня.weekday())
    return заметки / "недели" / f"неделя – {начало}.md"


def test_запуск_отказывается_сообщением_а_не_трейсбеком(установка):
    запустить, заметки = установка
    файл = _файл_этой_недели(заметки)
    файл.write_text(С_РАБОТОЙ_ЧЕЛОВЕКА, encoding="utf-8")

    готово = запустить("темы", "--папка", str(заметки))

    assert готово.returncode != 0
    assert "Traceback" not in готово.stderr
    assert "Внимание" in готово.stderr
    assert "--пересобрать" in готово.stderr
    assert файл.read_text(encoding="utf-8") == С_РАБОТОЙ_ЧЕЛОВЕКА


def test_запуск_с_флагом_пересобирает_банк(установка):
    запустить, заметки = установка
    файл = _файл_этой_недели(заметки)
    файл.write_text(С_РАБОТОЙ_ЧЕЛОВЕКА, encoding="utf-8")

    готово = запустить("темы", "--папка", str(заметки), "--пересобрать")

    assert готово.returncode == 0, готово.stderr
    assert "Тема из заглушки" in файл.read_text(encoding="utf-8")
    assert list((заметки / "недели" / "архив").glob("*.md"))


def test_флаг_пересобрать_не_принимается_тактом_план(установка):
    запустить, заметки = установка

    готово = запустить("план", "--папка", str(заметки), "--пересобрать")

    assert готово.returncode != 0
    assert "только с тактом" in готово.stderr
    assert "Traceback" not in готово.stderr
