"""Сторож стыка «что интервью предлагает» ↔ «для чего есть блок промпта».

Девять источников и три площадки перечислены словами в тексте интервью, а
сборка промпта берёт файлы из `blocks/`. Ничто эти два списка не сверяло:
переименованный пункт интервью проходил все тесты, а у человека такт А падал
посреди недельного прогона — `assemble` не находит блок с таким именем.
"""
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1] / "planerka"
ИНТЕРВЬЮ = (КОРЕНЬ / "skills" / "planerka-setup" / "SKILL.md").read_text(encoding="utf-8")

ПУНКТ = re.compile(r"^-\s+`([^`]+)`\s+—", re.MULTILINE)


def _раздел(заголовок: str) -> str:
    части = re.split(r"^## ", ИНТЕРВЬЮ, flags=re.MULTILINE)
    для = [ч for ч in части if ч.startswith(заголовок)]
    assert для, f"в интервью нет раздела «{заголовок}» — текст изменился"
    return для[0]


def источники_из_интервью() -> set[str]:
    имена = set(ПУНКТ.findall(_раздел("Блок 1. Источники")))
    assert имена, "в блоке 1 интервью не нашлось ни одного источника списком"
    return имена


def площадки_из_интервью() -> set[str]:
    раздел = _раздел("Блок 3. Площадки и ритм")
    строки = [с for с in раздел.splitlines() if "blocks/platforms/" in с]
    assert строки, "в блоке 3 интервью не нашлось строки со списком площадок"
    имена = {и for и in re.findall(r"`([^`]+)`", строки[0]) if "/" not in и}
    assert имена, "в строке про площадки не нашлось ни одного имени"
    return имена


def файлы_блоков(подпапка: str) -> set[str]:
    имена = {ф.stem for ф in (КОРЕНЬ / "blocks" / подпапка).glob("*.md")}
    assert имена, f"в blocks/{подпапка} нет ни одного блока"
    return имена


def test_у_каждого_источника_из_интервью_есть_блок():
    нет_блока = источники_из_интервью() - файлы_блоков("sources")
    assert not нет_блока, f"интервью предлагает источники без блока: {sorted(нет_блока)}"


def test_каждый_блок_источника_назван_в_интервью():
    не_предложены = файлы_блоков("sources") - источники_из_интервью()
    assert not не_предложены, f"блоки есть, а интервью их не предлагает: {sorted(не_предложены)}"


def test_у_каждой_площадки_из_интервью_есть_блок():
    нет_блока = площадки_из_интервью() - файлы_блоков("platforms")
    assert not нет_блока, f"интервью предлагает площадки без блока: {sorted(нет_блока)}"


def test_каждый_блок_площадки_назван_в_интервью():
    не_предложены = файлы_блоков("platforms") - площадки_из_интервью()
    assert not не_предложены, f"блоки есть, а интервью их не предлагает: {sorted(не_предложены)}"


# --- Часть 2: интервью зовёт бота. Стык «что интервью обещает» ↔ «что есть в коде».
#
# Блок 2 перестал быть текстом про один формат: он спрашивает про телеграм-бота,
# диктует команды с именами функций из `planerka/bot/api.py`, называет переменные
# окружения, маркеры решений и подписи кнопок. Всё это — обещания, которые
# выполняет код, а не текст. Разошлись — человек проходит интервью до конца и
# получает молчащего бота: ни одна проверка при этом не краснеет, потому что
# интервью не исполняется тестами, оно исполняется живым Клодом по инструкции.
#
# Блок 3 добавляет второй стык: строка дедлайна, которую интервью велит записать
# в конфиг, обязана разбираться той самой функцией, которая её потом читает.
# Прошлая редакция просила «день и время» свободной строкой, «среда 20:00» без
# запятой не разбиралось, и дедлайн такта Б не срабатывал ни разу — молча.

import json

from planerka import run
from planerka.bot import api, отправка
from planerka.bot.процесс import _ДНИ_НЕДЕЛИ, _разобрать_дедлайн
from planerka.runner import decisions

# Форматы решений перечислены в преамбуле блока 2 списком `- **имя** — описание`.
ФОРМАТ = re.compile(r"^-\s+\*\*([^*]+)\*\*\s+—", re.MULTILINE)
# «`[x]` беру,» / «`[ ]` не решено.» — маркер в кавычках и его человеческое имя.
МАРКЕР = re.compile(r"`\[(.)\]`\s+([^,.;]+)")
ПЕРЕМЕННАЯ_ОКРУЖЕНИЯ = re.compile(r"\bTELEGRAM_[A-Z_]+\b")
ИМПОРТ_ИЗ_API = re.compile(r"^\s*from bot\.api import (.+)$", re.MULTILINE)
СТРОКА_ТАБЛИЦЫ = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`", re.MULTILINE)

# Формат решений, названный в интервью, — это обещание, что где-то в коде он
# реализован. Таблица связывает название с тем, что его исполняет: новое имя в
# интервью без записи здесь (и без работающего кода за ней) роняет тест.
РЕАЛИЗАЦИЯ_ФОРМАТА = {
    "галочки в файле": (decisions, "parse_decisions"),
    "кнопки в боте": (отправка, "отправить_банк_тем"),
}


def _подраздел_блока_2(заголовок: str) -> str:
    """Подраздел блока 2 (`#### Заголовок`) — чтобы проверка попадала в него, а
    не в блок целиком: обещания у бота-который-есть и бота-которого-нет разные."""
    части = re.split(r"^#### ", _раздел("Блок 2."), flags=re.MULTILINE)
    для = [ч for ч in части if ч.startswith(заголовок)]
    assert для, f"в блоке 2 интервью нет подраздела «{заголовок}»"
    return для[0]


def _преамбула_блока_2() -> str:
    """Часть блока 2 до первого `###` — там перечислены форматы решений."""
    раздел = _раздел("Блок 2.")
    return re.split(r"^### ", раздел, flags=re.MULTILINE)[0]


def форматы_из_интервью() -> set[str]:
    имена = set(ФОРМАТ.findall(_преамбула_блока_2()))
    assert имена, "в блоке 2 интервью не нашлось ни одного формата решений списком"
    return имена


def маркеры_из_интервью() -> dict[str, str]:
    найдено = {м: имя.strip().replace(" ", "_") for м, имя in МАРКЕР.findall(_преамбула_блока_2())}
    assert найдено, "в блоке 2 интервью не нашлось ни одного маркера решения"
    return найдено


def подписи_кнопок_из_интервью() -> set[str]:
    строки = [с for с in _преамбула_блока_2().splitlines() if "кнопки в боте" in с]
    assert строки, "в блоке 2 интервью нет строки про кнопки в боте"
    подписи = set(re.findall(r"«([^»]+)»", строки[0]))
    assert подписи, "в строке про кнопки не нашлось ни одной подписи в кавычках"
    return подписи


def конфиг_из_интервью() -> dict:
    блоки = re.findall(r"```json\n(.*?)```", ИНТЕРВЬЮ, flags=re.DOTALL)
    assert блоки, "в интервью нет примера конфига в блоке ```json"
    return json.loads(блоки[-1])


def _дни_недели_из_интервью() -> set[str]:
    раздел = _раздел("Блок 3. Площадки и ритм")
    строки = [с for с in раздел.splitlines() if "Дни недели" in с]
    assert строки, "в блоке 3 интервью нет строки со списком дней недели"
    return set(re.findall(r"`([^`]+)`", строки[0]))


# --- формат решений


def test_каждый_формат_решений_из_интервью_реализован_в_коде():
    без_реализации = форматы_из_интервью() - set(РЕАЛИЗАЦИЯ_ФОРМАТА)
    assert not без_реализации, (
        f"интервью называет формат решений, за которым ничего не стоит: {sorted(без_реализации)}")
    for формат in форматы_из_интервью():
        модуль, имя = РЕАЛИЗАЦИЯ_ФОРМАТА[формат]
        assert hasattr(модуль, имя), (
            f"формат «{формат}» должен исполнять {модуль.__name__}.{имя}, а такого имени нет")


def test_каждый_реализованный_формат_решений_назван_в_интервью():
    не_предложены = set(РЕАЛИЗАЦИЯ_ФОРМАТА) - форматы_из_интервью()
    assert not не_предложены, (
        f"код умеет форматы, а интервью про них молчит: {sorted(не_предложены)}")


def test_формат_решений_в_примере_конфига_из_числа_названных():
    значение = конфиг_из_интервью().get("формат_решений")
    assert значение in форматы_из_интервью(), (
        f"в примере конфига формат_решений = {значение!r}, а блок 2 такого формата не называет")


