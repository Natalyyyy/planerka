def test_интервью_даёт_завести_бота_через_botfather():
    """Проверяется именно подраздел «Бота нет», а не блок 2 целиком: @BotFather
    упоминается в блоке несколько раз (в том числе там, где у человека бот УЖЕ
    есть), и `"@BotFather" in блок` остался бы истинным даже с полностью
    выпотрошенными шагами заведения."""
    шаги = _подраздел_блока_2("Бота нет")
    assert "@BotFather" in шаги, "у кого бота нет — интервью обязано его завести, а не отступить"
    assert "/newbot" in шаги, "шаги через @BotFather диктуются дословно, /newbot — первый из них"
    пронумерованные = re.findall(r"^\d+\. ", шаги, re.MULTILINE)
    assert len(пронумерованные) >= 3, (
        f"шагов заведения бота должно быть три, а размечено {len(пронумерованные)}: "
        "«зайдите в настройки и найдите» вместо шагов — это и есть место, где человек отваливается")


