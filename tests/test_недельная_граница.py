"""Пауза между тактами, пересёкшая понедельник, не должна ломать цикл.

Такт А писал файл по понедельнику своей даты, такт Б искал файл по
понедельнику своей. Любая пауза через границу недели давала либо падение
(«нет файла недели» на новый понедельник), либо тихую потерю: такт А заводил
новый файл, а неделя размеченных решений оставалась мёртвой и никто об этом
не говорил.
"""
import pytest
from datetime import date

from planerka.runner.takt_a import takt_a
from planerka.runner.takt_b import takt_b


@pytest.fixture
def мир(tmp_path):
    блоки = tmp_path / "blocks"
    (блоки / "sources").mkdir(parents=True)
    (блоки / "platforms").mkdir()
    (блоки / "core.md").write_text("ЯДРО", encoding="utf-8")
    (блоки / "core-план.md").write_text("ЯДРО-ПЛАН", encoding="utf-8")
    заметки = tmp_path / "notes"
    (заметки / "недели").mkdir(parents=True)
    конфиг = {"источники": [], "площадки": [], "модель": "claude-sonnet-5"}
    return конфиг, заметки, блоки


def _неделя(заметки, дата: str, текст: str):
    файл = заметки / "недели" / f"неделя – {дата}.md"
    файл.write_text(текст, encoding="utf-8")
    return файл


def test_такт_б_в_новый_понедельник_берёт_файл_прошлой_недели(мир):
    """Такт А в пятницу 04.09 → файл 2026-08-31. Такт Б в понедельник 07.09
    обязан работать с ним, а не искать несуществующий 2026-09-07."""
    конфиг, заметки, блоки = мир
    файл = _неделя(заметки, "2026-08-31", "## Банк тем\n\n- [x] Взятая тема\n")

    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 7),
                  зов=lambda *a, **k: "## Неделя по дням\n\nПн — Взятая тема")

    assert путь == файл
    assert "## Неделя по дням" in файл.read_text(encoding="utf-8")


def test_такт_б_берёт_свежайший_файл_с_банком(мир):
    конфиг, заметки, блоки = мир
    _неделя(заметки, "2026-08-24", "## Банк тем\n\n- [x] Старая тема\n")
    свежий = _неделя(заметки, "2026-08-31", "## Банк тем\n\n- [x] Свежая тема\n")
    видел = {}

    def зов(prompt, model, **k):
        видел["промпт"] = prompt
        return "## Неделя по дням\n\nПн — Свежая тема"

    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 7), зов=зов)

    assert путь == свежий
    assert "Свежая тема" in видел["промпт"]
    assert "Старая тема" not in видел["промпт"]


def test_свежайший_файл_без_банка_пропускается(мир):
    """Такт А упал или выдал файл без единой темы — такт Б не должен
    объявлять «не из чего собирать» поверх живой размеченной недели."""
    конфиг, заметки, блоки = мир
    с_банком = _неделя(заметки, "2026-08-24", "## Банк тем\n\n- [x] Взятая тема\n")
    _неделя(заметки, "2026-08-31", "## Банк тем\n\n(пусто)\n")

    путь = takt_b(конфиг, заметки, блоки, date(2026, 9, 7),
                  зов=lambda *a, **k: "## Неделя по дням\n\nПн — Взятая тема")

    assert путь == с_банком


def test_ни_одного_файла_недели_понятная_ошибка(мир):
    конфиг, заметки, блоки = мир
    with pytest.raises(FileNotFoundError, match="нет файла недели"):
        takt_b(конфиг, заметки, блоки, date(2026, 9, 7), зов=lambda *a, **k: "неважно")


def test_такт_а_говорит_про_неразобранный_прошлый_файл(мир, capsys):
    """Тихий вариант той же поломки: новый понедельник, такт А заводит новый
    файл, а неделя решений остаётся мёртвой. Молчать тут нельзя."""
    конфиг, заметки, блоки = мир
    _неделя(заметки, "2026-08-31",
            "## Банк тем\n\n- [ ] Неразобранная\n- [?] Отложенная\n- [x] Взятая\n")

    новый = takt_a(конфиг, заметки, блоки, date(2026, 9, 7),
                   зов=lambda *a, **k: "## Банк тем\n\n- [ ] Новая тема")

    вывод = capsys.readouterr().out
    assert новый.name == "неделя – 2026-09-07.md"
    assert "неделя – 2026-08-31.md" in вывод
    assert "Неразобранная" in вывод or "не отмечено" in вывод
    assert "Внимание" in вывод


def test_такт_а_молчит_когда_прошлая_неделя_разобрана(мир, capsys):
    конфиг, заметки, блоки = мир
    _неделя(заметки, "2026-08-31", "## Банк тем\n\n- [x] Взятая\n- [-] Отклонённая\n")

    takt_a(конфиг, заметки, блоки, date(2026, 9, 7),
           зов=lambda *a, **k: "## Банк тем\n\n- [ ] Новая тема")

    assert "Внимание" not in capsys.readouterr().out
