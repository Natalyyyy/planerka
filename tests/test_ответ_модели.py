"""Ответ модели вклеивался в файл недели без единой проверки.

Модель устойчиво добавляет вводную фразу перед заголовком («Конечно! Вот
план:»). Последствий три, и все три воспроизводятся:

1. преамбула прилипает к предыдущему разделу и копится по строке за прогон;
2. ответ прозой без заголовка вообще не даёт раздела — файл растёт, ошибки
   нет, человек об этом не узнаёт;
3. строка с галочкой внутри преамбулы на следующем прогоне разбирается как
   решение человека — в план приезжает тема, которую человек не отмечал.
"""
import pytest
from datetime import date

from planerka.runner.takt_b import takt_b

ПРЕАМБУЛА = "Конечно! Вот план недели:\n\n"


@pytest.fixture
def мир(tmp_path):
    блоки = tmp_path / "blocks"
    (блоки / "sources").mkdir(parents=True)
    (блоки / "platforms").mkdir()
    (блоки / "core.md").write_text("ЯДРО", encoding="utf-8")
    (блоки / "core-план.md").write_text("ЯДРО-ПЛАН", encoding="utf-8")
    заметки = tmp_path / "notes"
    (заметки / "недели").mkdir(parents=True)
    файл = заметки / "недели" / "неделя – 2026-08-31.md"
    файл.write_text("## Банк тем\n\n- [x] Взятая тема\n", encoding="utf-8")
    конфиг = {"источники": [], "площадки": [], "модель": "claude-sonnet-5"}
    return конфиг, заметки, блоки, файл


def test_ответ_прозой_без_заголовка_не_пишется(мир):
    конфиг, заметки, блоки, файл = мир
    исходное = файл.read_text(encoding="utf-8")

    with pytest.raises(RuntimeError, match="Неделя по дням"):
        takt_b(конфиг, заметки, блоки, date(2026, 9, 5),
               зов=lambda *a, **k: "Я подумал и решил рассказать про неделю словами.")

    assert файл.read_text(encoding="utf-8") == исходное


def test_преамбула_перед_заголовком_в_файл_не_попадает(мир):
    конфиг, заметки, блоки, файл = мир

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5),
           зов=lambda *a, **k: ПРЕАМБУЛА + "## Неделя по дням\n\nПн — Взятая тема")

    текст = файл.read_text(encoding="utf-8")
    assert "Конечно" not in текст
    assert "## Неделя по дням" in текст
    assert "Пн — Взятая тема" in текст


def test_преамбула_не_копится_за_три_прогона(мир):
    конфиг, заметки, блоки, файл = мир

    for метка in ("Первый", "Второй", "Третий"):
        takt_b(конфиг, заметки, блоки, date(2026, 9, 5),
               зов=lambda *a, м=метка, **k: ПРЕАМБУЛА + f"## Неделя по дням\n\n{м}")

    текст = файл.read_text(encoding="utf-8")
    assert текст.count("Конечно") == 0
    assert текст.count("## Неделя по дням") == 1
    assert "Третий" in текст and "Первый" not in текст


def test_галочка_из_преамбулы_не_становится_решением_человека(мир):
    конфиг, заметки, блоки, файл = мир
    придуманная = "- [x] Тему придумала модель, человек её не отмечал"

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5),
           зов=lambda *a, **k: f"Вот план:\n\n{придуманная}\n\n## Неделя по дням\n\nПн — Взятая тема")

    assert "придумала модель" not in файл.read_text(encoding="utf-8")

    видел = {}

    def зов(prompt, model, **k):
        видел["промпт"] = prompt
        return "## Неделя по дням\n\nПн — Взятая тема"

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=зов)
    assert "придумала модель" not in видел["промпт"]
