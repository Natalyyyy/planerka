"""Отклонённые темы: дозапись без дублей и тексты, которые не врут.

README обещал, что отклонённые темы «уезжают» в отдельный файл, скилл — что
такт Б их «переносит». Код ничего не переносит: раздел «Банк тем» он не
трогает, строки только копируются. Второй прогон такта Б по тому же файлу
дописывал каждую отклонённую тему заново, и `отклонённые.md` заполнялся
одной и той же строкой.
"""
from datetime import date
from pathlib import Path

import pytest

from planerka.runner.takt_b import takt_b

КОРЕНЬ = Path(__file__).resolve().parents[1]
README = (КОРЕНЬ / "README.md").read_text(encoding="utf-8")
СКИЛЛ = (КОРЕНЬ / "planerka" / "skills" / "planerka" / "SKILL.md").read_text(
    encoding="utf-8")


@pytest.fixture
def мир(tmp_path):
    блоки = tmp_path / "blocks"
    (блоки / "sources").mkdir(parents=True)
    (блоки / "platforms").mkdir()
    (блоки / "core.md").write_text("ЯДРО", encoding="utf-8")
    (блоки / "core-план.md").write_text("ЯДРО-ПЛАН", encoding="utf-8")
    заметки = tmp_path / "notes"
    (заметки / "недели").mkdir(parents=True)
    конфиг = {"источники": [], "площадки": [], "модель": "claude-sonnet-5"}
    return конфиг, заметки, блоки


def _неделя(заметки: Path, текст: str) -> Path:
    файл = заметки / "недели" / "неделя – 2026-08-31.md"
    файл.write_text(текст, encoding="utf-8")
    return файл


def _план(*a, **k):
    return "## Неделя по дням\n\nПн — Взятая тема"


БАНК = "## Банк тем\n\n- [x] Взятая тема\n- [-] Отклонённая тема\n"


def test_повторный_прогон_не_дублирует_отклонённую(мир):
    конфиг, заметки, блоки = мир
    _неделя(заметки, БАНК)

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=_план)
    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=_план)

    строки = (заметки / "отклонённые.md").read_text(encoding="utf-8").splitlines()
    сколько = [с for с in строки if "Отклонённая тема" in с]
    assert len(сколько) == 1, строки


def test_дубль_внутри_одного_прогона_не_даёт_двух_строк(мир):
    конфиг, заметки, блоки = мир
    _неделя(заметки,
            "## Банк тем\n\n- [x] Взятая тема\n"
            "- [-] Отклонённая тема\n- [-] Отклонённая тема\n")

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=_план)

    строки = (заметки / "отклонённые.md").read_text(encoding="utf-8").splitlines()
    сколько = [с for с in строки if "Отклонённая тема" in с]
    assert len(сколько) == 1, строки


def test_та_же_тема_в_другую_дату_записывается_снова(мир):
    """Дата в строке — часть смысла: тема, отклонённая ещё раз через неделю,
    это новый факт, а не дубль."""
    конфиг, заметки, блоки = мир
    _неделя(заметки, БАНК)

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=_план)
    takt_b(конфиг, заметки, блоки, date(2026, 9, 12), зов=_план)

    текст = (заметки / "отклонённые.md").read_text(encoding="utf-8")
    assert "2026-09-05" in текст
    assert "2026-09-12" in текст


def test_прежние_строки_отклонённых_остаются_на_месте(мир):
    конфиг, заметки, блоки = мир
    _неделя(заметки, БАНК)
    (заметки / "отклонённые.md").write_text(
        "# Отклонённые темы\n- Старая тема · 2026-08-01\n", encoding="utf-8")

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=_план)

    текст = (заметки / "отклонённые.md").read_text(encoding="utf-8")
    assert "Старая тема · 2026-08-01" in текст
    assert "Отклонённая тема · 2026-09-05" in текст


def test_банк_тем_остаётся_нетронутым(мир):
    """Основание для правки текстов: строка `[-]` из банка никуда не уходит."""
    конфиг, заметки, блоки = мир
    файл = _неделя(заметки, БАНК)

    takt_b(конфиг, заметки, блоки, date(2026, 9, 5), зов=_план)

    assert "- [-] Отклонённая тема" in файл.read_text(encoding="utf-8")


def test_тексты_не_обещают_перенос_отклонённых():
    assert "уезжают в отдельный файл" not in README
    assert "сюда уезжают темы" not in README
    assert "переносит в `отклонённые.md`" not in СКИЛЛ
    assert "копир" in README
    assert "копир" in СКИЛЛ
