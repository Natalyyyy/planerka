"""Сторож скилла расписания.

Скилл `planerka-schedule` — это инструкция, которую выполняет Клод на машине
человека, и весь риск у неё тот же, что был у README и у скилла настройки:
текст называет команду, флаг или переменную, которых в коде нет, — и человек
получает `unrecognized arguments` там, где ждал расписания. Проверяется то же
самое, что в `test_readme.py`, только на другом файле.

Отдельным пунктом — кириллица в переменных bash. Скрипт-прослойка из шага 3
писался с именами `ПИТОН`/`ЗАПАСНОЙ`, и это не работает вовсе: bash разрешает
в именах переменных только латиницу, цифры и подчёркивание, а строку
`ПИТОН="/usr/bin/python3"` разбирает как команду и отвечает
`No such file or directory`. Прогон черновика поймал это раньше человека;
сторож нужен, чтобы правка текста не вернула ошибку обратно.
"""
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
СКИЛЛ = КОРЕНЬ / "planerka" / "skills" / "planerka-schedule" / "SKILL.md"
ТЕКСТ = СКИЛЛ.read_text(encoding="utf-8")


def test_скилл_на_месте_и_называется_как_каталог():
    """Claude Code сопоставляет `name` во фронтматтере с именем каталога;
    разошлись — скилл не зовётся ни под одним из двух имён."""
    заголовок = re.search(r"^---\n(.*?)\n---", ТЕКСТ, re.DOTALL)
    assert заголовок, "у скилла нет фронтматтера"
    имя = re.search(r"^name:\s*(\S+)", заголовок.group(1), re.MULTILINE)
    assert имя and имя.group(1) == СКИЛЛ.parent.name, (
        f"во фронтматтере {имя and имя.group(1)!r}, каталог {СКИЛЛ.parent.name!r}")


# Прослойка зовётся `~/.planerka/прогон.sh темы` — подкоманда стоит внутри
# тех же обратных кавычек. Проза вокруг («прогон.cmd с аргументом») сюда не
# попадает намеренно: там следующее слово — не подкоманда.
ПОДКОМАНДА = re.compile(r"`[^`]*прогон\.(?:sh|cmd)\s+([а-яё-]+)[^`]*`")

# Два дела, которые расписание ставит. Переименуют команду в CLI — сторож
# поймает, даже если формулировки в скилле не тронут.
ПЛАНИРУЕМЫЕ = ("темы", "бот")


def test_подкоманды_из_скилла_существуют_в_cli():
    from planerka import run

    найдено = set(ПОДКОМАНДА.findall(ТЕКСТ))
    assert найдено, "скилл ни разу не зовёт прослойку с подкомандой"
    выдуманные = sorted(найдено - set(run.КОМАНДЫ))
    assert not выдуманные, (
        f"скилл зовёт подкоманду, которой нет в run.КОМАНДЫ: {выдуманные}; "
        f"есть только {sorted(run.КОМАНДЫ)}")


def test_оба_планируемых_дела_есть_в_cli_и_названы_в_скилле():
    from planerka import run

    пропало = [к for к in ПЛАНИРУЕМЫЕ if к not in run.КОМАНДЫ]
    assert not пропало, f"расписание ставит команду, которой в CLI больше нет: {пропало}"
    не_названы = [к for к in ПЛАНИРУЕМЫЕ if f"`{к}`" not in ТЕКСТ]
    assert not не_названы, f"скилл не называет, что именно ставит на расписание: {не_названы}"


def test_флаги_из_скилла_существуют_в_cli():
    # `--` с буквой сразу за ним: иначе разделитель фронтматтера `---`
    # прочитался бы как флаг.
    флаги = set(re.findall(r"--[A-Za-zА-Яа-яЁё][\w-]*", ТЕКСТ))
    системные = {  # флаги launchctl, systemctl, schtasks, journalctl — не наши
        "--user", "--now", "--no-pager", "--window-style",
    }
    наши = флаги - системные
    if not наши:
        return
    результат = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "planerka" / "run.py"), "--help"],
        capture_output=True, text=True, timeout=10,
    )
    assert результат.returncode == 0, результат.stderr
    выдуманные = sorted(ф for ф in наши if ф not in результат.stdout)
    assert not выдуманные, f"скилл зовёт флаг, которого нет в CLI: {выдуманные}"


def test_переменные_окружения_названы_те_что_читает_код():
    from planerka import run

    настоящие = {run._ПЕРЕМЕННАЯ_ТОКЕНА, run._ПЕРЕМЕННАЯ_CHAT_ID}
    упомянутые = set(re.findall(r"\bTELEGRAM_[A-Z_]+\b", ТЕКСТ))
    выдуманные = sorted(упомянутые - настоящие)
    assert not выдуманные, (
        f"скилл называет переменные бота, которых код не читает: {выдуманные}")


def test_скилл_не_обещает_что_токен_claude_работает_из_env_папки():
    """`run.py` разбирает `.env` папки заметок только ради двух переменных
    бота. Совет «положите CLAUDE_CODE_OAUTH_TOKEN в .env» дал бы человеку
    файл, который выглядит настроенным и ни на что не влияет: прогон под
    расписанием падал бы на незалогиненном `claude` каждую неделю."""
    предложения = re.split(r"(?<=[.:;])\s+", ТЕКСТ)
    ложные = [
        п for п in предложения
        if "CLAUDE_CODE_OAUTH_TOKEN" in п and ".env" in п
        and "бесполезно" not in п and "не доедет" not in п
    ]
    assert not ложные, f"скилл советует класть токен claude в .env: {ложные}"


# --- скрипт-прослойка

БЛОКИ_BASH = re.compile(r"```bash\n(.*?)```", re.DOTALL)
ПРИСВАИВАНИЕ = re.compile(r"^\s*([A-Za-zА-Яа-яЁё_][\wЀ-ӿ]*)=", re.MULTILINE)


def test_в_bash_нет_кириллических_имён_переменных():
    плохие = []
    for блок in БЛОКИ_BASH.findall(ТЕКСТ):
        for имя in ПРИСВАИВАНИЕ.findall(блок):
            if not re.fullmatch(r"[A-Za-z_]\w*", имя):
                плохие.append(имя)
    assert not плохие, (
        f"в bash-блоке скилла кириллические имена переменных: {плохие} — "
        "bash разберёт такую строку как команду и ответит No such file or directory")


def test_прослойка_ищет_свежий_run_py_а_не_вшивает_путь():
    """Плагины лежат в каталоге с хешем версии, и рядом остаются старые
    версии. Путь-константа после первого обновления плагина зовёт либо
    старую версию, либо исчезнувшую папку — и то и другое выглядит как
    «на этой неделе тем нет»."""
    блоки = БЛОКИ_BASH.findall(ТЕКСТ)
    ищущие = [б for б in блоки if "plugins/cache" in б and "run.py" in б]
    assert ищущие, "в скилле нет блока, который ищет run.py среди версий плагина"
    блок = ищущие[0]
    assert "-t" in блок, "поиск не сортирует по свежести — возьмётся произвольная версия"
    assert re.search(r"exit\s+1", блок), (
        "прослойка не падает с ненулевым кодом, когда run.py не нашёлся — "
        "планировщик посчитает такой прогон успешным")


def test_названы_три_ловушки_молчаливого_отказа():
    """Каждая из трёх даёт не ошибку, а тишину; выпадет любая — человек
    неделями считает, что планёрке нечего сказать."""
    низ = ТЕКСТ.lower()
    for метка, куски in {
        "пустой PATH под планировщиком": ("path", "абсолютн"),
        "доступ к файлам на маке (Full Disk Access)": ("full disk access", "desktop"),
        "claude не залогинен в фоне": ("claude_code_oauth_token", "залогин"),
        "systemd без linger умирает с сессией": ("enable-linger",),
        "пропущенный запуск systemd-таймера": ("persistent=true",),
    }.items():
        пропущено = [к for к in куски if к not in низ]
        assert not пропущено, f"скилл не разбирает ловушку «{метка}»: нет {пропущено}"


def test_шаг_проверки_требует_прогона_а_не_слов():
    """«Расписание поставлено» без прогона — ровно то утверждение, которое
    нельзя проверить: несработающее задание выглядит как сработающее."""
    низ = ТЕКСТ.lower()
    for команда in ("launchctl kickstart", "systemctl --user start", "schtasks /run"):
        assert команда in низ, f"в шаге проверки нет принудительного прогона: {команда}"
    assert "cat ~/.planerka/логи" in низ or "логи/темы.log" in низ, (
        "скилл не велит прочитать лог после принудительного прогона")


def test_названо_как_снять_расписание():
    низ = ТЕКСТ.lower()
    for команда in ("launchctl bootout", "systemctl --user disable", "schtasks /delete"):
        assert команда in низ, f"скилл не говорит, как снять расписание: {команда}"
